class NormativeReference:
    """Loads the Robson et al. (2025) normative dataset, applies transference
    corrections, computes Z-scores, assigns Traffic Light zones, and performs
    Bland-Altman-based change detection for serial comparisons.

    Reference
    ---------
    Robson, Baker et al. (2025). ISCEV standard full-field ERG reference
    limits from 407 healthy subjects. Documenta Ophthalmologica.
    DOI: 10.1007/s10633-025-10009-2

    Parameters
    ----------
    normative_csv : str
        Path to ISCEV_ffERG_reference_data.csv (Robson et al., 2025; N=407).
        Required columns: electrode, protocol, age_group, parameter,
                          mean, sd, n, lower_limit, upper_limit,
                          log_transformed (bool, optional).
    transference_config : dict, optional
        Output of validate_transference() — keyed by
        '{electrode}│{protocol}│{age_group}│{parameter}' with
        'correction_factor', 'slope', and 'intercept' sub-keys.
    """

    ZONE_GREEN = ZONE_GREEN
    ZONE_AMBER = ZONE_AMBER

    AGE_GROUPS = list(AGE_GROUPS)
    ELECTRODES = list(ELECTRODES)
    PROTOCOLS  = list(PROTOCOLS)

    def __init__(self,
                 normative_csv:       str,
                 transference_config: Optional[Dict] = None):
        self.df    = pd.read_csv(normative_csv)
        self.trans = transference_config or {}
        self._cache: Dict[str, NormStats] = {}

    # ── Internal helpers ───────────────────────────────────────────────────

    def _make_key(self, electrode: str, protocol: str,
                  age_group: str, parameter: str) -> str:
        return f'{electrode}│{protocol}│{age_group}│{parameter}'

    def _age_group(self, age: int) -> str:
        """Map integer age to Baker stratum key."""
        if   age <= 35: return 'le35'
        elif age <= 59: return '36to59'
        else:           return 'ge60'

    # ── Stratum statistics retrieval (cached) ─────────────────────────────

    def get_stats(self, electrode: str, protocol: str,
                  age_group: str, parameter: str) -> NormStats:
        """Retrieve (and cache) normative statistics for one stratum.

        Applies any registered transference corrections from self.trans.

        Raises KeyError if no normative data exists for the stratum.
        """
        key = self._make_key(electrode, protocol, age_group, parameter)
        if key in self._cache:
            return self._cache[key]

        mask = (
            (self.df['electrode'] == electrode) &
            (self.df['protocol']  == protocol)  &
            (self.df['age_group'] == age_group) &
            (self.df['parameter'] == parameter)
        )
        rows = self.df[mask]
        if len(rows) == 0:
            raise KeyError(
                f'No normative data for stratum: {key}')
        row = rows.iloc[0]

        tc  = self.trans.get(key, {})
        cf  = float(tc.get('correction_factor', 1.0))
        slp = tc.get('slope',     None)
        icp = tc.get('intercept', None)

        ns = NormStats(
            mu               = float(row['mean']) * cf,
            sigma            = float(row['sd'])   * cf,
            n                = int(row['n']),
            log_transformed  = bool(row.get('log_transformed', False)),
            correction_factor= cf,
            slope            = slp,
            intercept        = icp,
        )
        self._cache[key] = ns
        return ns

    # ── Z-score and Traffic Light ──────────────────────────────────────────

    def compute_z_score(self, x:         float,
                        age:       int,
                        electrode: str,
                        protocol:  str,
                        parameter: str) -> dict:
        """Compute Z-score and assign Traffic Light zone.

        Implements Equation 10.2 (Chapter 10):  Z = (x − μ_norm) / σ_norm

        For right-skewed parameters flagged log_transformed=True in the
        normative CSV, the Z-score is computed on log(x) using a delta-method
        approximation for the log-scale SD.

        Parameters
        ----------
        x : float
            Patient's measured (device-normalised) ERG parameter value.
        age : int  – patient age in years (maps to Baker age stratum)
        electrode, protocol, parameter : str – stratum identifiers

        Returns
        -------
        dict with keys: parameter, x, mu_norm, sigma_norm, z_score, abs_z,
                        traffic_light ('GREEN'/'AMBER'/'RED'), n_normative,
                        log_transformed, correction_applied
        """
        ag = self._age_group(age)
        ns = self.get_stats(electrode, protocol, ag, parameter)

        if ns.log_transformed:
            if x <= 0:
                raise ValueError(
                    f'Cannot log-transform non-positive value {x} '
                    f'for {parameter}')
            x_t  = np.log(x)
            mu_t = np.log(ns.mu)
            sd_t = ns.sigma / ns.mu   # delta-method approximation
            z    = (x_t - mu_t) / (sd_t + 1e-8)
        else:
            z = (x - ns.mu) / (ns.sigma + 1e-8)

        abs_z = abs(z)
        zone  = ('GREEN' if abs_z <= self.ZONE_GREEN
                 else 'AMBER' if abs_z <= self.ZONE_AMBER
                 else 'RED')

        return {
            'parameter'         : parameter,
            'x'                 : round(x,        3),
            'mu_norm'           : round(ns.mu,    3),
            'sigma_norm'        : round(ns.sigma, 3),
            'z_score'           : round(z,        3),
            'abs_z'             : round(abs_z,    3),
            'traffic_light'     : zone,
            'n_normative'       : ns.n,
            'log_transformed'   : ns.log_transformed,
            'correction_applied': ns.correction_factor != 1.0,
        }

    # ── Bland-Altman change detection ─────────────────────────────────────

    def compute_change(self, x_prior:   float,
                       x_current: float,
                       electrode: str,
                       protocol:  str,
                       parameter: str,
                       cor:       float,
                       mdc95:     float,
                       diagnosis: Optional[str] = None) -> dict:
        """Apply Bland-Altman change flagging rules (§15.5).

        Classifies the magnitude of change between two serial measurements
        against the Coefficient of Repeatability (CoR, Equation 15.2) and
        the Minimum Detectable Change at 95% CI (MDC₉₅, Equation 15.3).

        Change zones:
          |Δ| ≥ CoR            → SIGNIFICANT_PROGRESSION (Δ < 0)
                                  or SIGNIFICANT_IMPROVEMENT (Δ > 0)
          MDC₉₅ ≤ |Δ| < CoR   → BORDERLINE_CHANGE
          |Δ| < MDC₉₅          → NO_CHANGE

        An additional disease-specific flag is raised for retinitis pigmentosa
        / rod dystrophy when DA b-wave or a-wave amplitude declines ≥50% from
        the prior baseline, regardless of CoR threshold.

        Parameters
        ----------
        x_prior, x_current : float  – prior and current measurement values
        electrode, protocol, parameter : str  – stratum identifiers
        cor : float  – Coefficient of Repeatability for this stratum
        mdc95 : float  – Minimum Detectable Change (95% CI) for this stratum
        diagnosis : str or None  – disease label for disease-specific flags
                    (use 'retinitis_pigmentosa_rod_dystrophy' to activate the
                    RP ≥50% reduction flag)

        Returns
        -------
        dict with keys: parameter, x_prior, x_current, delta, pct_change,
                        cor_threshold, mdc95_threshold, change_zone, disease_flag
        """
        delta    = x_current - x_prior
        abs_d    = abs(delta)
        pct_chng = (delta / (abs(x_prior) + 1e-8)) * 100

        if abs_d >= cor:
            zone = ('SIGNIFICANT_PROGRESSION' if delta < 0
                    else 'SIGNIFICANT_IMPROVEMENT')
        elif abs_d >= mdc95:
            zone = 'BORDERLINE_CHANGE'
        else:
            zone = 'NO_CHANGE'

        # Disease-specific caveat: RP ≥50% amplitude reduction
        disease_flag = None
        if (diagnosis == 'retinitis_pigmentosa_rod_dystrophy'
                and parameter in ('b_wave_amplitude_uv', 'a_wave_amplitude_uv')
                and pct_chng <= -50):
            disease_flag = (
                'RP_50PCT_REDUCTION: DA b-wave amplitude has declined '
                '≥50% from prior baseline. Clinically significant in RP '
                'regardless of CoR threshold.')

        return {
            'parameter'      : parameter,
            'x_prior'        : round(x_prior,   3),
            'x_current'      : round(x_current, 3),
            'delta'          : round(delta,      3),
            'pct_change'     : round(pct_chng,   1),
            'cor_threshold'  : round(cor,        3),
            'mdc95_threshold': round(mdc95,      3),
            'change_zone'    : zone,
            'disease_flag'   : disease_flag,
        }


