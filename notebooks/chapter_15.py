@dataclass
class NormStats:
    """Normative statistics for one stratum (electrode × protocol × age_group × parameter).

    Attributes
    ----------
    mu, sigma : float
        Mean and SD of the normative distribution for this stratum.
    n : int
        Number of normative subjects in this stratum.
    log_transformed : bool
        True when Z-score should be computed on log(x) rather than x directly
        (applies to right-skewed amplitude distributions in some strata).
    correction_factor : float
        Transference correction multiplier (1.0 = no correction).
    slope, intercept : float or None
        Cross-electrode regression coefficients (None for same-electrode).
    """
    mu:               float
    sigma:            float
    n:                int
    log_transformed:  bool          = False
    correction_factor: float        = 1.0
    slope:            Optional[float] = None
    intercept:        Optional[float] = None


