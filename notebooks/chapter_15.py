# 1. Transference validation framework
# ══════════════════════════════════════════════════════════════════════════════

def validate_transference(local_df:       pd.DataFrame,
                           source_norms:  pd.DataFrame,
                           parameters:    list,
                           mode:          Literal['same_electrode',
                                                  'cross_electrode'],
                           min_pass_rate: float = TRANSFERENCE_PASS_RATE
                           ) -> dict:
    """Validate normative reference data transference to a target laboratory.

    Two transference modes are supported (§15.3):

    same_electrode (N ≥ 20):
        Verifies that ≥90% of local verification subjects fall within the
        source reference limits for each parameter. If pass rate < 90%,
        a laboratory-specific correction factor is computed as the ratio
        of the local mean to the source mean, and adjusted limits are returned.

    cross_electrode (N ≥ 40):
        Fits a linear regression from source-electrode values to
        target-electrode values on paired measurements from the same subjects.
        Transfers the source reference limits through the regression equation.
        Pass criteria: ≥90% of local subjects within transferred limits AND
        RMSE < 15% of source mean.

    Parameters
    ----------
    local_df : pd.DataFrame
        Verification subjects.
        same_electrode: columns include each parameter name directly.
        cross_electrode: columns named {parameter}_source and {parameter}_target.
    source_norms : pd.DataFrame
        Source normative dataset (Robson et al., 2025).
        Columns: parameter, lower_limit, upper_limit, mean, sd.
    parameters : list of str
        ERG parameter names to validate.
    mode : str
        'same_electrode' or 'cross_electrode'.
    min_pass_rate : float
        Minimum fraction of local subjects within limits (default 0.90).

    Returns
    -------
    dict with keys:
      overall_status – 'PASS' or 'PARTIAL'
      parameters     – per-parameter result dicts

    Raises
    ------
    ValueError if insufficient verification subjects.
    """
    min_n = (TRANSFERENCE_MIN_N_SAME if mode == 'same_electrode'
             else TRANSFERENCE_MIN_N_CROSS)
    if len(local_df) < min_n:
        raise ValueError(
            f'Insufficient verification subjects: {len(local_df)} provided, '
            f'{min_n} required for {mode} transference.')

    results = {}

    for param in parameters:
        src_row  = source_norms[source_norms['parameter'] == param].iloc[0]
        lo, hi   = src_row['lower_limit'], src_row['upper_limit']
        src_mean = src_row['mean']

        if mode == 'same_electrode':
            local_vals    = local_df[param].dropna().values
            within_limits = float(np.mean((local_vals >= lo) & (local_vals <= hi)))
            local_mean    = local_vals.mean()
            correction    = local_mean / src_mean if src_mean != 0 else 1.0
            status        = ('PASS' if within_limits >= min_pass_rate
                             else 'CORRECTION_REQUIRED')
            cf            = correction if status != 'PASS' else 1.0
            results[param] = {
                'mode'             : mode,
                'n_subjects'       : len(local_vals),
                'pass_rate'        : round(within_limits, 3),
                'status'           : status,
                'correction_factor': round(cf, 4),
                'corrected_lower'  : round(lo * cf, 3),
                'corrected_upper'  : round(hi * cf, 3),
            }

        else:  # cross_electrode
            src_vals = local_df[f'{param}_source'].dropna().values
            tgt_vals = local_df[f'{param}_target'].dropna().values
            slope_v, intercept_v, r, p_val, se = stats.linregress(
                src_vals, tgt_vals)
            pred     = slope_v * src_vals + intercept_v
            rmse     = float(np.sqrt(np.mean((tgt_vals - pred) ** 2)))
            rmse_pct = rmse / src_mean * 100 if src_mean != 0 else 999.0

            # Transfer source limits through regression
            trans_lo = slope_v * lo + intercept_v
            trans_hi = slope_v * hi + intercept_v
            within   = float(np.mean(
                (tgt_vals >= trans_lo) & (tgt_vals <= trans_hi)))
            status   = ('PASS'
                        if (within >= min_pass_rate and rmse_pct < TRANSFERENCE_RMSE_MAX_PCT)
                        else 'FAIL')
            results[param] = {
                'mode'             : mode,
                'n_subjects'       : len(src_vals),
                'slope'            : round(float(slope_v),    4),
                'intercept'        : round(float(intercept_v),3),
                'r_squared'        : round(float(r ** 2),     4),
                'rmse_pct'         : round(rmse_pct,          2),
                'pass_rate'        : round(within,            3),
                'status'           : status,
                'transferred_lower': round(trans_lo,          3),
                'transferred_upper': round(trans_hi,          3),
            }

    overall = ('PASS' if all(r['status'] == 'PASS' for r in results.values())
               else 'PARTIAL')
    return {'overall_status': overall, 'parameters': results}


