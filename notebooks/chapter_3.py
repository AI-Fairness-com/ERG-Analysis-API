def load_edf(edf_path: str) -> tuple:
    """Load a single ERG channel from an EDF file.

    Parameters
    ----------
    edf_path : str
        Path to the .edf file.  In Colab, upload first:
            from google.colab import files; files.upload()

    Returns
    -------
    times_ms : np.ndarray  – time axis in milliseconds
    erg_uV   : np.ndarray  – amplitude in microvolts
    fs       : float       – sampling rate in Hz

    Notes
    -----
    Unit check: raw.info['chs'][0]['unit'] should equal 107 (volts).
    Some devices export in mV (unit 201) – multiply by 1e3 instead of 1e6.
    """
    import mne  # imported here so the module loads without mne installed
    raw      = mne.io.read_raw_edf(edf_path, preload=True, verbose=False)
    erg_data = raw.get_data(picks='ERG')[0]   # volts
    erg_uV   = erg_data * 1e6                 # convert V → µV
    times_ms = raw.times * 1000               # convert s  → ms
    fs       = raw.info['sfreq']
    print(f'[EDF] Loaded {len(erg_uV)} samples at {fs:.0f} Hz')
    print(f'      Duration: {times_ms[-1]:.1f} ms  |  '
          f'Range: {erg_uV.min():.1f} to {erg_uV.max():.1f} µV')
    return times_ms, erg_uV, fs


