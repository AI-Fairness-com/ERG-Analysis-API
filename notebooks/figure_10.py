# 4. Normative reference and Traffic Light Z-score
# ══════════════════════════════════════════════════════════════════════════════

class NormativeReference:
    """Stores and queries the normative reference dataset.

    Computes Z-scores and assigns Traffic Light zones per Equation 10.2:

        Z = (x − μ_norm) / σ_norm

    where μ_norm and σ_norm are the normative mean and SD for the matching
    electrode type, protocol, and Baker age group from Robson et al. (2025)
    N=407 dataset.

    Traffic Light thresholds (locked):
        GREEN  |Z| ≤ 2.0
        AMBER  2.0 < |Z| ≤ 3.0
        RED    |Z| > 3.0

    Parameters
    ----------
    normative_df : pd.DataFrame
        Must contain columns: electrode, protocol, age_group, and one column
        per ERG parameter (e.g. b_amp_uv, b_implicit_ms, a_amp_uv, …).
    """

    ZONE_THRESHOLDS = ZONE_THRESHOLDS

    def __init__(self, normative_df: pd.DataFrame):
        self.norms = normative_df

    def get_norm_stats(self, electrode: str, protocol: str,
                       age_group: str, parameter: str) -> dict:
        """Return normative mean, SD, and n for a specific stratum.

        Raises ValueError if fewer than 5 normative observations exist for
        the requested stratum (insufficient for reliable statistics).
        """
        mask   = ((self.norms['electrode']  == electrode) &
                  (self.norms['protocol']   == protocol)  &
                  (self.norms['age_group']  == age_group))
        subset = self.norms.loc[mask, parameter].dropna()
        if len(subset) < 5:
            raise ValueError(
                f'Insufficient normative data for '
                f'{electrode}/{protocol}/{age_group}/{parameter}: '
                f'n={len(subset)}')
        return {'mu': float(subset.mean()),
                'sigma': float(subset.std()),
                'n': len(subset)}

    def compute_z_score(self, x: float, electrode: str, protocol: str,
                        age_group: str, parameter: str) -> dict:
        """Compute Z-score and assign Traffic Light zone (Equation 10.2).

        Parameters
        ----------
        x : float
            Patient's measured (and device-normalised) ERG parameter value.
        electrode, protocol, age_group, parameter : str
            Stratum identifiers for normative lookup.

        Returns
        -------
        dict with keys: parameter, x, mu_norm, sigma_norm, z_score, abs_z,
                        traffic_light ('GREEN'/'AMBER'/'RED'), n_normative.
        """
        stats     = self.get_norm_stats(electrode, protocol, age_group, parameter)
        mu, sigma = stats['mu'], stats['sigma']
        if sigma < 1e-8:
            raise ValueError(
                f'Near-zero SD in normative data for {parameter}.')

        z     = (x - mu) / sigma
        abs_z = abs(z)

        if abs_z <= self.ZONE_THRESHOLDS['green']:
            zone = 'GREEN'
        elif abs_z <= self.ZONE_THRESHOLDS['amber']:
            zone = 'AMBER'
        else:
            zone = 'RED'

        return {
            'parameter'    : parameter,
            'x'            : x,
            'mu_norm'      : round(mu,    2),
            'sigma_norm'   : round(sigma, 2),
            'z_score'      : round(z,     3),
            'abs_z'        : round(abs_z, 3),
            'traffic_light': zone,
            'n_normative'  : stats['n'],
        }


