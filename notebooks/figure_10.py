# 1. Inter-rater reliability gate
# ══════════════════════════════════════════════════════════════════════════════

def verify_inter_rater_reliability(labels_rater1: list,
                                    labels_rater2: list,
                                    min_kappa:     float = MIN_KAPPA) -> dict:
    """Compute Cohen's kappa between two raters; raise if below threshold.

    Must be called on a ≥15% random sample of the training dataset before
    training commences. Recordings where raters disagree must be adjudicated
    by a third specialist before being included in the training set.

    Parameters
    ----------
    labels_rater1, labels_rater2 : list
        Parallel lists of integer class labels from each rater for the same
        set of recordings.
    min_kappa : float
        Minimum acceptable Cohen's kappa (default 0.60 per §10.1.5).

    Returns
    -------
    dict with keys: kappa, p_observed, n_assessed.

    Raises
    ------
    ValueError
        If kappa < min_kappa. Training must not proceed until adjudication
        resolves disagreements and kappa rises above the threshold.
    """
    kappa   = cohen_kappa_score(labels_rater1, labels_rater2)
    agreed  = sum(a == b for a, b in zip(labels_rater1, labels_rater2))
    n_total = len(labels_rater1)
    p_obs   = agreed / n_total

    print('Inter-rater reliability')
    print(f'  Recordings assessed : {n_total}')
    print(f'  P_observed          : {p_obs:.3f}  ({agreed}/{n_total} agreed)')
    print(f"  Cohen's kappa       : {kappa:.3f}")
    print(f'  Minimum required    : {min_kappa:.2f}')

    if kappa < min_kappa:
        raise ValueError(
            f'Kappa {kappa:.3f} is below the minimum threshold {min_kappa:.2f}. '
            f'Adjudication by a third specialist is required before training.')

    print('  Status: PASS -- training may proceed.')
    return {'kappa': kappa, 'p_observed': p_obs, 'n_assessed': n_total}


