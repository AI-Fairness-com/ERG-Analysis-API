# 3. Device-relative normalisation
# ══════════════════════════════════════════════════════════════════════════════

def normalise_amplitude(a_measured:     float,
                         method:         int,
                         a_calibration:  Optional[float] = None,
                         norm_mean:      Optional[float] = None,
                         norm_std:       Optional[float] = None,
                         electrode_type: Optional[str]   = 'dtl') -> dict:
    """Apply device-relative normalisation to one ERG amplitude measurement.

    Three methods correspond to data availability (§10.3):

    Method 1 – Internal calibration signal (preferred)
        Divides the measured amplitude by a same-session calibration signal
        amplitude, removing device gain differences entirely.
        Requires: a_calibration > 0.

    Method 2 – Laboratory normative scaling
        Expresses the measured amplitude as a fraction of the laboratory's
        own normative mean for the same protocol and electrode type.
        Requires: norm_mean > 0.

    Method 3 – ISCEV relative criteria (fallback)
        Expresses the measured amplitude as a fraction of the ISCEV minimum
        acceptable b-wave for the electrode type (Esakowitz et al. 1993;
        Robson et al. 2025). Increased uncertainty; use only when Methods 1
        and 2 are unavailable.

    Parameters
    ----------
    a_measured : float
        Measured ERG amplitude in µV.
    method : int
        1, 2, or 3.
    a_calibration : float, optional
        Calibration signal amplitude in µV (Method 1 only).
    norm_mean : float, optional
        Laboratory normative mean in µV (Method 2).
    norm_std : float, optional
        Laboratory normative SD in µV (available for future use).
    electrode_type : str, optional
        Electrode type key for Method 3 ISCEV reference lookup.

    Returns
    -------
    dict with keys: normalised_value (float), method_used (int),
                    method_note (str).
    """
    if method == 1:
        if a_calibration is None or a_calibration <= 0:
            raise ValueError(
                'Method 1 requires a valid calibration signal amplitude.')
        norm_val = a_measured / a_calibration
        note     = 'Internal calibration signal (Method 1)'

    elif method == 2:
        if norm_mean is None or norm_mean <= 0:
            raise ValueError('Method 2 requires a valid normative mean.')
        norm_val = a_measured / norm_mean
        note     = 'Laboratory normative scaling (Method 2)'

    elif method == 3:
        electrode_key = (electrode_type.lower()
                         if electrode_type else 'dtl')
        iscev_ref = ISCEV_MIN_BWAVE.get(electrode_key, 60.0)
        norm_val  = a_measured / iscev_ref
        note      = (f'ISCEV relative criteria (Method 3 – fallback, '
                     f'increased uncertainty, electrode={electrode_key})')
    else:
        raise ValueError(f'Unknown normalisation method: {method}')

    return {
        'normalised_value': norm_val,
        'method_used':      method,
        'method_note':      note,
    }


