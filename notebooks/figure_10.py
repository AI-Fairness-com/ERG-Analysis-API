    for x in x_range:
        r = ref.compute_z_score(x, 'dtl', 'DA 3.0', '36–59y', 'b_amp_uv')
        z_vals.append(r['z_score'])
        zones.append(r['traffic_light'])

    zone_colours = {'GREEN': '#2E7D32', 'AMBER': '#F9A825', 'RED': '#C62828'}
    fig2, ax2 = plt.subplots(figsize=(10, 4))
    for zone, col in zone_colours.items():
        mask = [z == zone for z in zones]
        ax2.scatter(x_range[mask], np.array(z_vals)[mask],
                    color=col, s=15, label=zone, zorder=3)
    ax2.axhline( 2.0, color='#F9A825', lw=1.2, ls='--', alpha=0.8)
    ax2.axhline(-2.0, color='#F9A825', lw=1.2, ls='--', alpha=0.8)
    ax2.axhline( 3.0, color='#C62828', lw=1.2, ls='--', alpha=0.8)
    ax2.axhline(-3.0, color='#C62828', lw=1.2, ls='--', alpha=0.8)
    ax2.axhline(0,    color='gray',    lw=0.6, ls=':')
