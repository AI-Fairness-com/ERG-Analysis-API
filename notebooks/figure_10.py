# 2. Class imbalance handling
# ══════════════════════════════════════════════════════════════════════════════

def apply_smote(X_train:                    np.ndarray,
                y_train:                    np.ndarray,
                categorical_feature_indices: list = None,
                k_neighbours:               int  = 5,
                random_state:               int  = 42) -> tuple:
    """Apply SMOTE or SMOTE-NC to the training partition only.

    Uses standard SMOTE when all features are numerical (the common case for
    ERG feature vectors). Uses SMOTE-NC when categorical features are present
    (e.g. electrode type encoded as an integer column).

    Must be applied AFTER the train/val/test split and ONLY to the training
    partition. Applying SMOTE before splitting causes data leakage.

    Parameters
    ----------
    X_train : np.ndarray, shape (n_samples, n_features)
        Training feature matrix (numerical, NaNs already imputed).
    y_train : np.ndarray, shape (n_samples,)
        Integer class labels for training samples.
    categorical_feature_indices : list of int, optional
        Column indices that are categorical. If None, standard SMOTE is used.
    k_neighbours : int
        Number of nearest neighbours for synthetic sample generation.
    random_state : int
        Random seed for reproducibility.

    Returns
    -------
    tuple (X_resampled, y_resampled) with balanced class distribution.
    """
    if categorical_feature_indices:
        sampler = SMOTENC(categorical_features=categorical_feature_indices,
                          k_neighbors=k_neighbours,
                          random_state=random_state)
        print(f'Applying SMOTE-NC '
              f'({len(categorical_feature_indices)} categorical features)')
    else:
        sampler = SMOTE(k_neighbors=k_neighbours, random_state=random_state)
        print('Applying standard SMOTE (all numerical features)')

    counts_before = dict(zip(*np.unique(y_train, return_counts=True)))
    X_res, y_res  = sampler.fit_resample(X_train, y_train)
    counts_after  = dict(zip(*np.unique(y_res, return_counts=True)))

    print('Class distribution before SMOTE:', counts_before)
    print('Class distribution after  SMOTE:', counts_after)
    return X_res, y_res


def stratified_kfold_split(X:            np.ndarray,
                            y:            np.ndarray,
                            patient_ids:  np.ndarray,
                            n_splits:     int = N_FOLDS,
                            random_state: int = 42):
    """Patient-level stratified k-fold iterator.

    Ensures that all recordings from a single patient appear in exactly one
    fold, preventing optimistic performance estimates due to patient leakage
    across train/validation boundaries.

    Prerequisite: label consistency per patient must be enforced before
    calling this function (§10.1.4). All recordings from one patient must
    share the same class label.

    Parameters
    ----------
    X : np.ndarray, shape (n_recordings, n_features)
    y : np.ndarray, shape (n_recordings,) integer class labels
    patient_ids : np.ndarray, shape (n_recordings,) patient identifier array
    n_splits : int
        Number of folds (default 5).
    random_state : int

    Yields
    ------
    (fold_index, train_indices, val_indices) for each fold.
    """
    unique_patients = np.unique(patient_ids)
    patient_labels  = np.array([
        y[patient_ids == pid][0] for pid in unique_patients
    ])

    skf = StratifiedKFold(n_splits=n_splits, shuffle=True,
                          random_state=random_state)

    for fold, (train_pt_idx, val_pt_idx) in enumerate(
            skf.split(unique_patients, patient_labels)):

        train_patients = unique_patients[train_pt_idx]
        val_patients   = unique_patients[val_pt_idx]
        train_idx      = np.where(np.isin(patient_ids, train_patients))[0]
        val_idx        = np.where(np.isin(patient_ids, val_patients))[0]

        overlap = set(patient_ids[train_idx]) & set(patient_ids[val_idx])
        assert len(overlap) == 0, \
            f'Fold {fold}: patient leak detected: {overlap}'

        yield fold, train_idx, val_idx


