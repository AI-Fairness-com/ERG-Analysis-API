# 5. Patient-level data splitting
# ══════════════════════════════════════════════════════════════════════════════

def _verify_no_leakage(df_train: pd.DataFrame,
                        df_val:   pd.DataFrame,
                        df_test:  pd.DataFrame,
                        patient_col: str) -> None:
    """Assert zero patient overlap across the three partitions.

    Raises ValueError with the offending patient IDs if any leak is found.
    """
    train_pts = set(df_train[patient_col])
    val_pts   = set(df_val[patient_col])
    test_pts  = set(df_test[patient_col])
    tv = train_pts & val_pts
    tt = train_pts & test_pts
    vt = val_pts   & test_pts
    if tv or tt or vt:
        raise ValueError(
            f'Patient leakage detected!\n'
            f'  Train ∩ Val  : {tv}\n'
            f'  Train ∩ Test : {tt}\n'
            f'  Val   ∩ Test : {vt}')
    print('  Leakage check: PASS -- zero patient overlap across partitions.')


def patient_level_split(df:           pd.DataFrame,
                         label_col:   str   = 'label',
                         patient_col: str   = 'patient_id',
                         train_frac:  float = SPLIT_TRAIN,
                         val_frac:    float = SPLIT_VAL,
                         random_state: int  = 42) -> tuple:
    """Split a feature DataFrame into train/val/test with patient-level integrity.

    Splitting is performed at patient level: all recordings from a single
    patient end up in exactly one partition. Class proportions are preserved
    in each partition via stratification on the patient-level majority label.

    Parameters
    ----------
    df : pd.DataFrame
        Feature DataFrame with at least label_col and patient_col columns.
    label_col : str
        Column name for integer class labels.
    patient_col : str
        Column name for patient identifiers.
    train_frac, val_frac : float
        Fractions of the total dataset (test_frac = 1 − train − val = 0.10).
    random_state : int

    Returns
    -------
    tuple (df_train, df_val, df_test)
    """
    # Step 1 – Patient-level majority label
    patient_df = (
        df.groupby(patient_col)[label_col]
          .agg(lambda x: x.value_counts().index[0])
          .reset_index()
          .rename(columns={label_col: 'patient_label'})
    )

    # Step 2 – Train vs holdout split
    test_frac = 1.0 - train_frac
    patients_train, patients_holdout = train_test_split(
        patient_df,
        test_size    = test_frac,
        stratify     = patient_df['patient_label'],
        random_state = random_state,
    )

    # Step 3 – Holdout → val + test
    val_of_holdout = val_frac / test_frac
    patients_val, patients_test = train_test_split(
        patients_holdout,
        test_size    = 1.0 - val_of_holdout,
        stratify     = patients_holdout['patient_label'],
        random_state = random_state,
    )

    # Step 4 – Map back to recording level
    train_ids = set(patients_train[patient_col])
    val_ids   = set(patients_val[patient_col])
    test_ids  = set(patients_test[patient_col])

    df_train = df[df[patient_col].isin(train_ids)].copy()
    df_val   = df[df[patient_col].isin(val_ids)].copy()
    df_test  = df[df[patient_col].isin(test_ids)].copy()

    # Step 5 – Leakage check
    _verify_no_leakage(df_train, df_val, df_test, patient_col)

    print('Split complete:')
    print(f'  Train : {len(df_train):4d} recordings  ({len(train_ids)} patients)')
    print(f'  Val   : {len(df_val):4d} recordings  ({len(val_ids)} patients)')
    print(f'  Test  : {len(df_test):4d} recordings  ({len(test_ids)} patients)')
    return df_train, df_val, df_test


