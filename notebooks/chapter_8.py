# 2. Window-function empirical validation
# ══════════════════════════════════════════════════════════════════════════════

WINDOWS  = ['boxcar', 'triang', 'hann', 'hamming', 'blackman']
_NPERSEG  = STFT_CONFIG['nperseg']
_NOVERLAP = STFT_CONFIG['noverlap']
_FS       = STFT_CONFIG['fs']


def _spectro_features(signal_uv: np.ndarray, window: str) -> np.ndarray:
    """Compute a flattened 64×64 log-power spectrogram feature vector.

    Internal helper used by validate_windows(). Intentionally uses a smaller
    output size (64×64) than the production pipeline (224×224) to keep
    cross-validation runtime tractable.
    """
    _, _, Zxx   = stft(signal_uv, fs=_FS, window=window,
                       nperseg=_NPERSEG, noverlap=_NOVERLAP)
    S           = np.abs(Zxx) ** 2
    S_small     = resize(S, (64, 64), anti_aliasing=True, preserve_range=True)
    return np.log1p(S_small).ravel()


def validate_windows(X_sweeps: np.ndarray,
                     y_labels: np.ndarray) -> dict:
    """Empirically select the best STFT window via 5-fold stratified AUC-ROC.

    Evaluates all five candidate windows against the project dataset using a
    Random Forest classifier. The window with the highest mean macro AUC-ROC
    across folds is selected and should be locked into STFT_CONFIG['window'].

    Parameters
    ----------
    X_sweeps : np.ndarray
        Shape (n_recordings, n_samples). Filtered ERG sweeps.
    y_labels : np.ndarray
        Shape (n_recordings,). Integer class labels.

    Returns
    -------
    dict
        {window_name: mean_auc_roc} for all five candidate windows.

    Notes
    -----
    On the project dataset (Baker et al., 2025, N=407), 'hamming' achieved
    the highest macro AUC-ROC and is the locked default in STFT_CONFIG.
    Re-run this function if the training set changes materially.
    """
    lb      = LabelBinarizer().fit(y_labels)
    cv      = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
    results = {}

    for win in WINDOWS:
        print(f'Evaluating window: {win} ...', end=' ', flush=True)
        X_feat    = np.array([_spectro_features(x, win) for x in X_sweeps])
        fold_aucs = []
        for train_idx, test_idx in cv.split(X_feat, y_labels):
            clf = RandomForestClassifier(n_estimators=100, max_depth=8,
                                         random_state=42, n_jobs=-1)
            clf.fit(X_feat[train_idx], y_labels[train_idx])
            y_prob = clf.predict_proba(X_feat[test_idx])
            auc    = roc_auc_score(lb.transform(y_labels[test_idx]),
                                   y_prob, multi_class='ovr', average='macro')
            fold_aucs.append(auc)
        mean_auc       = float(np.mean(fold_aucs))
        results[win]   = mean_auc
        print(f'AUC = {mean_auc:.4f}')

    best = max(results, key=results.get)
    print(f'\nSelected window: {best}  (AUC = {results[best]:.4f})')
    print('Lock selection into STFT_CONFIG[\'window\'] before generating '
          'the training spectrogram batch.')
    return results


