def flatten_spectrogram_for_ml(S_norm:     np.ndarray,
                                small_size: int = 32) -> np.ndarray:
    """Downsample a normalised 224×224 spectrogram and flatten to 1-D.

    Reduces the 224×224 image (50,176 values) to a small_size×small_size
    vector (default 1,024 values) suitable as input to SVM or Random Forest
    classifiers (Chapter 12). For the ViT classifier (Chapter 13), use the
    full 224×224 array directly.

    Parameters
    ----------
    S_norm : np.ndarray
        Output of generate_erg_spectrogram(), shape (output_h, output_w).
    small_size : int
        Target side length in pixels (default 32 → 1,024 features).

    Returns
    -------
    np.ndarray
        1-D float32 feature vector of length small_size².
    """
    S_small = resize(S_norm, (small_size, small_size),
                     order=3, anti_aliasing=True, preserve_range=True)
    return S_small.ravel().astype(np.float32)


class SpectrogramPCAReducer:
    """PCA-based dimensionality reducer for spectrogram feature vectors.

    Fit on the training set; apply to validation, test, and deployment
    recordings. Combines StandardScaler (zero mean, unit variance) with PCA
    to produce a compact, decorrelated feature matrix for classical ML.

    Parameters
    ----------
    n_components : int
        Number of PCA components to retain (default 128).
    small_size : int
        Intermediate downsampling size before PCA (default 32 → 1,024 input
        features per spectrogram).

    Example
    -------
    reducer = SpectrogramPCAReducer(n_components=128)
    X_train = reducer.fit_transform(train_spectrograms)   # (N, 128)
    X_test  = reducer.transform(test_spectrograms)        # (M, 128)
    # Pass X_train / X_test to SVM or Random Forest in Chapter 12.
    """

    def __init__(self, n_components: int = 128, small_size: int = 32):
        self.pca        = PCA(n_components=n_components, random_state=42)
        self.scaler     = StandardScaler()
        self.small_size = small_size

    def fit(self, spectrograms: list) -> 'SpectrogramPCAReducer':
        """Fit scaler and PCA on a list of (output_h, output_w) arrays."""
        X         = np.array([flatten_spectrogram_for_ml(S, self.small_size)
                               for S in spectrograms])
        X_scaled  = self.scaler.fit_transform(X)
        self.pca.fit(X_scaled)
        explained = self.pca.explained_variance_ratio_.cumsum()
        print(f'PCA: {self.pca.n_components_} components explain '
              f'{100 * explained[-1]:.1f}% of variance')
        return self

    def transform(self, spectrograms: list) -> np.ndarray:
        """Transform a list of spectrograms to PCA feature matrix."""
        X = np.array([flatten_spectrogram_for_ml(S, self.small_size)
                      for S in spectrograms])
        return self.pca.transform(self.scaler.transform(X))

    def fit_transform(self, spectrograms: list) -> np.ndarray:
        """Fit and transform in one step."""
        return self.fit(spectrograms).transform(spectrograms)


