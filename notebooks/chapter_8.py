    t_ms  = np.linspace(0, epoch, N, endpoint=False)

    def make_sweep(a_amp=-120, b_amp=280, op_scale=1.0,
                   noise_sd=5, seed=0) -> np.ndarray:
        rng = np.random.default_rng(seed)
        sig = np.zeros(N)
        sig += a_amp * np.exp(-((t_ms - (pre + 20)) ** 2) / (2 * 8  ** 2))
        sig += b_amp * np.exp(-((t_ms - (pre + 60)) ** 2) / (2 * 18 ** 2))
        for op_t, op_a in [(28, 18), (35, 22), (45, 16), (58, 10)]:
            sig += (op_scale * op_a
                    * np.sin(2 * np.pi * 120 * (t_ms - (pre + op_t)) / 1000)
                    * np.exp(-((t_ms - (pre + op_t)) ** 2) / (2 * 5 ** 2)))
        return sig + rng.normal(0, noise_sd, N)

    normal   = make_sweep(seed=0)
