# ── Locked project-wide STFT configuration ────────────────────────────────────
# All parameters stored here for reproducibility across training and deployment.
# Any change to these values invalidates previously generated spectrograms and
# requires retraining the classifier from scratch.
STFT_CONFIG = {
    'window'   : 'hamming',    # empirically validated on project dataset (§8.2)
    'nperseg'  : 64,           # 32 ms window at 2000 Hz
    'noverlap' : 56,           # 87.5% overlap → 4 ms hop size
    'fs'       : 2000.0,       # Hz; must match recording metadata
    'fmin_hz'  : 0.0,          # include full ISCEV passband from DC
    'fmax_hz'  : 300.0,        # ISCEV upper cutoff
    'output_h' : 224,          # output image height (pixels)
    'output_w' : 224,          # output image width (pixels)
    'norm'     : 'db_zscore',  # normalisation strategy (see generate_erg_spectrogram)
}


# ══════════════════════════════════════════════════════════════════════════════
# 1. Core spectrogram generator
# ══════════════════════════════════════════════════════════════════════════════

def generate_erg_spectrogram(signal_uv:   np.ndarray,
                              config:      dict = None,
                              return_axes: bool = False):
    """Generate a normalised 2-D spectrogram array from a filtered ERG sweep.

    Steps
    -----
    1. Compute STFT with the configured window, nperseg, and noverlap.
    2. Convert complex STFT output to power in dB.
    3. Crop to the clinical frequency range [fmin_hz, fmax_hz].
    4. Normalise: z-score within the recording, clip to ±3σ, rescale to [0, 1].
    5. Bicubic resize to (output_h, output_w) for fixed-size model input.

    Parameters
    ----------
    signal_uv : np.ndarray
        1-D filtered ERG array in µV (output of Chapter 5 pipeline).
    config : dict, optional
        STFT configuration dict. Defaults to STFT_CONFIG above.
    return_axes : bool
        When True, also return (freqs_hz, times_s) for axis labelling.

    Returns
    -------
    S_norm : np.ndarray
        2-D float32 array, shape (output_h, output_w), values in [0, 1].
        Ready for single-channel image input. Add a channel dimension before
        passing to a ViT or CNN:  S_norm[np.newaxis, ...]  or
        torch.tensor(S_norm).unsqueeze(0).
    freqs, times : np.ndarray (only when return_axes=True)
        Frequency axis (Hz) and time axis (s) of the raw STFT output,
        before cropping and resizing.

    Notes
    -----
    Normalisation strategy 'db_zscore' is amplitude-invariant: a recording
    with a large b-wave and one with a small b-wave will have the same mean
    and std after normalisation. The spectral PATTERN is preserved; only
    absolute amplitude differences between recordings are removed. This is
    intentional — the ViT classifier learns from spectral shape, not raw
    amplitude, because amplitude is handled separately by the Traffic Light
    z-score framework (Chapter 15).
    """
    cfg = config or STFT_CONFIG

    # Step 1 – STFT
    freqs, times, Zxx = stft(signal_uv,
                              fs       = cfg['fs'],
                              window   = cfg['window'],
                              nperseg  = cfg['nperseg'],
                              noverlap = cfg['noverlap'])

    # Step 2 – Power in dB
    power = np.abs(Zxx) ** 2
    S_db  = 10 * np.log10(power + 1e-12)

    # Step 3 – Crop to clinical frequency range
    fmask = (freqs >= cfg['fmin_hz']) & (freqs <= cfg['fmax_hz'])
    S_db  = S_db[fmask, :]
    freqs_cropped = freqs[fmask]

    # Step 4 – Normalisation
    if cfg['norm'] == 'db_zscore':
        mu    = S_db.mean()
        sigma = S_db.std() + 1e-8
        S_n   = (S_db - mu) / sigma
        S_n   = np.clip(S_n, -3, 3)
        S_n   = (S_n + 3) / 6.0          # rescale to [0, 1]
    elif cfg['norm'] == 'minmax':
        lo, hi = S_db.min(), S_db.max()
        S_n    = (S_db - lo) / (hi - lo + 1e-8)
    else:
        raise ValueError(f'Unknown normalisation strategy: {cfg["norm"]}')

    # Step 5 – Bicubic resize to fixed output dimensions
    S_norm = resize(S_n,
                    (cfg['output_h'], cfg['output_w']),
                    order=3,
                    anti_aliasing=True,
                    preserve_range=True).astype(np.float32)

    if return_axes:
        return S_norm, freqs_cropped, times
    return S_norm


