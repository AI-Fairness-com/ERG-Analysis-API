# Integration – full SHAP report block
# ══════════════════════════════════════════════════════════════════════════════

def generate_shap_report_block(rf_pipeline,
                                vit_model,
                                feature_matrix: np.ndarray,
                                spectrogram:    torch.Tensor,
                                background:     torch.Tensor,
                                class_names:    list,
                                feature_names:  list,
                                feature_means:  np.ndarray,
                                output_dir:     str = OUTPUT_DIR) -> dict:
    """Generate all three SHAP levels for one patient record.

    Produces and saves three artefacts:
      Layer 2: plain-language narrative string
      Layer 3: waterfall PNG + spectrogram saliency overlay PNG + region dict
      Layer 4: raw SHAP values dict + top-5 features list

    Parameters
    ----------
    rf_pipeline : fitted sklearn Pipeline (Chapter 12 Random Forest)
    vit_model : trained ViT Small nn.Module (Chapter 13, calibrated)
    feature_matrix : np.ndarray, shape (1, n_features) – one patient record
    spectrogram : torch.Tensor, shape (1, 3, 224, 224)
    background : torch.Tensor, shape (n_bg, 3, 224, 224)
    class_names, feature_names : lists of str
    feature_means : np.ndarray, shape (n_features,) – training-set means
    output_dir : str

    Returns
    -------
    dict ready for embedding in the four-layer clinical report
    """
    os.makedirs(output_dir, exist_ok=True)

    # ── Level 1: TreeSHAP (Random Forest) ────────────────────────────────
    l1 = compute_feature_shap(
        rf_pipeline, feature_matrix, None, 0,
        class_names, feature_names, output_dir,
    )

    # ── Level 2: GradientSHAP (ViT Small) ────────────────────────────────
    pred_class_idx = class_names.index(l1['predicted_class'])
    saliency       = compute_spectrogram_shap(
        vit_model, spectrogram, background,
        pred_class_idx, l1['predicted_class'], output_dir,
    )
    region_summary = summarise_saliency_regions(saliency)

    # ── Level 3: Plain-language narrative ─────────────────────────────────
    preproc  = rf_pipeline[:-1]
    X_trans  = preproc.transform(feature_matrix)
    sv       = shap.TreeExplainer(rf_pipeline[-1]).shap_values(X_trans)[pred_class_idx][0]
    narrative = plain_language_shap(
        sv, X_trans[0], feature_names, feature_means, l1['predicted_class'])

    clean_cls = l1['predicted_class'].replace(' ', '_')
    return {
        'layer2_narrative'     : narrative,
        'layer3_waterfall_path': os.path.join(output_dir, 'waterfall_sample0.png'),
        'layer3_saliency_path' : os.path.join(output_dir,
                                              f'spectrogram_shap_{clean_cls}.png'),
        'layer3_region_summary': region_summary,
        'layer4_shap_values'   : dict(zip(feature_names, sv.tolist())),
        'layer4_top5_features' : l1['top_features'],
        'predicted_class'      : l1['predicted_class'],
        'predicted_proba'      : l1['predicted_proba'],
    }


