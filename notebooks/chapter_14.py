# Calibration – Platt scaling for ViT output
# ══════════════════════════════════════════════════════════════════════════════

def calibrate_vit_output(logits_val:      np.ndarray,
                          y_val:           np.ndarray,
                          logits_test:     np.ndarray,
                          y_test:          np.ndarray,
                          class_names:     list,
                          brier_threshold: float = BRIER_THRESHOLD) -> dict:
    """Apply per-class Platt scaling to ViT logits (§14.5).

    Fits a sigmoid A·x + B on the validation logits for each class
    independently (one-versus-rest). Re-normalises calibrated probabilities
    to sum to 1. Validates calibration quality with per-class Brier Score.

    A macro Brier Score above brier_threshold triggers CALIBRATION_WARNING
    in the Layer 4 audit record and must be resolved before deployment.

    Parameters
    ----------
    logits_val : np.ndarray, shape (n_val, n_classes) – raw ViT logits, val set
    y_val : np.ndarray, shape (n_val,) – true integer labels, val set
    logits_test : np.ndarray, shape (n_test, n_classes) – raw ViT logits, test set
    y_test : np.ndarray, shape (n_test,) – true integer labels, test set
    class_names : list of str
    brier_threshold : float (default 0.25)

    Returns
    -------
    dict with keys: calibrated_proba, platt_params, brier_per_class,
                    macro_brier, layer4_audit_flag
    """
    n_classes   = logits_val.shape[1]
    platt_params = {}
    calib_proba  = np.zeros_like(logits_test, dtype=float)

    for c in range(n_classes):
        y_bin_val = (y_val == c).astype(float)

        def neg_log_likelihood(params):
            A, B = params
            p    = sigmoid(A * logits_val[:, c] + B)
            p    = np.clip(p, 1e-7, 1 - 1e-7)
            return -np.mean(y_bin_val * np.log(p) + (1 - y_bin_val) * np.log(1 - p))

        res = minimize(neg_log_likelihood, x0=[1.0, 0.0], method='Nelder-Mead')
        A, B = res.x
        platt_params[class_names[c]] = {'A': round(A, 5), 'B': round(B, 5)}
        calib_proba[:, c] = sigmoid(A * logits_test[:, c] + B)

    # Re-normalise to sum to 1
    calib_proba = calib_proba / calib_proba.sum(axis=1, keepdims=True)

    # Brier Score validation
    y_test_bin      = label_binarize(y_test, classes=list(range(n_classes)))
    brier_per_class = [
        brier_score_loss(y_test_bin[:, c], calib_proba[:, c])
        for c in range(n_classes)
    ]
    macro_brier = float(np.mean(brier_per_class))
    audit_flag  = 'PASS'

    if macro_brier > brier_threshold:
        audit_flag = 'CALIBRATION_WARNING'
        warnings.warn(
            f'Macro Brier Score {macro_brier:.4f} exceeds threshold '
            f'{brier_threshold}. Layer 4 audit flag set to '
            f'CALIBRATION_WARNING. Recalibrate before production deployment.',
            UserWarning,
        )

    print(f'Platt scaling complete.  '
          f'Macro Brier Score: {macro_brier:.4f}  [{audit_flag}]')

    return {
        'calibrated_proba' : calib_proba,
        'platt_params'     : platt_params,
        'brier_per_class'  : dict(zip(class_names, brier_per_class)),
        'macro_brier'      : round(macro_brier, 4),
        'layer4_audit_flag': audit_flag,
    }


