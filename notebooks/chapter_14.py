# Level 3 – Plain-language SHAP narrative
# ══════════════════════════════════════════════════════════════════════════════

def plain_language_shap(shap_values:     np.ndarray,
                         feature_values:  np.ndarray,
                         feature_names:   List[str],
                         feature_means:   np.ndarray,
                         predicted_class: str,
                         min_pct:         float = 5.0) -> str:
    """Convert SHAP values to a clinician-readable narrative paragraph.

    Processes features in descending order of |SHAP| contribution. Features
    above min_pct (5%) are named individually using the SHAP_SENTENCE_MAP
    template. Features between 2% and 5% are grouped into a single sentence.
    Features below 2% are not mentioned.

    No SHAP numerical values or probability units appear in the output —
    only plain-language clinical descriptions are shown in the Layer 2 report.

    Parameters
    ----------
    shap_values : np.ndarray, shape (n_features,)
    feature_values : np.ndarray, shape (n_features,) – post-transform values
    feature_names : list of str
    feature_means : np.ndarray, shape (n_features,) – training-set mean per feature
    predicted_class : str
    min_pct : float – minimum % contribution to name a feature individually

    Returns
    -------
    str – plain-English narrative for the Layer 2 Clinical Summary
    """
    total = np.sum(np.abs(shap_values))
    contributions = [
        (feat, sv, fv, abs(sv) / (total + 1e-8) * 100)
        for feat, sv, fv in zip(feature_names, shap_values, feature_values)
    ]
    contributions.sort(key=lambda x: -x[3])

    sentences  = []
    rank_idx   = 0
    minor_feats = []

    for feat, sv, fv, pct in contributions:
        if pct < min_pct:
            if pct >= 2.0:
                minor_feats.append(feat)
            continue
        direction = 'high' if fv > feature_means[feature_names.index(feat)] else 'low'
        key = (feat, direction)
        if key in SHAP_SENTENCE_MAP:
            tmpl, _ = SHAP_SENTENCE_MAP[key]
            rank_word = RANK_WORDS[rank_idx] if rank_idx < len(RANK_WORDS) else 'a'
            sentences.append(tmpl.format(
                rank=rank_word, cls=predicted_class, pct=f'{pct:.0f}'))
            rank_idx += 1

    if minor_feats:
        joined = ', '.join(minor_feats[:3])
        sentences.append(f'Additional supporting contributors included: {joined}.')

    if not sentences:
        return (
            'The classification is supported by a combination of minor feature '
            'contributions, none of which individually exceeds 5% of the total '
            'attribution. Please refer to the SHAP waterfall chart in the '
            'Specialist Report for details.')

    return ' '.join(sentences)


