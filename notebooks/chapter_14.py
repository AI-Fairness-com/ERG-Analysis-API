# Level 2 – GradientSHAP for Vision Transformer
# ══════════════════════════════════════════════════════════════════════════════

def compute_spectrogram_shap(model,
                               spectrogram: torch.Tensor,
                               background:  torch.Tensor,
                               class_idx:   int,
                               class_name:  str,
                               output_dir:  str = OUTPUT_DIR) -> np.ndarray:
    """Compute pixel-level GradientSHAP saliency for a single spectrogram.

    GradientExplainer is the primary spectrogram-level explainability method
    (selected over attention rollout for superior spatial specificity on
    ERG spectrograms per §14.3.3). Produces a 224×224 saliency map overlaid
    on the original spectrogram.

    Validation criterion: highest-saliency regions must correspond to the
    clinically expected ERG components for the predicted disease class
    (OP burst at 75–300 Hz / 15–70 ms for DR; PhNR band for Glaucoma; etc.).

    Parameters
    ----------
    model : trained ViT Small nn.Module (Chapter 13), in eval mode
    spectrogram : torch.Tensor, shape (1, 3, 224, 224)
    background : torch.Tensor, shape (n_bg, 3, 224, 224)
        Reference background for SHAP baseline (typically 20 training images).
    class_idx : int – predicted class index (0–5 for Stage 2)
    class_name : str – predicted class label for figure title
    output_dir : str

    Returns
    -------
    np.ndarray, shape (224, 224) – normalised saliency map in [0, 1]
    """
    os.makedirs(output_dir, exist_ok=True)
    model.eval()

    explainer   = shap.GradientExplainer(model, background)
    shap_values = explainer.shap_values(spectrogram)
    # shap_values: list of (1, 3, 224, 224) per class
    sv_class = shap_values[class_idx][0]          # (3, 224, 224)
    saliency = np.mean(np.abs(sv_class), axis=0)  # (224, 224)
    saliency = (saliency - saliency.min()) / (saliency.max() - saliency.min() + 1e-8)

    # Original spectrogram for overlay
    spec_np = spectrogram[0].permute(1, 2, 0).cpu().numpy()  # (224, 224, 3)
    spec_np = (spec_np - spec_np.min()) / (spec_np.max() - spec_np.min() + 1e-8)

    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    axes[0].imshow(spec_np)
    axes[0].set_title('Original Spectrogram')
    axes[0].axis('off')

    axes[1].imshow(saliency, cmap='hot')
    axes[1].set_title(f'SHAP Saliency — {class_name}')
    axes[1].axis('off')

    heat    = cm.hot(saliency)[..., :3]
    overlay = np.clip((1 - 0.45) * spec_np + 0.45 * heat, 0, 1)
    axes[2].imshow(overlay)
    axes[2].set_title('Spectrogram + SHAP Overlay')
    axes[2].axis('off')

    plt.suptitle(f'Spectrogram-Level SHAP  │  {class_name}',
                 fontsize=13, fontweight='bold')
    plt.tight_layout()
    fname = f'spectrogram_shap_{class_name.replace(" ", "_")}.png'
    plt.savefig(os.path.join(output_dir, fname), dpi=220, bbox_inches='tight')
    plt.close()

    return saliency


def summarise_saliency_regions(saliency:          np.ndarray,
                                fs:               int   = FS_HZ,
                                nperseg:          int   = 64,
                                total_duration_ms: float = 250.0) -> dict:
    """Map a 224×224 saliency map to named ERG time-frequency regions.

    Divides the saliency map into five clinically defined regions and computes
    mean saliency per region, normalised to [0, 1]. Included in the Layer 3
    Specialist Report alongside the full saliency overlay.

    Parameters
    ----------
    saliency : np.ndarray, shape (H, W) – normalised saliency from compute_spectrogram_shap
    fs : int – sampling rate in Hz (sets frequency axis scale)
    nperseg : int – STFT window length (not used directly; retained for API consistency)
    total_duration_ms : float – total post-stimulus duration in ms (sets time axis scale)

    Returns
    -------
    dict {region_name: normalised_mean_saliency} all values in [0, 1]

    Regions:
      b_wave_band    0–30 Hz,   40–150 ms  (b-wave dominant band)
      phnr_band      0–15 Hz,   80–160 ms  (PhNR / slow photopic response)
      op_burst_band  75–300 Hz, 15–70 ms   (oscillatory potentials)
      high_freq_band 300–500 Hz, 0–100 ms  (high-frequency noise reference)
      prestim_noise  all freq,   0–20 ms   (pre-stimulus baseline)
    """
    H, W      = saliency.shape
    freq_max  = fs / 2           # 1000 Hz
    time_max  = total_duration_ms

    def px_rows(f_low, f_high):
        return int(f_low / freq_max * H), int(f_high / freq_max * H)

    def px_cols(t_low_ms, t_high_ms):
        return int(t_low_ms / time_max * W), int(t_high_ms / time_max * W)

    regions = {
        'b_wave_band'   : (px_rows(0,   30),  px_cols(40,  150)),
        'phnr_band'     : (px_rows(0,   15),  px_cols(80,  160)),
        'op_burst_band' : (px_rows(75,  300), px_cols(15,   70)),
        'high_freq_band': (px_rows(300, 500), px_cols(0,   100)),
        'prestim_noise' : (px_rows(0,   500), px_cols(0,    20)),
    }

    results = {}
    for name, ((r0, r1), (c0, c1)) in regions.items():
        patch = saliency[r0:r1, c0:c1]
        results[name] = float(patch.mean()) if patch.size > 0 else 0.0

    max_sal  = max(results.values()) or 1.0
    return {k: round(v / max_sal, 3) for k, v in results.items()}


