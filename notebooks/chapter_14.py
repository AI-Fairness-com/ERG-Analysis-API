# Level 1 – TreeSHAP for Random Forest
# ══════════════════════════════════════════════════════════════════════════════

def compute_feature_shap(pipeline,
                          X_test:        np.ndarray,
                          y_test,
                          sample_idx:    int,
                          class_names:   List[str],
                          feature_names: List[str],
                          output_dir:    str = OUTPUT_DIR) -> dict:
    """Compute TreeSHAP values for a single patient record.

    Uses shap.TreeExplainer for exact (not approximate) Shapley values
    computed in polynomial time for the Random Forest.

    The waterfall chart shows all 28 features ranked by |SHAP|, with signed
    bars coloured by feature value direction (above/below training mean).
    The sum of all bars exactly bridges the gap between the model's average
    output (base value) and its output for this specific recording.

    Parameters
    ----------
    pipeline : fitted sklearn Pipeline (Chapter 12 Random Forest)
    X_test : np.ndarray, shape (n_test, n_features) – raw (pre-transform) matrix
    y_test : array-like or None – true labels (optional, for display only)
    sample_idx : int – index into X_test for the patient to explain
    class_names : list of str – 7-class label list
    feature_names : list of str – 28-feature name list
    output_dir : str – directory for saved PNG artefacts

    Returns
    -------
    dict with keys: shap_values, base_value, predicted_class,
                    predicted_proba, feature_names, top_features (top 5 by |SHAP|)
    """
    os.makedirs(output_dir, exist_ok=True)

    preproc = pipeline[:-1]   # all steps except final classifier
    clf     = pipeline[-1]    # RandomForestClassifier
    X_trans = preproc.transform(X_test)

    explainer = shap.TreeExplainer(clf)
    shap_vals = explainer.shap_values(X_trans)
    # shap_vals shape: (n_classes, n_samples, n_features)
    base_vals = explainer.expected_value   # shape: (n_classes,)

    pred_class_idx = int(clf.predict(X_trans[[sample_idx]])[0])
    pred_class     = class_names[pred_class_idx]
    pred_proba     = float(clf.predict_proba(X_trans[[sample_idx]])[0, pred_class_idx])

    sv   = shap_vals[pred_class_idx][sample_idx]   # (n_features,)
    base = base_vals[pred_class_idx]

    # Waterfall chart
    shap_exp = shap.Explanation(
        values        = sv,
        base_values   = base,
        data          = X_trans[sample_idx],
        feature_names = feature_names,
    )
    plt.figure(figsize=(10, 8))
    shap.plots.waterfall(shap_exp, max_display=15, show=False)
    plt.title(f'SHAP Waterfall — {pred_class} (p={pred_proba:.2f})',
              fontsize=12, fontweight='bold')
    plt.tight_layout()
    save_path = os.path.join(output_dir, f'waterfall_sample{sample_idx}.png')
    plt.savefig(save_path, dpi=220, bbox_inches='tight')
    plt.close()

    return {
        'shap_values'    : sv,
        'base_value'     : base,
        'predicted_class': pred_class,
        'predicted_proba': round(pred_proba, 4),
        'feature_names'  : feature_names,
        'top_features'   : sorted(
            zip(feature_names, sv), key=lambda x: abs(x[1]), reverse=True)[:5],
    }


