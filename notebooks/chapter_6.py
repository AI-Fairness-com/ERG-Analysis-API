# 5. Wiener filter for residual noise reduction
# ══════════════════════════════════════════════════════════════════════════════

def wiener_denoise(sweep_uv:    np.ndarray,
                   pre_samples: int,
                   noise_floor: float = 1e-10) -> np.ndarray:
    """Apply a Wiener filter to a single ERG sweep.

    The noise PSD is estimated from the pre-stimulus baseline window and used
    to compute a frequency-dependent gain that suppresses noise while
    preserving signal energy.

    Parameters
    ----------
    sweep_uv : np.ndarray
        Single ERG sweep in µV.
    pre_samples : int
        Number of pre-stimulus samples used for noise PSD estimation.
    noise_floor : float
        Small regularisation constant preventing division by zero.

    Returns
    -------
    np.ndarray
        Denoised sweep in µV, same length as input.
    """
    N     = len(sweep_uv)
    S     = np.fft.rfft(sweep_uv, n=N)
    S_pwr = np.abs(S) ** 2

    pre   = sweep_uv[:pre_samples]
    N_spec = np.fft.rfft(pre, n=N)
    N_pwr  = np.abs(N_spec) ** 2

    # Wiener gain: W(f) = S_pwr / (S_pwr + N_pwr)
    # Approaches 1 where signal >> noise; approaches 0 where noise >> signal.
    W      = S_pwr / (S_pwr + N_pwr + noise_floor)
    S_filt = W * S
    return np.fft.irfft(S_filt, n=N)[:N]


