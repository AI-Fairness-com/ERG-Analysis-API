# 7. EMD + k-means artifact removal (single sweep)
# ══════════════════════════════════════════════════════════════════════════════

def emd_artifact_removal(sweep_uv:   np.ndarray,
                          fs_hz:     float,
                          pre_samples: int,
                          max_imf:   int = 8) -> dict:
    """Decompose a sweep with EMD and reconstruct without artifact IMFs.

    Intrinsic Mode Functions (IMFs) are classified as signal or artifact via
    k-means clustering on two features:
      1. Normalised pre-stimulus energy (artifact IMFs are active pre-stimulus)
      2. Cross-correlation with a synthetic b-wave template (signal IMFs
         correlate strongly with the ERG waveform shape)

    Requires the EMD-signal package:  pip install EMD-signal

    Parameters
    ----------
    sweep_uv : np.ndarray
        Single ERG sweep in µV.
    fs_hz : float
        Sampling rate in Hz.
    pre_samples : int
        Number of pre-stimulus samples.
    max_imf : int
        Maximum number of IMFs to extract.

    Returns
    -------
    dict with keys:
      reconstructed_uv  – np.ndarray, cleaned sweep in µV
      labels            – list of 'signal' or 'artifact' per IMF
      imfs              – np.ndarray of shape (n_imf, n_samples)
      n_artifact_imfs   – int
    """
    try:
        from PyEMD import EMD
    except ImportError:
        raise ImportError(
            'EMD-signal is required: pip install EMD-signal')

    emd   = EMD()
    imfs  = emd.emd(sweep_uv, max_imf=max_imf)
    n_imf = imfs.shape[0]
    N     = len(sweep_uv)

    # Feature 1: normalised pre-stimulus energy
    total_energy = np.mean(imfs ** 2, axis=1) + 1e-12
    pre_energy   = np.mean(imfs[:, :pre_samples] ** 2, axis=1)
    feat_base    = pre_energy / total_energy

    # Feature 2: cross-correlation with b-wave template
    t_vec  = np.linspace(0, N / fs_hz * 1000, N)
    pre_ms = pre_samples / fs_hz * 1000
    tmpl   = 2.5 * np.exp(-((t_vec - (pre_ms + 60)) ** 2) / (2 * 18 ** 2))
    tmpl  /= np.std(tmpl) + 1e-9
    feat_corr = np.array([np.abs(np.corrcoef(imfs[k], tmpl)[0, 1])
                          for k in range(n_imf)])

    # k-means on 2-D feature space (low pre-stimulus energy + high template corr = signal)
    X  = np.column_stack([feat_base, 1 - feat_corr])
    km = KMeans(n_clusters=2, random_state=42, n_init=10).fit(X)

    c0_score     = km.cluster_centers_[0].sum()
    c1_score     = km.cluster_centers_[1].sum()
    signal_cluster = 0 if c0_score <= c1_score else 1

    labels      = ['signal' if km.labels_[i] == signal_cluster else 'artifact'
                   for i in range(n_imf)]
    signal_imfs = imfs[np.array([l == 'signal' for l in labels])]
    reconstructed = signal_imfs.sum(axis=0) if len(signal_imfs) else np.zeros(N)

    return {
        'reconstructed_uv': reconstructed,
        'labels':           labels,
        'imfs':             imfs,
        'n_artifact_imfs':  int(sum(l == 'artifact' for l in labels)),
    }


