# 2. EMG artifact detection
# ══════════════════════════════════════════════════════════════════════════════

def detect_emg(sweep_uv:     np.ndarray,
               fs_hz:        float,
               pre_samples:  int,
               op_band_hz:   tuple = (75, 300),
               threshold_db: float = 6.0) -> dict:
    """Detect EMG contamination in the oscillatory potential band.

    Compares post-stimulus OP band RMS energy to the pre-stimulus baseline.
    A post/pre ratio exceeding threshold_db dB indicates EMG contamination.

    Parameters
    ----------
    sweep_uv : np.ndarray
        Single ERG sweep in µV.
    fs_hz : float
        Sampling rate in Hz.
    pre_samples : int
        Number of pre-stimulus samples (index boundary).
    op_band_hz : tuple
        (low, high) frequency bounds of the OP band in Hz.
    threshold_db : float
        Excess above pre-stimulus noise floor (dB) required to flag.

    Returns
    -------
    dict with keys: flagged, excess_db, reason
    """
    pre  = sweep_uv[:pre_samples]
    post = sweep_uv[pre_samples:]

    def op_rms(segment: np.ndarray) -> float:
        if len(segment) < 8:
            return 0.0
        f, psd = welch(segment, fs=fs_hz, nperseg=min(64, len(segment)))
        mask   = (f >= op_band_hz[0]) & (f <= op_band_hz[1])
        return float(np.sqrt(np.mean(psd[mask]))) if mask.any() else 0.0

    pre_rms  = op_rms(pre)
    post_rms = op_rms(post)

    if pre_rms < 1e-9:
        return {'flagged': False, 'excess_db': 0.0,
                'reason': 'pre-stimulus OP band energy too low to assess'}

    excess_db = 20 * np.log10(post_rms / pre_rms)
    flagged   = excess_db > threshold_db

    return {
        'flagged':   flagged,
        'excess_db': float(excess_db),
        'reason':    (f'OP band {excess_db:.1f} dB > pre-stimulus by '
                      f'threshold {threshold_db:.1f} dB') if flagged else 'none',
    }


# ══════════════════════════════════════════════════════════════════════════════
# 3. Electrode movement detection
# ══════════════════════════════════════════════════════════════════════════════

def detect_electrode_movement(sweep_uv:  np.ndarray,
                               fs_hz:    float,
                               step_uv:  float = 150.0,
                               window_ms: float = 10.0) -> dict:
    """Detect abrupt step changes caused by electrode movement or contact loss.

    Parameters
    ----------
    sweep_uv : np.ndarray
        Single ERG sweep in µV.
    fs_hz : float
        Sampling rate in Hz.
    step_uv : float
        Minimum change in windowed mean (µV) that constitutes a step event.
    window_ms : float
        Window length (ms) over which the local mean is computed.

    Returns
    -------
    dict with keys: flagged, max_step_uv, step_time_ms, reason
    """
    win_n = max(2, int(window_ms * fs_hz / 1000))
    if len(sweep_uv) < win_n * 2:
        return {'flagged': False, 'max_step_uv': 0.0,
                'step_time_ms': None, 'reason': 'none'}

    means    = np.mean(sliding_window_view(sweep_uv, win_n), axis=1)
    steps    = np.abs(np.diff(means))
    max_step = float(np.max(steps))
    flagged  = max_step > step_uv
    step_idx = int(np.argmax(steps)) + win_n // 2 if flagged else None
    step_t   = (step_idx / fs_hz * 1000) if step_idx is not None else None

    return {
        'flagged':      flagged,
        'max_step_uv':  max_step,
        'step_time_ms': step_t,
        'reason':       (f'Step {max_step:.0f} µV > threshold {step_uv:.0f} µV'
                         f' at {step_t:.1f} ms') if flagged else 'none',
    }


