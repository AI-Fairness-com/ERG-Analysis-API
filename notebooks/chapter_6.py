# ══════════════════════════════════════════════════════════════════════════════
# 1. Blink artifact detection
# ══════════════════════════════════════════════════════════════════════════════

def detect_blink(sweep_uv:          np.ndarray,
                 fs_hz:             float,
                 amp_ceiling_uv:    float = 500.0,
                 slope_uv_per_50ms: float = 100.0) -> dict:
    """Flag a single ERG sweep as containing a blink artifact.

    Two independent criteria are evaluated:
      1. Peak-to-peak amplitude exceeds amp_ceiling_uv.
      2. Maximum amplitude range within any 50 ms window exceeds
         slope_uv_per_50ms.

    Either criterion alone is sufficient to flag the sweep.

    Parameters
    ----------
    sweep_uv : np.ndarray
        Single ERG sweep in µV.
    fs_hz : float
        Sampling rate in Hz.
    amp_ceiling_uv : float
        Peak-to-peak amplitude ceiling in µV.
    slope_uv_per_50ms : float
        Maximum permitted amplitude range within a 50 ms window (µV).

    Returns
    -------
    dict with keys: flagged, reason, max_amp_ptp, max_slope_50ms
    """
    ptp      = float(np.ptp(sweep_uv))
    amp_flag = ptp > amp_ceiling_uv

    win = max(1, int(0.050 * fs_hz))    # 50 ms in samples
    if len(sweep_uv) >= win:
        wins      = sliding_window_view(sweep_uv, win)
        slopes    = np.max(wins, axis=1) - np.min(wins, axis=1)
        max_slope = float(np.max(slopes))
    else:
        max_slope = ptp

    slope_flag = max_slope > slope_uv_per_50ms
    flagged    = amp_flag or slope_flag

    reason = []
    if amp_flag:
        reason.append(
            f'peak-to-peak {ptp:.0f} µV > ceiling {amp_ceiling_uv:.0f} µV')
    if slope_flag:
        reason.append(
            f'slope {max_slope:.0f} µV/50ms > threshold {slope_uv_per_50ms:.0f}')

    return {
        'flagged':        flagged,
        'reason':         '; '.join(reason) if reason else 'none',
        'max_amp_ptp':    ptp,
        'max_slope_50ms': max_slope,
    }


