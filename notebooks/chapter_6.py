# 4. Combined sweep-level screener
# ══════════════════════════════════════════════════════════════════════════════

def screen_sweep(sweep_uv:   np.ndarray,
                 fs_hz:      float,
                 pre_samples: int,
                 electrode:  str = 'dtl') -> dict:
    """Apply all three artifact detectors to a single ERG sweep.

    Parameters
    ----------
    sweep_uv : np.ndarray
        Single ERG sweep in µV.
    fs_hz : float
        Sampling rate in Hz.
    pre_samples : int
        Number of pre-stimulus samples.
    electrode : str
        Electrode type key for amplitude ceiling lookup.
        One of: 'contact_lens', 'gold_foil', 'dtl', 'dtl_fiber', 'skin'.

    Returns
    -------
    dict with keys:
      reject       – bool, True if ANY detector flagged this sweep
      flags        – list of triggered detector names
      blink        – blink detector result dict
      emg          – EMG detector result dict
      electrode_mv – electrode movement detector result dict
    """
    amp_ceilings = {
        'contact_lens': 500, 'gold_foil': 450,
        'dtl': 350, 'dtl_fiber': 350, 'skin': 250,
    }
    ceil = amp_ceilings.get(electrode.lower().replace(' ', '_'), 400)

    b = detect_blink(sweep_uv, fs_hz, amp_ceiling_uv=ceil)
    e = detect_emg(sweep_uv, fs_hz, pre_samples)
    m = detect_electrode_movement(sweep_uv, fs_hz)

    triggered = []
    if b['flagged']: triggered.append('BLINK')
    if e['flagged']: triggered.append('EMG')
    if m['flagged']: triggered.append('ELECTRODE_MOVEMENT')

    return {
        'reject':       bool(triggered),
        'flags':        triggered,
        'blink':        b,
        'emg':          e,
        'electrode_mv': m,
    }


def screen_all_sweeps(sweeps:      np.ndarray,
                      fs_hz:       float,
                      pre_samples: int,
                      electrode:   str = 'dtl') -> dict:
    """Screen a 2-D array of sweeps and compute the rejection-rate quality flag.

    Parameters
    ----------
    sweeps : np.ndarray
        Shape (n_sweeps, n_samples).
    fs_hz : float
        Sampling rate in Hz.
    pre_samples : int
        Number of pre-stimulus samples per sweep.
    electrode : str
        Electrode type key (see screen_sweep).

    Returns
    -------
    dict with keys:
      accept_mask    – bool array, True = sweep passes screening
      rejection_rate – float, fraction of sweeps rejected
      quality_flag   – str, PASS / WARNING / FAIL (Chapter 2 §2.5)
      sweep_results  – list of per-sweep screen_sweep() dicts
    """
    results  = [screen_sweep(sweeps[i], fs_hz, pre_samples, electrode)
                for i in range(len(sweeps))]
    accept   = np.array([not r['reject'] for r in results])
    rej_rate = float(1 - accept.mean())

    if   rej_rate <= 0.20: q_flag = 'PASS'
    elif rej_rate <= 0.40: q_flag = 'WARNING'
    else:                  q_flag = 'FAIL'

    return {
        'accept_mask':    accept,
        'rejection_rate': rej_rate,
        'quality_flag':   q_flag,
        'sweep_results':  results,
    }


