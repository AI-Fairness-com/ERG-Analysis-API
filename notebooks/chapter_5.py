# 5. Streaming mode: causal SOS filter with rolling buffer
# ══════════════════════════════════════════════════════════════════════════════

class StreamingERGFilter:
    """Real-time (causal) ERG filter for streaming / portable device use.

    Maintains filter state across successive input chunks so the filter
    behaves as if processing one continuous signal rather than independent
    segments.

    Use for real-time applications only.  All offline analysis in this
    book uses apply_erg_filter_pipeline() (zero-phase sosfiltfilt).

    Parameters
    ----------
    fs_hz : float
        Sampling rate in Hz.
    highpass_hz, lowpass_hz : float
        Butterworth cutoff frequencies in Hz.
    order : int
        Butterworth filter order (default 4).

    Notes
    -----
    Implicit times in streaming output are systematically 5–15 ms longer
    than in batch-mode output due to causal phase delay.  The recording
    metadata must flag the filtering mode so that the classifier uses the
    correct normative thresholds (see §5.4.4).
    """

    def __init__(self,
                 fs_hz:       float,
                 highpass_hz: float = ISCEV_HIGHPASS_HZ,
                 lowpass_hz:  float = ISCEV_LOWPASS_HZ,
                 order:       int   = FILTER_ORDER):
        self.sos = design_butterworth_bandpass(highpass_hz, lowpass_hz,
                                               fs_hz, order)
        self.zi  = sosfilt_zi(self.sos) * 0.0    # zero initial state

    def process_chunk(self, chunk: np.ndarray) -> np.ndarray:
        """Filter one chunk of incoming samples and update the filter state.

        Parameters
        ----------
        chunk : np.ndarray
            1-D array of new samples in µV.

        Returns
        -------
        np.ndarray
            Filtered chunk (same length as input).
        """
        filtered, self.zi = sosfilt(self.sos, chunk, zi=self.zi)
        return filtered

    def reset(self):
        """Reset filter state between ERG epochs (between flash presentations)."""
        self.zi *= 0.0


