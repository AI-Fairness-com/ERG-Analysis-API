# ── Locked pipeline constants (ISCEV 2022) ─────────────────────────────────────
ISCEV_HIGHPASS_HZ = 0.3    # Lower cutoff – preserves PhNR
ISCEV_LOWPASS_HZ  = 300.0  # Upper cutoff – preserves OPs
FILTER_ORDER      = 4      # 4th-order Butterworth: flat passband, 24 dB/oct roll-off
FS_PIPELINE_HZ    = 2000   # Locked pipeline sampling rate (Chapter 3)


# ══════════════════════════════════════════════════════════════════════════════
# 1. Butterworth bandpass filter
# ══════════════════════════════════════════════════════════════════════════════

def design_butterworth_bandpass(highpass_hz: float,
                                lowpass_hz:  float,
                                fs_hz:       float,
                                order:       int = FILTER_ORDER) -> np.ndarray:
    """Design a Butterworth bandpass filter.

    Parameters
    ----------
    highpass_hz : float
        High-pass cutoff in Hz (ISCEV: 0.3 Hz).
    lowpass_hz : float
        Low-pass cutoff in Hz (ISCEV: 300.0 Hz).
    fs_hz : float
        Sampling rate in Hz.
    order : int
        Filter order (default 4, the ISCEV clinical standard).

    Returns
    -------
    np.ndarray
        SOS (second-order sections) array for use with sosfiltfilt / sosfilt.

    Notes
    -----
    SOS format is used instead of 'ba' (transfer function) because high-order
    filters are numerically unstable in 'ba' form – see §5.3.1 sidebar.
    """
    nyquist = fs_hz / 2.0
    low  = highpass_hz / nyquist
    high = lowpass_hz  / nyquist
    if high >= 1.0:
        raise ValueError(
            f'Low-pass cutoff {lowpass_hz} Hz exceeds Nyquist ({nyquist} Hz) '
            f'for sampling rate {fs_hz} Hz. '
            f'Reduce the cutoff or increase the sampling rate.')
    return butter(order, [low, high], btype='bandpass', output='sos')


def apply_bandpass(signal_uv:   np.ndarray,
                   fs_hz:       float,
                   highpass_hz: float = ISCEV_HIGHPASS_HZ,
                   lowpass_hz:  float = ISCEV_LOWPASS_HZ,
                   order:       int   = FILTER_ORDER) -> np.ndarray:
    """Apply the ISCEV Butterworth bandpass filter to a raw ERG signal.

    Uses sosfiltfilt (zero-phase, forward-backward) to preserve implicit times.

    Parameters
    ----------
    signal_uv : np.ndarray
        Raw ERG amplitude in µV.
    fs_hz : float
        Sampling rate in Hz.
    highpass_hz, lowpass_hz : float
        Filter cutoff frequencies in Hz.
    order : int
        Butterworth filter order.

    Returns
    -------
    np.ndarray
        Filtered signal in µV, same length as input.
    """
    sos = design_butterworth_bandpass(highpass_hz, lowpass_hz, fs_hz, order)
    return sosfiltfilt(sos, signal_uv)


def plot_filter_response(sos:   np.ndarray,
                         fs_hz: float,
                         title: str = 'Butterworth Bandpass – Frequency Response') -> plt.Figure:
    """Plot the magnitude frequency response of an SOS filter.

    Use this to verify that the filter rolls off where expected before
    applying it to any recording.

    Parameters
    ----------
    sos : np.ndarray
        SOS filter coefficients (output of design_butterworth_bandpass).
    fs_hz : float
        Sampling rate in Hz (sets the x-axis Nyquist limit).
    title : str
        Figure title.

    Returns
    -------
    plt.Figure
    """
    w, h = sosfreqz(sos, worN=4096, fs=fs_hz)
    fig, ax = plt.subplots(figsize=(10, 4))
    ax.plot(w, 20 * np.log10(np.abs(h) + 1e-12), color='#2E75B6', lw=1.8)
    ax.axvline(ISCEV_HIGHPASS_HZ, color='red',   ls='--', lw=1.0,
               label=f'High-pass: {ISCEV_HIGHPASS_HZ} Hz')
    ax.axvline(ISCEV_LOWPASS_HZ,  color='green', ls='--', lw=1.0,
               label=f'Low-pass: {ISCEV_LOWPASS_HZ} Hz')
    ax.axhline(-3, color='gray', ls=':', lw=0.8,
               label='−3 dB (half-power) cutoff')
    ax.set_xlim(0.1, fs_hz / 2)
    ax.set_ylim(-80, 5)
    ax.set_xscale('log')
    ax.set_xlabel('Frequency (Hz)', fontsize=11)
    ax.set_ylabel('Magnitude (dB)', fontsize=11)
    ax.set_title(title, fontsize=12)
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    return fig


