# 2. Notch filter  ⚠️  OFF by default – ISCEV 2022 advises against routine use
# ══════════════════════════════════════════════════════════════════════════════

def detect_mains_interference(signal_uv: np.ndarray,
                               fs_hz:     float,
                               notch_hz:  float = 50.0,
                               threshold_db: float = 6.0) -> bool:
    """Return True if a spectral peak at notch_hz exceeds the noise floor.

    Parameters
    ----------
    signal_uv : np.ndarray
        ERG amplitude in µV.
    fs_hz : float
        Sampling rate in Hz.
    notch_hz : float
        Power-line frequency to test (50.0 Hz UK/Europe; 60.0 Hz N. America).
    threshold_db : float
        Minimum excess above shoulder noise (dB) to flag as interference.

    Returns
    -------
    bool
    """
    freqs, psd = welch(signal_uv, fs=fs_hz,
                       nperseg=min(1024, len(signal_uv)))
    idx       = int(np.argmin(np.abs(freqs - notch_hz)))
    p_notch   = 10 * np.log10(psd[idx] + 1e-30)
    shoulder  = np.concatenate([psd[max(0, idx - 5): idx],
                                 psd[idx + 1: idx + 6]])
    p_shoulder = 10 * np.log10(np.mean(shoulder) + 1e-30)
    return (p_notch - p_shoulder) > threshold_db


def apply_notch(signal_uv:      np.ndarray,
                fs_hz:          float,
                notch_hz:       float = 50.0,
                quality_factor: float = 50.0) -> np.ndarray:
    """Remove power-line interference at notch_hz (zero-phase IIR notch).

    ⚠️  ISCEV 2022 advises against notch filters due to waveform distortion.
    Apply only with explicit clinical justification and set the notch_applied
    flag in the recording metadata.

    Parameters
    ----------
    signal_uv : np.ndarray
        ERG amplitude in µV.
    fs_hz : float
        Sampling rate in Hz.
    notch_hz : float
        Notch centre frequency (50.0 Hz UK/Europe; 60.0 Hz N. America).
    quality_factor : float
        Q factor. Q = 50 gives a −3 dB bandwidth of ~1 Hz at 50 Hz.
        Increase to 50 for a very clean cut; reduce to 20 if residual hum
        remains after filtering.

    Returns
    -------
    np.ndarray
        Filtered signal in µV.
    """
    b, a = iirnotch(notch_hz, quality_factor, fs=fs_hz)
    sos  = tf2sos(b, a)        # Convert ba → SOS for numerical stability
    return sosfiltfilt(sos, signal_uv)


# ══════════════════════════════════════════════════════════════════════════════
# 3. Median filter for isolated spike suppression
# ══════════════════════════════════════════════════════════════════════════════

def apply_median_filter(signal_uv:      np.ndarray,
                        kernel_samples: int = 5) -> np.ndarray:
    """Remove high-amplitude short-duration spikes using a median filter.

    Applied as Stage 1 (before bandpass/notch) to prevent spike-induced
    ringing in the frequency-domain filters.

    Parameters
    ----------
    signal_uv : np.ndarray
        ERG amplitude in µV.
    kernel_samples : int
        Window length in samples (must be odd).
        Default 5 samples = 2.5 ms at 2000 Hz or 5 ms at 1000 Hz.
        Spikes shorter than the kernel are replaced by their neighbours'
        median; physiological features (a-wave ≥15 ms) pass unchanged.

    Returns
    -------
    np.ndarray
        Spike-cleaned signal in µV.
    """
    if kernel_samples % 2 == 0:
        kernel_samples += 1    # scipy.signal.medfilt requires an odd kernel
    return medfilt(signal_uv, kernel_size=kernel_samples)


