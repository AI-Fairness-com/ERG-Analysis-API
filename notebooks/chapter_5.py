# 4. Complete three-stage pipeline
# ══════════════════════════════════════════════════════════════════════════════

def apply_erg_filter_pipeline(recording:     dict,
                               apply_median:  bool  = True,
                               apply_notch_f: bool  = False,
                               notch_hz:      float = 50.0,
                               highpass_hz:   float = ISCEV_HIGHPASS_HZ,
                               lowpass_hz:    float = ISCEV_LOWPASS_HZ,
                               filter_order:  int   = FILTER_ORDER,
                               confirm_notch: bool  = True) -> dict:
    """Apply the full ISCEV 2022-compliant ERG filter pipeline.

    Pipeline order
    --------------
    1. Median filter   – spike removal (always recommended)
    2. Notch filter    – power-line removal (OFF by default per ISCEV 2022)
    3. Butterworth bandpass – main ISCEV 0.3–300 Hz passband

    Parameters
    ----------
    recording : dict
        Standardised ERG dict with keys:
          amplitude_uv, fs_hz, hardware_lowpass_hz (optional)
    apply_median : bool
        Apply median spike filter (Stage 1). Recommended: True.
    apply_notch_f : bool
        Apply notch filter (Stage 2). ISCEV 2022 default: False.
    notch_hz : float
        Notch frequency (50.0 Hz UK/Europe; 60.0 Hz N. America).
    highpass_hz, lowpass_hz : float
        Butterworth cutoff frequencies in Hz.
    filter_order : int
        Butterworth order (clinical standard: 4).
    confirm_notch : bool
        When True, prompts for interactive confirmation before applying
        the notch filter. Set False for automated batch processing.

    Returns
    -------
    dict
        Copy of the input recording dict with additional keys:
          filtered_uv      – fully filtered signal array (µV)
          filter_log       – list of strings documenting every step applied
          hw_cutoff_ok     – bool (True if hardware allows full ISCEV band)
          iscev_compliance – dict of compliance flags
          notch_applied    – bool (True if notch was actually applied)
          mains_detected   – bool (True if 50/60 Hz peak was detected)
    """
    sig    = recording['amplitude_uv'].copy()
    fs     = recording['fs_hz']
    hw_lp  = recording.get('hardware_lowpass_hz', 300.0)
    log    = []

    # ── ISCEV: sampling rate check (≥1000 Hz required) ────────────────────
    if fs < 1000.0:
        log.append(f'WARNING: Sampling rate {fs} Hz is below ISCEV minimum 1000 Hz')
        log.append(f'         Implicit time measurements may be unreliable')

    # ── Respect hardware bandwidth ─────────────────────────────────────────
    hw_cutoff_ok = hw_lp >= lowpass_hz
    effective_lp = min(lowpass_hz, hw_lp * 0.95) if hw_lp < lowpass_hz else lowpass_hz
    if not hw_cutoff_ok:
        log.append(f'WARNING: Hardware cutoff {hw_lp} Hz < requested {lowpass_hz} Hz.')
        log.append(f'         Software low-pass set to {effective_lp:.1f} Hz.')
        log.append(f'         OP features may be unavailable for this recording.')

    # ── Stage 1: Median filter (spike removal) ────────────────────────────
    if apply_median:
        sig_before   = sig.copy()
        sig          = apply_median_filter(sig, kernel_samples=5)
        spike_removed = np.sum(np.abs(sig_before - sig) > 5) > 0
        log.append('Stage 1 – Median filter: kernel = 5 samples (spike removal)')
        if spike_removed:
            log.append('  → Spike(s) detected and removed')
    else:
        log.append('Stage 1 – Median filter: SKIPPED (not recommended for noisy recordings)')

    # ── Stage 2: Notch filter (ISCEV 2022: off by default) ────────────────
    notch_applied  = False
    mains_detected = detect_mains_interference(sig, fs, notch_hz)

    if mains_detected:
        log.append(f'Stage 2 – Detection: {notch_hz} Hz mains interference present')
        log.append(f'          ISCEV 2022 advises against notch filters (§7)')
    else:
        log.append(f'Stage 2 – Detection: no significant {notch_hz} Hz interference')

    if apply_notch_f:
        log.append(f'Stage 2 – Notch filter REQUESTED at {notch_hz} Hz')
        log.append(f'          ISCEV 2022: "Such filters should not be used"')

        proceed = True
        if confirm_notch:
            print('\n' + '=' * 70)
            print('⚠️  ISCEV 2022 COMPLIANCE WARNING')
            print('=' * 70)
            print('Notch filters distort the ERG waveform and are NOT recommended')
            print('by ISCEV for routine clinical use (ISCEV 2022, Page 7).')
            print('\nOnly proceed if:')
            print('  • Recording is in a high-noise environment (e.g. portable screening)')
            print('  • Clinical interpretation accounts for potential distortion')
            print('  • This is NOT for grading against normative data')
            print('=' * 70)
            response = input('Apply notch filter anyway? (yes/no): ').strip().lower()
            proceed  = response == 'yes'

        if proceed:
            sig           = apply_notch(sig, fs, notch_hz)
            notch_applied = True
            log.append(f'Stage 2 – NOTCH APPLIED: {notch_hz} Hz (ISCEV non-compliant)')
            log.append(f'          NOTCH_APPLIED flag set in metadata for audit')
        else:
            log.append(f'Stage 2 – Notch filter: SKIPPED per user selection (ISCEV compliant)')
            if mains_detected:
                log.append(f'          {notch_hz} Hz interference remains in signal')
    else:
        if mains_detected:
            log.append(f'Stage 2 – Notch filter: SKIPPED (ISCEV 2022 compliant)')
            log.append(f'          {notch_hz} Hz interference remains; review waveform')
        else:
            log.append(f'Stage 2 – Notch filter: SKIPPED (no interference detected)')

    # ── Stage 3: Butterworth bandpass ─────────────────────────────────────
    sig = apply_bandpass(sig, fs, highpass_hz, effective_lp, filter_order)
    log.append(f'Stage 3 – Butterworth bandpass: order = {filter_order}, '
               f'{highpass_hz}–{effective_lp:.1f} Hz (zero-phase sosfiltfilt)')

    # ── ISCEV: pre-stimulus baseline check (≥20 ms required) ──────────────
    prestimulus_samples = int(0.020 * fs)
    has_prestimulus     = len(recording.get('prestimulus_uv', [])) >= prestimulus_samples
    if not has_prestimulus:
        log.append('WARNING: Pre-stimulus baseline < 20 ms (ISCEV minimum)')
        log.append('         Filter transient may affect early waveform features')

    result = recording.copy()
    result.update({
        'filtered_uv':  sig,
        'filter_log':   log,
        'hw_cutoff_ok': hw_cutoff_ok,
        'iscev_compliance': {
            'sampling_rate_ok':    fs >= 1000.0,
            'prestimulus_ok':      has_prestimulus,
            'bandwidth_ok':        hw_cutoff_ok,
            'notch_applied':       notch_applied,
            'notch_iscev_compliant': not notch_applied,
        },
        'notch_applied':  notch_applied,
        'mains_detected': mains_detected,
    })
    return result


