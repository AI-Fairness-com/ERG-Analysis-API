# 2. Welch PSD with diagnostic band powers
# ══════════════════════════════════════════════════════════════════════════════

def compute_welch_psd(sweeps_uv: np.ndarray,
                      fs_hz:    float,
                      nperseg:  int = None) -> dict:
    """Compute the Welch PSD from a stack of accepted ERG sweeps.

    The sweeps are averaged first to maximise SNR before PSD estimation.
    Band powers are integrated using the trapezoid rule.

    Parameters
    ----------
    sweeps_uv : np.ndarray
        Shape (n_sweeps, n_samples). Should contain only artifact-free sweeps
        (output of screen_all_sweeps from Chapter 6).
    fs_hz : float
        Sampling rate in Hz.
    nperseg : int, optional
        Welch segment length in samples. Defaults to min(256, n_samples // 4).

    Returns
    -------
    dict with keys:
      freqs      – np.ndarray, frequency axis in Hz
      psd        – np.ndarray, power spectral density in µV²/Hz
      band_power – dict of integrated band powers and power ratios
    """
    n_sw, n_samp = sweeps_uv.shape
    avg    = sweeps_uv.mean(axis=0)
    seg    = nperseg or min(256, n_samp // 4)
    freqs, psd = welch(avg, fs=fs_hz, nperseg=seg,
                       noverlap=seg // 2, window='hann')

    def band_power(f1: float, f2: float) -> float:
        mask = (freqs >= f1) & (freqs <= f2)
        return float(np.trapz(psd[mask], freqs[mask]))

    bands = {
        'total_0_300':      band_power(0.3, 300),
        'bwave_0_30':       band_power(0.3,  30),
        'op_75_300':        band_power(75,  300),
        'phnr_0_5':         band_power(0.3,   5),
        'transition_30_75': band_power(30,   75),
    }
    total = bands['total_0_300'] + 1e-12
    bands['op_power_ratio']    = bands['op_75_300'] / total
    bands['bwave_power_ratio'] = bands['bwave_0_30'] / total

    return {'freqs': freqs, 'psd': psd, 'band_power': bands}


