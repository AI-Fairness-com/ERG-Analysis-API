# 1. FFT – single-sided amplitude spectrum
# ══════════════════════════════════════════════════════════════════════════════

def compute_fft(signal_uv: np.ndarray,
                fs_hz:     float) -> dict:
    """Compute the single-sided amplitude spectrum of a real ERG signal.

    A Hann window is applied before the FFT to reduce spectral leakage caused
    by the signal's non-periodic boundary conditions.

    Parameters
    ----------
    signal_uv : np.ndarray
        Single ERG sweep in µV.
    fs_hz : float
        Sampling rate in Hz.

    Returns
    -------
    dict with keys:
      freqs     – np.ndarray, frequency axis in Hz
      amplitude – np.ndarray, single-sided amplitude spectrum in µV
      power     – np.ndarray, power spectrum in µV²
    """
    N        = len(signal_uv)
    window   = np.hanning(N)
    windowed = signal_uv * window

    fft_vals  = np.fft.rfft(windowed, n=N)
    freqs     = np.fft.rfftfreq(N, d=1.0 / fs_hz)

    # Single-sided amplitude: multiply by 2/N for correct scaling,
    # except DC and Nyquist bins which are not doubled.
    amplitude    = (2.0 / N) * np.abs(fft_vals)
    amplitude[0] /= 2
    if N % 2 == 0:
        amplitude[-1] /= 2

    return {'freqs': freqs, 'amplitude': amplitude, 'power': amplitude ** 2}


def plot_fft(fft_result: dict,
             title:      str = 'ERG Amplitude Spectrum') -> plt.Figure:
    """Plot an annotated single-sided amplitude spectrum.

    Shades the three diagnostic frequency bands:
      0.3–30 Hz   b-wave band (blue)
      30–75 Hz    Transition (gray)
      75–300 Hz   OP band (orange)

    Parameters
    ----------
    fft_result : dict
        Output of compute_fft().
    title : str
        Figure title.

    Returns
    -------
    plt.Figure
    """
    freqs = fft_result['freqs']
    amp   = fft_result['amplitude']

    fig, ax = plt.subplots(figsize=(11, 4))
    ax.plot(freqs, amp, color='#2E75B6', lw=1.6)
    ax.axvspan(0.3,  30,  alpha=0.10, color='blue',
               label='b-wave band (0.3–30 Hz)')
    ax.axvspan(30,   75,  alpha=0.08, color='gray',
               label='Transition (30–75 Hz)')
    ax.axvspan(75,   300, alpha=0.10, color='orange',
               label='OP band (75–300 Hz)')
    ax.set_xlabel('Frequency (Hz)', fontsize=11)
    ax.set_ylabel('Amplitude (µV)', fontsize=11)
    ax.set_title(title, fontsize=12)
    ax.set_xlim(0, 320)
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    return fig


