# 4. Discrete Wavelet Transform + ML feature vector
# ══════════════════════════════════════════════════════════════════════════════

def compute_dwt(signal_uv: np.ndarray,
                wavelet:   str = 'db4',
                level:     int = None) -> dict:
    """Compute the DWT of a single ERG sweep and extract a compact feature vector.

    Decomposes the signal into one approximation sub-band and up to six detail
    sub-bands. The feature vector includes log-energy per level plus three
    statistics (mean absolute, std, max absolute) per coefficient array,
    providing 28 features for a 6-level decomposition.

    Parameters
    ----------
    signal_uv : np.ndarray
        Single filtered ERG sweep in µV.
    wavelet : str
        PyWavelets wavelet name. 'db4' (Daubechies 4) is the standard choice
        for ERG because its smooth shape closely matches the ERG waveform
        morphology, improving the concentration of signal energy into fewer
        coefficients.
    level : int, optional
        Decomposition depth. Defaults to min(max_possible, 6) per §7.4.2.
        Do not exceed 6 at fs ≥ 1000 Hz: deeper levels produce sub-bands
        below the 0.3 Hz ISCEV high-pass cutoff.

    Returns
    -------
    dict with keys:
      coeffs         – list [cA_n, cD_n, …, cD_1] (pywt.wavedec convention)
      level_energies – np.ndarray, energy per detail level (D1…Dn)
      approx_energy  – float, energy of the final approximation cA_n
      feature_vector – np.ndarray, compact ML feature vector
      n_features     – int, length of feature_vector
    """
    max_lvl = pywt.dwt_max_level(len(signal_uv), wavelet)
    lvl     = level or min(max_lvl, 6)
    coeffs  = pywt.wavedec(signal_uv, wavelet, level=lvl)
    # coeffs[0]   = approximation cA_lvl
    # coeffs[1:] = details cD_lvl … cD_1

    approx_energy   = float(np.sum(coeffs[0] ** 2) / len(coeffs[0]))
    detail_energies = np.array(
        [float(np.sum(c ** 2) / len(c)) for c in coeffs[1:]])

    # Log-energy features (more Gaussian distribution than raw energy)
    log_energies = np.log1p(
        np.concatenate([[approx_energy], detail_energies]))

    # Per-level statistics: mean absolute, std, max absolute
    stats = []
    for c in coeffs:
        stats.extend([float(np.mean(np.abs(c))),
                      float(np.std(c)),
                      float(np.max(np.abs(c)))])

    feature_vector = np.concatenate([log_energies, stats])

    return {
        'coeffs':         coeffs,
        'level_energies': detail_energies,
        'approx_energy':  approx_energy,
        'feature_vector': feature_vector,
        'n_features':     len(feature_vector),
    }


