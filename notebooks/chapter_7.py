# 3. Continuous Wavelet Transform
# ══════════════════════════════════════════════════════════════════════════════

def compute_cwt(signal_uv:  np.ndarray,
                fs_hz:      float,
                wavelet:    str   = 'cmor1.5-1.0',
                freq_min_hz: float = 0.5,
                freq_max_hz: float = 300.0,
                n_freqs:    int   = 128) -> dict:
    """Compute the CWT power scalogram of a single ERG sweep.

    Parameters
    ----------
    signal_uv : np.ndarray
        Single ERG sweep in µV.
    fs_hz : float
        Sampling rate in Hz.
    wavelet : str
        PyWavelets CWT wavelet string.
        'cmor1.5-1.0' = complex Morlet (bandwidth 1.5, centre freq 1.0) –
        recommended for ERG; provides good joint time-frequency resolution.
        'mexh' = Mexican hat (real-valued, suited to peak detection).
        'morl' = standard Morlet.
    freq_min_hz, freq_max_hz : float
        Frequency range to analyse in Hz.
    n_freqs : int
        Number of logarithmically spaced frequency bins.

    Returns
    -------
    dict with keys:
      scalogram – np.ndarray (n_freqs × n_samples), power in µV²
      freqs     – np.ndarray, frequency axis in Hz
      times_ms  – np.ndarray, time axis in ms
    """
    freqs_hz = np.logspace(np.log10(freq_min_hz),
                           np.log10(freq_max_hz), n_freqs)
    scales   = pywt.frequency2scale(wavelet, freqs_hz / fs_hz)
    coeffs, _ = pywt.cwt(signal_uv, scales, wavelet,
                          sampling_period=1.0 / fs_hz)
    scalogram = np.abs(coeffs) ** 2
    times_ms  = np.arange(len(signal_uv)) * 1000.0 / fs_hz

    return {'scalogram': scalogram, 'freqs': freqs_hz, 'times_ms': times_ms}


def plot_cwt(cwt_result: dict,
             pre_ms:     float = 100.0,
             title:      str   = 'CWT Scalogram') -> plt.Figure:
    """Display the CWT power scalogram as a time-frequency image.

    The frequency axis is logarithmic. The OP band (75–300 Hz) is shaded and
    the stimulus onset is marked with a vertical line.

    Parameters
    ----------
    cwt_result : dict
        Output of compute_cwt().
    pre_ms : float
        Pre-stimulus window length in ms (marks stimulus onset on plot).
    title : str
        Figure title.

    Returns
    -------
    plt.Figure
    """
    scalo  = cwt_result['scalogram']
    freqs  = cwt_result['freqs']
    times  = cwt_result['times_ms']

    fig, ax = plt.subplots(figsize=(12, 5))
    img = ax.pcolormesh(times, freqs,
                        10 * np.log10(scalo + 1e-12),
                        cmap='inferno', shading='auto')
    ax.set_yscale('log')
    ax.set_ylim(freqs[0], freqs[-1])
    ax.set_yticks([1, 5, 10, 30, 75, 150, 300])
    ax.set_yticklabels(['1', '5', '10', '30', '75', '150', '300'])
    ax.axvline(pre_ms, color='cyan', lw=1.2, ls='--',
               label=f'Stimulus onset ({pre_ms:.0f} ms)')
    ax.axhspan(75, 300, alpha=0.12, color='orange',
               label='OP band (75–300 Hz)')
    ax.set_xlabel('Time (ms)', fontsize=11)
    ax.set_ylabel('Frequency (Hz)', fontsize=11)
    ax.set_title(title, fontsize=12)
    plt.colorbar(img, ax=ax, label='Power (dB)')
    ax.legend(fontsize=9)
    plt.tight_layout()
    return fig


