# 6. Single-visit pipeline runner
# ══════════════════════════════════════════════════════════════════════════════

def run_single_visit_pipeline(case_params: dict,
                               norm_stats:  dict,
                               config:      ERGAPIConfig) -> dict:
    """Run the complete 8-stage single-visit pipeline for one case.

    Uses synthetic Z-scores derived from the case parameters and normative
    statistics rather than calling the full Chapter 9–15 stack, making this
    a self-contained integration test that runs without real patient data.

    Parameters
    ----------
    case_params : dict – one entry from CASE_STUDIES
    norm_stats : dict – {parameter: {'mu': float, 'sigma': float}}
    config : ERGAPIConfig

    Returns
    -------
    dict with status, report (four layers), quality_result
    """
    os.makedirs(config.output_dir, exist_ok=True)
    pid       = case_params['patient_id']
    electrode = case_params.get('electrode', case_params.get('electrode_A', 'dtl_fiber'))

    # Stage 1 – schema check (simulated for synthetic data)
    if electrode is None:
        error = validate_csv_schema(pd.DataFrame(), patient_id=pid)
        return {'status': 'HALT', 'report': error['error_report'],
                'quality_result': None}

    # Stage 2–3 – signal quality
    snr  = case_params.get('snr_db', case_params.get('snr_db_A', 5.0))
    if snr is None:
        snr = 0.0
    qual = assess_signal_quality(snr, electrode)

    # Stage 4 – Z-scores from synthetic case parameters
    z_scores = {}
    for param, stats in norm_stats.items():
        val = case_params.get(param)
        if val is None:
            continue
        z = (val - stats['mu']) / (stats['sigma'] + 1e-8)
        z_scores[param] = {'z': round(z, 3), 'tl': assign_traffic_light(z)}

    # Stage 5 – missing data handled by NaN fill (already handled by case_params)

    # Stage 6 – classification (use provided proba or derive from composite TL)
    stage2_proba = case_params.get('stage2_proba')
    if stage2_proba is None:
        comp = composite_traffic_light([v['tl'] for v in z_scores.values()])
        stage2_proba = {'GREEN': 0.88, 'AMBER': 0.72, 'RED': 0.91}[comp]

    disease_class = case_params['disease_class']

    # Stage 7 – SHAP (synthetic summary)
    if not qual['shap_suppressed'] and z_scores:
        top_feat  = sorted(z_scores.items(), key=lambda x: abs(x[1]['z']),
                           reverse=True)[:3]
        shap_summary = {
            f: {'shap': round(v['z'] * 0.08, 3), 'tl': v['tl']}
            for f, v in top_feat
        }
    else:
        shap_summary = None

    # Stage 8 – report assembly
    report = assemble_report(
        patient_id    = pid,
        case_params   = case_params,
        z_scores      = z_scores,
        stage2_proba  = stage2_proba,
        disease_class = disease_class,
        quality_result= qual,
        shap_summary  = shap_summary,
        config        = config,
    )

    return {'status': qual['state'], 'report': report, 'quality_result': qual}


