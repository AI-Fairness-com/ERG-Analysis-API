    def save_results(self, path: str = None):
        """Save all results to JSON."""
        out = path or os.path.join(self.config.output_dir, 'case_study_results.json')
        os.makedirs(os.path.dirname(out), exist_ok=True)

        # Serialise (convert non-serialisable types)
        def make_serial(obj):
            if isinstance(obj, dict): return {k: make_serial(v) for k, v in obj.items()}
            if isinstance(obj, list): return [make_serial(v) for v in obj]
            if isinstance(obj, np.integer): return int(obj)
            if isinstance(obj, np.floating): return float(obj)
            return obj

        with open(out, 'w') as f:
            json.dump(make_serial(self.results), f, indent=2)
        print(f'Results saved: {out}')

