# 3. Signal quality assessment
# ══════════════════════════════════════════════════════════════════════════════

def assess_signal_quality(snr_db: float,
                           electrode_type: str) -> dict:
    """Assess signal quality and return pipeline state (PASS / WARNING / HALT).

    In WARNING mode: pipeline continues with SHAP suppressed and mandatory
    caveats on all report layers. The Traffic Light badge is shown in grey.

    Parameters
    ----------
    snr_db : float – SNR in dB (Chapter 2 §2.4)
    electrode_type : str

    Returns
    -------
    dict with keys: state ('PASS'/'WARNING'/'FAIL'), snr_db, thresholds,
                    shap_suppressed, caveats
    """
    thresholds = SNR_THRESHOLDS.get(electrode_type.lower(), SNR_THRESHOLDS['dtl_fiber'])
    pass_thr   = thresholds['pass']
    warn_thr   = thresholds['warn']

    if snr_db >= pass_thr:
        state     = 'PASS'
        caveats   = []
        suppress  = False
    elif snr_db >= warn_thr:
        state     = 'WARNING'
        suppress  = True
        caveats   = [
            'SIGNAL_QUALITY_WARNING: recording SNR is below the PASS threshold.',
            'Classification result is provided for reference only.',
            'SHAP attribution suppressed (unreliable on low-SNR signals).',
            'Repeat recording with improved electrode contact is recommended.',
        ]
    else:
        state     = 'FAIL'
        suppress  = True
        caveats   = [
            'SIGNAL_QUALITY_FAIL: recording SNR is below the minimum acceptable threshold.',
            'Classification result is NOT clinically reliable.',
            'Do not use for clinical decision-making. Repeat recording required.',
        ]

    return {
        'state'          : state,
        'snr_db'         : round(snr_db, 2),
        'thresholds'     : thresholds,
        'shap_suppressed': suppress,
        'caveats'        : caveats,
    }


