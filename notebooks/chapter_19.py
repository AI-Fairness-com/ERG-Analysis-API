# 2. CSV schema validation (Stage 1)
# ══════════════════════════════════════════════════════════════════════════════

def validate_csv_schema(df: pd.DataFrame,
                         patient_id: str = 'UNKNOWN') -> dict:
    """Validate a submitted ERG CSV against the Standardized schema (Appendix A).

    Missing required fields trigger a HALT: the pipeline does not proceed to
    any subsequent stage. All required fields must be present and non-null.
    The electrode_type field requires a recognised value; without it no valid
    Z-score, SNR threshold, or transference correction can be applied.

    Parameters
    ----------
    df : pd.DataFrame – loaded CSV
    patient_id : str – for error report labelling

    Returns
    -------
    dict with keys: status ('PASS' or 'HALT'), missing_fields,
                    error_report (None on PASS)
    """
    missing = [f for f in REQUIRED_CSV_FIELDS if f not in df.columns]
    null_electrode = (
        'electrode_type' in df.columns and
        df['electrode_type'].isna().any()
    )

    if missing or null_electrode:
        missing_full = list(set(missing + (['electrode_type'] if null_electrode else [])))
        error_report = {
            'status'        : 'HALT',
            'patient_id'    : patient_id,
            'timestamp'     : datetime.datetime.now().isoformat(),
            'missing_fields': missing_full,
            'error_message' : (
                f'Required field(s) {missing_full} are absent or null. '
                f'No processing has been attempted. '
                f'Valid electrode_type values: '
                f'{list(SNR_THRESHOLDS.keys())}. '
                f'Resubmit with all required fields populated.'),
            'layer1_report' : 'ERROR — see error_message',
            'layer2_report' : None,
            'layer3_report' : None,
            'layer4_audit'  : None,
        }
        return {'status': 'HALT', 'missing_fields': missing_full,
                'error_report': error_report}

    return {'status': 'PASS', 'missing_fields': [], 'error_report': None}


