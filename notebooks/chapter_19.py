# 4. Traffic Light zone assignment
# ══════════════════════════════════════════════════════════════════════════════

def assign_traffic_light(z_score: float,
                          tl_green: float = TL_GREEN,
                          tl_amber: float = TL_AMBER) -> str:
    """Assign a Traffic Light zone from a Z-score (Chapter 10 Equation 10.2)."""
    abs_z = abs(z_score)
    if abs_z <= tl_green:
        return 'GREEN'
    elif abs_z <= tl_amber:
        return 'AMBER'
    return 'RED'


def composite_traffic_light(tl_list: list) -> str:
    """Return the most severe Traffic Light zone across all parameters."""
    if 'RED'   in tl_list: return 'RED'
    if 'AMBER' in tl_list: return 'AMBER'
    return 'GREEN'


