# 7. Case Study Runner
# ══════════════════════════════════════════════════════════════════════════════

class CaseStudyRunner:
    """Runs all 9 case studies and saves outputs to JSON and a summary figure.

    Parameters
    ----------
    config : ERGAPIConfig
    norm_stats : dict – {parameter: {'mu': float, 'sigma': float}}
                 Synthetic normative statistics for Z-score calculation.
    """

    def __init__(self, config: ERGAPIConfig, norm_stats: dict):
        self.config     = config
        self.norm_stats = norm_stats
        self.results    = {}

    def run_all(self) -> dict:
        """Run all case studies and return results dict."""
        print('Running 9 case studies...\n')
        for name, params in CASE_STUDIES.items():
            print(f'── {name} ──')
            if name == 'CS09_DataQuality':
                self._run_cs09(name, params)
            else:
                result = run_single_visit_pipeline(
                    params, self.norm_stats, self.config)
                self.results[name] = result
                l1 = result['report']['layer1']
                print(f'  Patient : {params["patient_id"]}')
                print(f'  Status  : {result["status"]}')
                print(f'  TL badge: {l1["badge_colour"]} '
                      f'({l1.get("traffic_light", "ERROR")})')
                print(f'  Disease : {params["disease_class"]}')
                if result['report']['layer2'].get('confidence_note'):
                    print(f'  ⚠ {result["report"]["layer2"]["confidence_note"][:80]}')
            print()
        return self.results

    def _run_cs09(self, name: str, params: dict):
        """Case Study 9: two-scenario data quality failure."""
        print('  Scenario A: SIGNAL_QUALITY_WARNING')
        cs09a        = dict(params)
        cs09a['electrode'] = params.get('electrode_A', 'skin')
        cs09a['snr_db']    = params.get('snr_db_A', 2.1)
        res_a = run_single_visit_pipeline(cs09a, self.norm_stats, self.config)
        print(f'    Status : {res_a["status"]}')
        print(f'    SHAP   : {"SUPPRESSED" if res_a["quality_result"]["shap_suppressed"] else "SHOWN"}')
