# 5. Layer report assembler
# ══════════════════════════════════════════════════════════════════════════════

def assemble_report(patient_id:      str,
                    case_params:     dict,
                    z_scores:        dict,
                    stage2_proba:    Optional[float],
                    disease_class:   str,
                    quality_result:  dict,
                    shap_summary:    Optional[dict],
                    config:          ERGAPIConfig,
                    version_stamp:   Optional[dict] = None,
                    longitudinal:    Optional[dict] = None) -> dict:
    """Assemble the four-layer clinical report for one recording.

    Parameters
    ----------
    patient_id : str
    case_params : dict – ERG parameter values
    z_scores : dict – {parameter: {'z': float, 'tl': str}}
    stage2_proba : float or None – calibrated top-class probability
    disease_class : str – predicted class label
    quality_result : dict – from assess_signal_quality()
    shap_summary : dict or None – top SHAP contributors (None if suppressed)
    config : ERGAPIConfig
    version_stamp : dict or None
    longitudinal : dict or None – progression summary from Chapter 18

    Returns
    -------
    dict with keys: layer1, layer2, layer3, layer4
    """
    tl_list    = [v['tl'] for v in z_scores.values()]
    composite  = composite_traffic_light(tl_list)
    timestamp  = datetime.datetime.now().isoformat()

    # Layer 1 — Traffic Light badge
    layer1 = {
        'traffic_light'     : composite,
        'patient_id'        : patient_id,
        'timestamp'         : timestamp,
        'quality_state'     : quality_result['state'],
        'badge_colour'      : (composite if quality_result['state'] == 'PASS'
                               else 'GREY'),
        'badge_label'       : (composite if quality_result['state'] == 'PASS'
                               else 'RESULT UNRELIABLE'),
    }

    # Layer 2 — Clinical summary
    conf_note = ''
    if stage2_proba is not None and stage2_proba < 0.60:
        conf_note = (
            f' This is a low-confidence classification '
            f'(probability {stage2_proba:.0%}). Clinical correlation recommended.')
    layer2 = {
        'predicted_class'  : disease_class,
        'stage2_probability': stage2_proba,
        'z_score_summary'  : {p: v['tl'] for p, v in z_scores.items()},
        'composite_tl'     : composite,
        'quality_caveats'  : quality_result['caveats'],
        'confidence_note'  : conf_note,
    }

    # Layer 3 — Specialist Report
    layer3 = {
        'per_parameter_z'  : z_scores,
        'shap_attribution' : shap_summary if not quality_result['shap_suppressed']
                             else {'suppressed': True,
                                   'reason': 'SIGNAL_QUALITY_WARNING'},
        'longitudinal'     : longitudinal,
        'clinical_notes'   : case_params.get('notes', ''),
    }

    # Layer 4 — Audit JSON
    layer4 = {
        'patient_id'      : patient_id,
        'timestamp'       : timestamp,
        'api_version'     : config.api_version,
        'version_stamp'   : version_stamp,
        'config_snapshot' : config.to_dict(),
        'raw_z_scores'    : {p: round(v['z'], 3) for p, v in z_scores.items()},
        'composite_tl'    : composite,
        'quality_result'  : quality_result,
        'case_params'     : {k: v for k, v in case_params.items()
                             if isinstance(v, (int, float, str, bool))},
    }

    return {'layer1': layer1, 'layer2': layer2,
            'layer3': layer3, 'layer4': layer4}


