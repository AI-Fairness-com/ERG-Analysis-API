# 4. Two-stage cascade classifier
# ══════════════════════════════════════════════════════════════════════════════

class CascadeClassifier:
    """Two-stage cascade classifier for ERG spectrogram disease classification.

    Stage 1: Binary ViT Small (Normal vs Abnormal).
             Decision threshold set to achieve Stage 1 sensitivity ≥ 0.95.
             If Stage 1 probability(Abnormal) ≥ threshold: forward to Stage 2.
             If Stage 1 probability(Normal)   > threshold complement: Green TL.

    Stage 2: Six-class ViT Small (disease classification).
             Receives only recordings flagged as Abnormal by Stage 1.
             Output: probability vector over 6 disease classes.

    Joint confidence = p(Abnormal) × p(disease class | Abnormal).
    Top-3 disease classes by probability are reported in the Layer 2 summary.

    Parameters
    ----------
    stage1_path : str  path to Stage 1 .pt weights file
    stage2_path : str  path to Stage 2 .pt weights file
    stage1_threshold : float  abnormal decision threshold (default 0.5;
                               tune from ROC curve for sensitivity ≥ 0.95)
    """

    def __init__(self,
                 stage1_path:      str,
                 stage2_path:      str,
                 stage1_threshold: float = 0.5):
        self.stage1 = build_vit_stage1(pretrained=False)
        self.stage1.load_state_dict(
            torch.load(stage1_path, map_location=DEVICE))
        self.stage1 = self.stage1.to(DEVICE).eval()

        self.stage2 = build_vit_stage2(pretrained=False)
        self.stage2.load_state_dict(
            torch.load(stage2_path, map_location=DEVICE))
        self.stage2 = self.stage2.to(DEVICE).eval()

        self.threshold = stage1_threshold

    @torch.no_grad()
    def predict(self, images: torch.Tensor) -> list:
        """Run the cascade on a batch of 224×224 spectrogram tensors.

        Parameters
        ----------
        images : torch.Tensor, shape (B, C, H, W)

        Returns
        -------
        list of dicts, one per recording, with keys:
          stage1_label      – 'Normal' or 'Abnormal'
          stage1_prob_abnormal – float
          stage2_probs      – np.ndarray (6,) or None if stage1=Normal
          top3_classes      – list of (class_name, joint_confidence) or None
          joint_confidence  – float (p_abnormal × p_top_class) or None
          traffic_light_input – float confidence for Traffic Light assignment
        """
        images = images.to(DEVICE)
        s1_logits = self.stage1(images)
        s1_probs  = torch.softmax(s1_logits, dim=1).cpu().numpy()
        # Convention: class 0 = Normal, class 1 = Abnormal
        p_abnormal = s1_probs[:, 1]

        results = []
        for i, pa in enumerate(p_abnormal):
            if pa < self.threshold:
                results.append({
                    'stage1_label'         : 'Normal',
                    'stage1_prob_abnormal' : float(pa),
                    'stage2_probs'         : None,
                    'top3_classes'         : None,
                    'joint_confidence'     : float(1 - pa),
                    'traffic_light_input'  : float(1 - pa),
                })
            else:
                img_i    = images[i].unsqueeze(0)
                s2_logits = self.stage2(img_i)
                s2_probs  = torch.softmax(s2_logits, dim=1).cpu().numpy()[0]
                joint     = pa * s2_probs
                top3_idx  = np.argsort(joint)[::-1][:3]
                top3      = [(DISEASE_CLASSES[j], float(joint[j]))
                             for j in top3_idx]
                results.append({
                    'stage1_label'         : 'Abnormal',
                    'stage1_prob_abnormal' : float(pa),
                    'stage2_probs'         : s2_probs,
                    'top3_classes'         : top3,
                    'joint_confidence'     : float(joint[top3_idx[0]]),
                    'traffic_light_input'  : float(pa),
                })
        return results

    def tune_threshold(self,
                       images:    torch.Tensor,
                       y_binary:  np.ndarray,
                       min_sens:  float = STAGE1_SENS_MIN) -> float:
        """Set Stage 1 threshold to achieve minimum sensitivity on a held-out set.

        Scans thresholds from 0.01 to 0.99 in steps of 0.01. Selects the
        highest threshold (most specific) that achieves sensitivity ≥ min_sens
        for the Abnormal class. Returns the selected threshold and updates
        self.threshold.

        Parameters
        ----------
        images : torch.Tensor, shape (N, C, H, W) – validation set images
        y_binary : np.ndarray, shape (N,) – binary labels (0=Normal, 1=Abnormal)
        min_sens : float – minimum required sensitivity (default 0.95)

        Returns
        -------
        float – selected threshold
        """
        with torch.no_grad():
            s1_logits = self.stage1(images.to(DEVICE))
            p_abn     = torch.softmax(s1_logits, dim=1)[:, 1].cpu().numpy()

        best_thr  = 0.5
        for thr in np.arange(0.99, 0.00, -0.01):
            preds     = (p_abn >= thr).astype(int)
            tp        = ((preds == 1) & (y_binary == 1)).sum()
            fn        = ((preds == 0) & (y_binary == 1)).sum()
            sens      = tp / (tp + fn) if (tp + fn) > 0 else 0.0
            if sens >= min_sens:
                best_thr = float(thr)
                break

        print(f'Stage 1 threshold tuned: {best_thr:.2f} '
              f'(sensitivity ≥ {min_sens:.2f})')
        self.threshold = best_thr
        return best_thr


