def compute_fid(real_image_dir: str,
                fake_image_dir: str,
                device:         str = DEVICE) -> float:
    """Compute Fréchet Inception Distance between real and synthetic spectrograms.

    FID < 50 is the admission threshold for synthetic data to the training set
    (§13.6.2). FID ≥ 50 requires retraining the GAN before any synthetic
    examples are used.

    Requires:  pip install pytorch-fid

    Parameters
    ----------
    real_image_dir : str  directory of real spectrogram PNG/JPEG images
    fake_image_dir : str  directory of synthetic spectrogram PNG/JPEG images
    device : str  'cuda' or 'cpu'

    Returns
    -------
    float  FID score
    """
    try:
        from pytorch_fid import fid_score
    except ImportError:
        raise ImportError('pytorch-fid is required: pip install pytorch-fid')

    fid    = fid_score.calculate_fid_given_paths(
        [real_image_dir, fake_image_dir],
        batch_size = 32,
        device     = device,
        dims       = 2048,
    )
    status = 'PASS' if fid < FID_THRESHOLD else f'FAIL (threshold {FID_THRESHOLD}) -- retrain GAN'
    print(f'FID = {fid:.2f}  [{status}]')
    return fid


