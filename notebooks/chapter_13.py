# 1. ERG-specific data augmentation
# ══════════════════════════════════════════════════════════════════════════════

class ERGSpectrogramAugment:
    """Apply ERG-validated augmentations to a 224×224 spectrogram tensor.

    Four augmentation types are applied stochastically during training (§13.3):
      1. Time masking    – zeros a random contiguous band of time columns
      2. Frequency masking – zeros a random contiguous band of frequency rows
      3. Gaussian noise  – additive noise to simulate recording noise floor
      4. Brightness jitter – multiplicative intensity scaling

    ⚠️  Geometric augmentations (horizontal flip, vertical flip, rotation) are
    explicitly PROHIBITED for ERG spectrograms. Flipping the time axis reverses
    stimulus onset; flipping the frequency axis inverts the OP/b-wave band
    relationship. Both destroy the physiological meaning of the image.

    Parameters
    ----------
    time_mask_max : int
        Maximum width of the time mask in pixels (default 20 = ~4.5 % of 224).
    freq_mask_max : int
        Maximum height of the frequency mask in pixels (default 20).
    noise_std : float
        Standard deviation of additive Gaussian noise (default 0.05).
    brightness_range : tuple
        (min, max) multiplicative brightness jitter (default 0.9–1.1).
    p : float
        Probability of applying each augmentation independently (default 0.5).
    """

    def __init__(self,
                 time_mask_max:    int   = 20,
                 freq_mask_max:    int   = 20,
                 noise_std:        float = 0.05,
                 brightness_range: tuple = (0.9, 1.1),
                 p:                float = 0.5):
        self.time_mask_max    = time_mask_max
        self.freq_mask_max    = freq_mask_max
        self.noise_std        = noise_std
        self.brightness_range = brightness_range
        self.p                = p

    def __call__(self, x: torch.Tensor) -> torch.Tensor:
        """Augment a single spectrogram tensor.

        Parameters
        ----------
        x : torch.Tensor, shape (C, H, W) or (H, W)

        Returns
        -------
        torch.Tensor, same shape as input.
        """
        x = x.clone()
        rng = np.random.default_rng()

        # Time masking: zero a random time-axis band
        if rng.random() < self.p:
            w    = rng.integers(1, self.time_mask_max + 1)
            t0   = rng.integers(0, max(1, x.shape[-1] - w))
            x[..., t0: t0 + w] = 0.0

        # Frequency masking: zero a random frequency-axis band
        if rng.random() < self.p:
            h    = rng.integers(1, self.freq_mask_max + 1)
            f0   = rng.integers(0, max(1, x.shape[-2] - h))
            x[..., f0: f0 + h, :] = 0.0

        # Gaussian noise
        if rng.random() < self.p:
            x = x + torch.randn_like(x) * self.noise_std

        # Brightness jitter (multiplicative)
        if rng.random() < self.p:
            lo, hi = self.brightness_range
            scale  = lo + rng.random() * (hi - lo)
            x      = x * scale

        return x.clamp(0.0, 1.0)


