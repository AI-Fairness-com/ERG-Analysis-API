def train_vit(model:        nn.Module,
              train_loader: DataLoader,
              val_loader:   DataLoader,
              class_weights: torch.Tensor = None,
              num_epochs:   int   = NUM_EPOCHS,
              patience:     int   = PATIENCE,
              save_path:    str   = 'models/vit_best.pt',
              config:       dict  = None) -> dict:
    """Fine-tune ViT Small with differential learning rates and early stopping.

    Training configuration (§13.3):
      Optimiser     : AdamW (weight_decay=1e-2)
      LR schedule   : CosineAnnealingLR (T_max=num_epochs, eta_min=1e-7)
      Differential LR: backbone 1e-5  (10× lower than head — §13.3.2)
                        head    1e-4
      Loss          : CrossEntropyLoss with optional class_weights
      Gradient clip : max_norm=1.0 (prevents large updates in early epochs)
      Early stopping: patience=10 on validation loss

    Parameters
    ----------
    model : nn.Module (output of build_vit_stage1 or build_vit_stage2)
    train_loader, val_loader : DataLoader yielding (images, labels) batches
    class_weights : torch.Tensor, shape (n_classes,) or None
    num_epochs : int
    patience : int
    save_path : str  path for best model checkpoint
    config : dict  config-API dict; training metadata written here if provided

    Returns
    -------
    dict with keys: train_losses, val_losses, best_epoch, best_val_loss
    """
    os.makedirs(os.path.dirname(save_path) if os.path.dirname(save_path)
                else '.', exist_ok=True)

    model = model.to(DEVICE)

    # Differential learning rates
    backbone_params = [p for n, p in model.named_parameters()
                       if 'head' not in n]
    head_params     = [p for n, p in model.named_parameters()
                       if 'head'     in n]
    optimizer = AdamW([
        {'params': backbone_params, 'lr': BACKBONE_LR},
        {'params': head_params,     'lr': HEAD_LR},
    ], weight_decay=WEIGHT_DECAY)

    scheduler = CosineAnnealingLR(optimizer, T_max=num_epochs, eta_min=1e-7)
    criterion = nn.CrossEntropyLoss(
        weight=class_weights.to(DEVICE) if class_weights is not None else None)

    best_val_loss  = float('inf')
    patience_count = 0
    best_epoch     = 0
    train_losses, val_losses = [], []

    for epoch in range(num_epochs):
        # ── Training ───────────────────────────────────────────────────────
        model.train()
        train_loss = 0.0
        for X_batch, y_batch in train_loader:
            X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)
            optimizer.zero_grad()
            logits = model(X_batch)
            loss   = criterion(logits, y_batch)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(),
                                           max_norm=GRAD_CLIP)
            optimizer.step()
            train_loss += loss.item()

        # ── Validation ─────────────────────────────────────────────────────
        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for X_val, y_val in val_loader:
                logits    = model(X_val.to(DEVICE))
                val_loss += criterion(logits, y_val.to(DEVICE)).item()

        scheduler.step()
        train_losses.append(train_loss / len(train_loader))
        val_losses.append(val_loss   / len(val_loader))

        print(f'Epoch {epoch:3d}  '
              f'train={train_losses[-1]:.4f}  '
              f'val={val_losses[-1]:.4f}  '
              f'patience={patience_count}/{patience}')

        # ── Early stopping ─────────────────────────────────────────────────
        if val_loss < best_val_loss:
            best_val_loss  = val_loss
            best_epoch     = epoch
            patience_count = 0
            torch.save(model.state_dict(), save_path)
        else:
            patience_count += 1
            if patience_count >= patience:
                print(f'Early stopping at epoch {epoch}.')
                break

    # Record training metadata in config-API dict
    if config is not None:
        key = os.path.basename(save_path).replace('.pt', '')
        config[key] = {
            'model_path'  : save_path,
            'best_epoch'  : best_epoch,
            'best_val_loss': round(best_val_loss, 6),
            'num_epochs'  : epoch + 1,
        }

    return {
        'train_losses' : train_losses,
        'val_losses'   : val_losses,
        'best_epoch'   : best_epoch,
        'best_val_loss': best_val_loss,
    }


