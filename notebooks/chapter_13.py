def build_vit_stage1(pretrained: bool = True) -> nn.Module:
    """Build the Stage 1 binary ViT Small (Normal vs Abnormal).

    Architecture: vit_small_r26_s32_224
      - 22 M parameters, 8 attention heads, 8 encoder blocks, embedding dim 384
      - Pre-trained on ImageNet-21k (14 M images, 21,843 classes)
      - Classification head replaced with 2-output linear layer

    Parameters
    ----------
    pretrained : bool
        Load ImageNet-21k weights (True for fine-tuning; False for ablation).

    Returns
    -------
    nn.Module ready to move to device with .to(DEVICE).
    """
    model = timm.create_model(
        VIT_MODEL_NAME,
        pretrained  = pretrained,
        num_classes = N_STAGE1_CLASSES,
    )
    return model


def build_vit_stage2(pretrained: bool = True) -> nn.Module:
    """Build the Stage 2 six-class disease ViT Small.

    Same architecture as Stage 1 with a 6-output classification head.
    Receives only recordings classified as Abnormal by Stage 1.
    """
    model = timm.create_model(
        VIT_MODEL_NAME,
        pretrained  = pretrained,
        num_classes = N_STAGE2_CLASSES,
    )
    return model


def build_comparison_model(arch:        str  = 'densenet121',
                            num_classes: int  = N_STAGE2_CLASSES,
                            pretrained:  bool = True) -> nn.Module:
    """Build a comparison CNN architecture (DenseNet121 / ResNet50 / VGG16).

    Architecture AUC baselines (Albasu et al., 2024):
      densenet121 → 0.851
      resnet50    → 0.823
      vgg16       → 0.811

    Parameters
    ----------
    arch : str
        One of 'densenet121', 'resnet50', 'vgg16', 'vgg19'.
    num_classes : int
    pretrained : bool

    Returns
    -------
    nn.Module
    """
    supported = ('densenet121', 'resnet50', 'vgg16', 'vgg19')
    if arch not in supported:
        raise ValueError(f'arch must be one of {supported}; got {arch!r}')
    model = timm.create_model(arch, pretrained=pretrained,
                               num_classes=num_classes)
    return model


