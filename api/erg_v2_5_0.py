def run_pipeline(b):
    with output_area:
        clear_output()

        # Start timing
        t_start = time.perf_counter()

        if not upload_widget.value:
            print("❌ Please upload an ERG CSV file first")
            return

        if notch_override_widget.value and not notch_consent_widget.value:
            print("❌ Notch filter override requires confirmation of clinical justification")
            return

        uploaded_file = list(upload_widget.value.values())[0]
        filename = uploaded_file['metadata']['name']
        content = uploaded_file['content']

        temp_path = f"/tmp/{filename}"
        try:
            with open(temp_path, 'wb') as f:
                f.write(content)

            print("=" * 60)
            print("PROCESSING ERG SIGNAL...")
            print("=" * 60)
            print(f"File: {filename}")
            print(f"Age Group: {age_group_widget.value}")
            print(f"Electrode: {electrode_widget.value}")
            print(f"Protocol: {protocol_widget.value}")
            print(f"Flash Duration: {flash_duration_widget.value} ms")
            print(f"Pre-stimulus Duration: {pre_stimulus_widget.value} ms")
            print(f"Notch Filter: {'APPLIED (override)' if notch_override_widget.value else 'SKIPPED (ISCEV compliant)'}")
            print("-" * 60)

            # Timeout guard — abort if pipeline exceeds 60 seconds
            PIPELINE_TIMEOUT_S = 60
            pipeline_result = {}
            pipeline_error  = {}

            def _run_pipeline_inner():
                try:
                    # Load CSV file
                    time_ms, signal_uv, fs_hz, metadata = load_erg_csv(temp_path)
                    print(f"✓ Signal loaded: {len(signal_uv)} samples @ {fs_hz:.0f} Hz")

                    # Calculate flash onset sample
                    pre_stimulus_ms = pre_stimulus_widget.value
                    flash_onset_sample = int(pre_stimulus_ms * fs_hz / 1000)
                    prestimulus_samples = flash_onset_sample

                    # Calculate noise RMS
                    if prestimulus_samples > 0 and prestimulus_samples < len(signal_uv):
                        pre_stim_signal = signal_uv[:prestimulus_samples]
                        noise_rms_uv = float(np.sqrt(np.mean(pre_stim_signal**2)))
                    else:
                        noise_rms_uv = 1.0
                        print(f"⚠️ Warning: Could not extract pre-stimulus baseline. Using default noise RMS.")

                    # Run audit
                    audit_result = run_full_audit(
                        signal_uv, fs_hz,
                        electrode_type=electrode_widget.value,
                        prestimulus_samples=prestimulus_samples,
                        age_group=age_group_widget.value,
                        flash_duration_ms=flash_duration_widget.value
                    )

                    print(f"✓ Audit complete: Grade {audit_result['quality']['grade']}")
                    print(f"  OP Available: {audit_result['oscillatory_potentials']['available']}")
                    print(f"  SNR: {audit_result['snr']['linear']} ({audit_result['snr']['status']})")

                    # Run filter pipeline
                    hardware_cutoff = audit_result['bandwidth'].get('hardware_cutoff_hz')

                    filtered_signal, filter_log = run_filter_pipeline(
                        signal_uv, fs_hz,
                        apply_notch=notch_override_widget.value,
                        notch_hz=50.0,
                        hardware_cutoff_hz=hardware_cutoff,
                        user_confirmed_notch=notch_consent_widget.value
                    )

                    print(f"✓ Filtering complete")

                    # Extract features
                    op_signal = None
                    if op_extract_widget.value and audit_result['oscillatory_potentials']['available']:
                        op_signal = extract_ops(filtered_signal, fs_hz)
                        print(f"✓ OP signal extracted (75-300 Hz)")

                    # ── Step 2.5: Signal orientation auto-detection ──────────
                    # ISCEV physiology: the a-wave is a negative deflection and
                    # the b-wave is positive. Some recording systems invert the
                    # amplifier output, producing a mirror-image waveform.
                    # Detect this by summing the post-stimulus signal in the
                    # 0-30 ms window: if the sum is positive (dominant positive
                    # peak where the a-trough should be), the signal polarity
                    # is inverted. Multiply by -1 to correct, and set the audit
                    # flag for Layer 4 and FHIR reporting. Only applied to DA
                    # protocols, where a large negative a-wave physiologically
                    # dominates the 0-30 ms post-stimulus window (see prior
                    # session notes for the full rationale). This step lives
                    # here, not inside extract_all_features, matching Chapter
                    # 5/9's separation of signal conditioning from feature
                    # extraction.
                    inverted_polarity_detected = False
                    _DA_PROTOCOLS = {'DA 0.01', 'DA 3.0', 'DA 10.0'}
                    if protocol_widget.value.strip().upper() in {p.upper() for p in _DA_PROTOCOLS}:
                        post_stim_signal = filtered_signal[flash_onset_sample:]
                        window_30ms_samples = min(int(30.0 * fs_hz / 1000), len(post_stim_signal))
                        if window_30ms_samples > 0:
                            window_sum = float(np.sum(post_stim_signal[:window_30ms_samples]))
                            if window_sum > 0:
                                filtered_signal = filtered_signal * -1.0
                                if op_signal is not None:
                                    op_signal = op_signal * -1.0
                                inverted_polarity_detected = True

                    # Extract all features
                    features = extract_all_features(
                        signal=filtered_signal,
                        fs_hz=fs_hz,
                        protocol=protocol_widget.value,
                        flash_onset_sample=flash_onset_sample,
                        flash_duration_ms=flash_duration_widget.value,
                        op_signal=op_signal,
                        noise_rms_uv=noise_rms_uv,
                        hardware_lowpass_hz=hardware_cutoff if hardware_cutoff is not None else 300.0,
                        hardware_highpass_hz=0.3
                    )
                    features['inverted_polarity_detected'] = inverted_polarity_detected

                    print(f"✓ Features extracted")
                    if 'a_amp_uv' in features and not np.isnan(features['a_amp_uv']):
                        print(f"  a-wave: {features['a_amp_uv']} µV @ {features['a_implicit_ms']} ms")
                        print(f"  b-wave: {features['b_amp_uv']} µV @ {features['b_implicit_ms']} ms")
                    if 'phnr_amp_uv' in features and not np.isnan(features['phnr_amp_uv']):
                        print(f"  PhNR: {features['phnr_amp_uv']} µV")
                    if 'op2_amp_uv' in features and not np.isnan(features.get('op2_amp_uv', np.nan)):
                        print(f"  OPs: OP2={features['op2_amp_uv']} µV, OP3={features.get('op3_amp_uv', 0)} µV, OP4={features.get('op4_amp_uv', 0)} µV")

                    # Calculate processing time
                    processing_time_ms = (time.perf_counter() - t_start) * 1000

                    # Generate full report
                    report_gen = ERGReportGenerator()
                    electrode_value = electrode_widget.value
                    if hasattr(electrode_value, 'value'):
                        electrode_value = electrode_value.value

                    full_report = report_gen.generate_full_report(
                        features=features,
                        audit_results=audit_result,
                        electrode_type=electrode_value,
                        protocol=protocol_widget.value,
                        age_years=age_group_widget.value,
                        filtered_signal=filtered_signal,
                        time_ms=time_ms,
                        filter_log=filter_log,
                        processing_time_ms=processing_time_ms
                    )

                    # Generate FHIR JSON (Cell 9)
                    fhir_gen = ERGFHIRGenerator()
                    fhir_observation = fhir_gen.generate_observation(
                        report_id=full_report['layer_4_technical_audit']['report_id'],
                        patient_id=patient_id_widget.value.strip() if patient_id_widget.value.strip() else "UNKNOWN",
                        traffic_light=full_report['layer_1_traffic_light'],
                        features=features,
                        audit_results=audit_result,
                        electrode_type=electrode_value,
                        protocol=protocol_widget.value
                    )
                    full_report['fhir_observation'] = fhir_observation

                    print("-" * 60)
                    print("\n" + "=" * 60)
                    print("FINAL REPORT")
                    print("=" * 60)

                    tl = full_report['layer_1_traffic_light']
                    print(f"\n{tl['color']} TRAFFIC LIGHT: {tl['signal']}")
                    print(f"   {tl['message']}")
                    print(f"\n📊 QUALITY GRADE: {audit_result['quality']['grade']}")
                    print(f"   {audit_result['quality']['description']}")
                    print(f"\n📋 RECOMMENDED ACTION: {full_report['layer_2_clinical_summary']['recommended_action']}")
                    print(f"\n⏱️ Processing time: {processing_time_ms:.0f} ms")
                    print("\n" + "=" * 60)
                    print("✅ Pipeline execution complete")
                    print("=" * 60)

                except Exception as e:
                    pipeline_error['exc'] = e
                    pipeline_error['tb']  = __import__('traceback').format_exc()

            pipeline_thread = __import__('threading').Thread(
                target=_run_pipeline_inner, daemon=True
            )
            pipeline_thread.start()
            pipeline_thread.join(timeout=PIPELINE_TIMEOUT_S)

            if pipeline_thread.is_alive():
                print(
                    f"❌ Pipeline timed out after {PIPELINE_TIMEOUT_S} s. "
                    f"The signal may be malformed, excessively long, or the "
                    f"sampling rate could not be determined. "
                    f"Check your CSV file and re-upload."
                )
            elif pipeline_error:
                print(f"❌ Error: {pipeline_error['exc']}")
                print(pipeline_error['tb'])

        finally:
            if os.path.exists(temp_path):
                os.remove(temp_path)

run_button.on_click(run_pipeline)
print("\n✓ UI Ready - Please upload an ERG CSV file and click 'RUN PIPELINE'")
