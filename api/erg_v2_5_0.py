def load_erg_csv(filepath: str) -> Tuple[np.ndarray, np.ndarray, float, Dict]:
    """Load ERG CSV file in standardized format (Time_ms, Amplitude_uV)"""
    df = pd.read_csv(filepath)

    time_col = None
    amp_col = None

    # Priority 1: exact canonical names (most real-world ERG export formats)
    CANONICAL_TIME = {'time_ms', 'time (ms)', 'time(ms)', 't_ms', 't (ms)'}
    CANONICAL_AMP  = {'amplitude_uv', 'amplitude (uv)', 'amplitude(uv)',
                      'amp_uv', 'signal_uv', 'amplitude (µv)', 'amplitude(µv)'}

    for col in df.columns:
        if col.strip().lower() in CANONICAL_TIME:
            time_col = col
        if col.strip().lower() in CANONICAL_AMP:
            amp_col = col

    # Priority 2: substring match fallback
    if time_col is None or amp_col is None:
        for col in df.columns:
            col_lower = col.lower()
            if time_col is None and ('time' in col_lower or col_lower.endswith('ms')):
                time_col = col
            if amp_col is None and ('amplitude' in col_lower
                                    or 'uv' in col_lower
                                    or 'µv' in col_lower
                                    or 'μv' in col_lower
                                    or 'signal' in col_lower):
                amp_col = col

    if time_col is None or amp_col is None:
        raise ValueError(
            f"Cannot identify time and amplitude columns.\n"
            f"Found columns: {df.columns.tolist()}\n"
            f"Expected a time column containing 'time' or ending in 'ms', "
            f"and an amplitude column containing 'amplitude', 'uv', or 'signal'.\n"
            f"Rename your columns to 'Time_ms' and 'Amplitude_uV' for guaranteed detection."
        )
    time_ms = df[time_col].values
    signal_uv = df[amp_col].values

    dt_ms = np.median(np.diff(time_ms))
    fs_hz = 1000.0 / dt_ms

    metadata = {
        'filename': filepath,
        'n_samples': len(signal_uv),
        'duration_ms': time_ms[-1] - time_ms[0],
        'fs_hz': fs_hz,
        'time_col': time_col,
        'amp_col': amp_col
    }

    return time_ms, signal_uv, fs_hz, metadata


def compute_kernel_samples(fs_hz: float, kernel_ms: float = 5.0) -> int:
    """Convert kernel duration (ms) to samples, ensuring odd number for median filter"""
    kernel = int(fs_hz * kernel_ms / 1000)
    if kernel % 2 == 0:
        kernel += 1
    return max(kernel, 3)


def validate_iscev_requirements(fs_hz: float, prestimulus_ms: float, total_duration_ms: float) -> Dict[str, Any]:
    """Validate ISCEV 2022 minimum requirements"""
    post_stimulus_ms = total_duration_ms - prestimulus_ms

    results = {
        'sampling_rate_ok': fs_hz >= CONFIG.ISCEV_MIN_SAMPLING_RATE_HZ,
        'sampling_rate_value': fs_hz,
        'sampling_rate_required': CONFIG.ISCEV_MIN_SAMPLING_RATE_HZ,
        'prestimulus_ok': prestimulus_ms >= CONFIG.ISCEV_MIN_PRESTIMULUS_MS,
        'prestimulus_value': prestimulus_ms,
        'prestimulus_required': CONFIG.ISCEV_MIN_PRESTIMULUS_MS,
        'post_stimulus_ok': post_stimulus_ms >= CONFIG.ISCEV_MIN_RECORDING_MS,
        'post_stimulus_value': post_stimulus_ms,
        'post_stimulus_required': CONFIG.ISCEV_MIN_RECORDING_MS,
        'overall_compliant': False
    }

    results['overall_compliant'] = results['sampling_rate_ok'] and results['prestimulus_ok'] and results['post_stimulus_ok']

    warnings_list = []
    if not results['sampling_rate_ok']:
        warnings_list.append(f"Sampling rate {fs_hz:.1f} Hz below ISCEV minimum {CONFIG.ISCEV_MIN_SAMPLING_RATE_HZ} Hz")
    if not results['prestimulus_ok']:
        warnings_list.append(f"Pre-stimulus baseline {prestimulus_ms:.1f} ms below ISCEV minimum {CONFIG.ISCEV_MIN_PRESTIMULUS_MS} ms")
    if not results['post_stimulus_ok']:
        warnings_list.append(f"Post-stimulus duration {post_stimulus_ms:.0f} ms below ISCEV minimum {CONFIG.ISCEV_MIN_RECORDING_MS} ms")

    results['warnings'] = warnings_list
    return results


def calculate_snr(signal_uv: np.ndarray, fs_hz: float, prestimulus_samples: int = 0,
                   a_search_start_ms: float = 5.0, a_search_end_ms: float = 40.0,
                   b_search_end_ms: float = 150.0, smooth_ms: float = 9.0) -> float:
    """
    Calculate SNR per Chapter 2 §2.2.1: SNR = signal amplitude / noise
    amplitude, where signal amplitude = (b-wave peak) - (a-wave trough)
    and noise amplitude = RMS of the pre-stimulus baseline. Returns the
    LINEAR ratio (not dB) -- the pipeline's Pass/Warning/Fail thresholds
    (§2.2.2/§2.3) are defined on the linear scale.

    The post-stimulus signal is smoothed with a short centered moving
    average (smooth_ms, the same technique extract_phnr uses for noise
    reduction) before the a-wave trough and b-wave peak are located.
    Without this smoothing, a raw max/min over a window is a biased
    estimator: noise inflates the apparent peak-to-trough amplitude, and
    the bias is worst exactly at the Pass/Warning boundary. A 9 ms
    window was chosen by simulation: it tracked the true linear SNR most
    closely across a range of noise levels (linear SNR 2-21), while
    wider windows under-estimate genuine peaks and narrower windows
    retain more of the noise bias.

    Args:
        signal_uv: Full signal in microvolts
        fs_hz: Sampling rate in Hz
        prestimulus_samples: Number of samples before flash onset
        a_search_start_ms / a_search_end_ms: post-stimulus window (ms)
            searched for the a-wave trough (most negative point)
        b_search_end_ms: upper bound (ms, post-stimulus) searched for
            the b-wave peak (most positive point after the a-wave trough)
        smooth_ms: centered moving-average window (ms) applied before
            peak/trough search

    Returns:
        Linear SNR ((b-wave peak - a-wave trough) / pre-stimulus RMS),
        or 0.0 if insufficient pre-stimulus samples or no valid a-wave/
        b-wave could be located
    """
    if prestimulus_samples < 5 or prestimulus_samples >= len(signal_uv):
        return 0.0

    # Guard: minimum pre-stimulus duration must be ≥ 2 cycles at fs_hz
    # to ensure RMS estimate is not dominated by a single transient
    min_samples_required = max(5, int(2.0 * fs_hz / 1000.0))
    if prestimulus_samples < min_samples_required:
        return 0.0

    # Noise RMS from pre-stimulus baseline
    noise_rms = float(np.sqrt(np.mean(signal_uv[:prestimulus_samples] ** 2)))
    if noise_rms <= 0:
        return 0.0

    post_signal = signal_uv[prestimulus_samples:]
    t_post_ms = np.arange(len(post_signal)) * 1000.0 / fs_hz

    # Smooth before peak/trough search to suppress noise-driven extrema
    from numpy.lib.stride_tricks import sliding_window_view
    win = max(1, int(round(smooth_ms * fs_hz / 1000.0)))
    if win % 2 == 0:
        win += 1
    if win > 1 and len(post_signal) >= win:
        pad = win // 2
        padded = np.pad(post_signal, (pad, pad), mode='edge')
        smoothed = np.mean(sliding_window_view(padded, win), axis=1)
    else:
        smoothed = post_signal

    # a-wave trough: most negative point in the early post-stimulus window
    a_mask = (t_post_ms >= a_search_start_ms) & (t_post_ms <= a_search_end_ms)
    if not a_mask.any():
        return 0.0
    a_indices = np.where(a_mask)[0]
    a_local_idx = int(np.argmin(smoothed[a_mask]))
    a_global_idx = int(a_indices[a_local_idx])
    a_trough_uv = float(smoothed[a_global_idx])

    # b-wave peak: most positive point after the a-wave trough
    b_mask = (t_post_ms > t_post_ms[a_global_idx]) & (t_post_ms <= b_search_end_ms)
    if not b_mask.any():
        return 0.0
    b_peak_uv = float(np.max(smoothed[b_mask]))

    signal_amp_uv = b_peak_uv - a_trough_uv
    if signal_amp_uv <= 0:
        return 0.0

    return float(signal_amp_uv / noise_rms)

