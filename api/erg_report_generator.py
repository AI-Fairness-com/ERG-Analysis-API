class ReportCanvas(pdfcanvas.Canvas):
    """Custom canvas drawing the letterhead header and footer on every page."""

    def __init__(self, *args, report_meta=None, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_states = []
        self.report_meta = report_meta or {}

    def showPage(self):
        self._draw_header()
        self._draw_footer()
        super().showPage()

    def save(self):
        if self._saved_states or self.getPageNumber() >= 1:
            pass
        super().save()

