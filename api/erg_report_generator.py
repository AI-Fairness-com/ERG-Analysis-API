def generate_clinical_report_pdf(output_path, full_report, waveform_data, meta=None):
    """
    Parameters
    ----------
    output_path : str — file path to write the PDF to
    full_report : dict — the existing ERGReportGenerator output
                  (layer_1_traffic_light, layer_2_clinical_summary, etc.)
    waveform_data : dict — {time_ms, amplitude_uv, op_signal, fs_hz, pre_stimulus_ms,
                             a_wave: {time_ms}, b_wave: {time_ms}}
                             (any 'amp_uv' key is ignored — y-position is always
                             sampled from the real trace, see _sample_at())
    meta : dict — optional override for patient_id, age_stratum, protocol, electrode,
                  recording_date, report_generated, report_id
    """
    meta = meta or {}
    layer1 = full_report.get("layer_1_traffic_light", full_report.get("traffic_light", {}))
    layer4 = full_report.get("layer_4_technical_audit", {})

    # The live API response (erg_server.py /api/v1/analyse) is flat:
    #   { traffic_light, features, z_scores, audit_results: {quality, snr, iscev_compliance}, ... }
    # full_report may be passed either as that flat dict, or as the nested
    # ERGReportGenerator output (layer_1_..., layer_2_..., etc). Support both.
    features = full_report.get("features", {})
    z_scores = full_report.get("z_scores",
                   full_report.get("layer_2_clinical_summary", {}).get("z_scores", {}))
    audit_results = full_report.get("audit_results", {})
    zscore_available = layer4.get("zscore_available", True)

    quality_raw = audit_results.get("quality", full_report.get("quality", {}))
    snr_raw     = audit_results.get("snr", {})
    iscev_raw   = audit_results.get("iscev_compliance", {})

    quality = {
        "grade": quality_raw.get("grade", "—"),
        "description": quality_raw.get("description", ""),
        "snr_db": snr_raw.get("db"),
        "snr_status": snr_raw.get("status", ""),
        "iscev_text": (
            "Compliant" if iscev_raw.get("overall_compliant") else
            "Non-compliant" if iscev_raw.get("overall_compliant") is False else "—"
        ),
    }

    fhir_obs = full_report.get("fhir_observation", {})
    report_id = layer4.get("report_id") or fhir_obs.get("id") or meta.get("report_id") or \
        f"ERG-{datetime.now().strftime('%Y%m%d-%H%M%S')}"

    fhir_patient_id = "UNKNOWN"
    if fhir_obs.get("subject", {}).get("reference"):
        fhir_patient_id = fhir_obs["subject"]["reference"].replace("Patient/", "")

    meta_full = {
        "patient_id": meta.get("patient_id") or fhir_patient_id,
        "age_stratum": meta.get("age_stratum", layer4.get("age_stratum", "—")),
        "protocol": meta.get("protocol", layer4.get("protocol", "—")),
        "electrode": meta.get("electrode", layer4.get("electrode_type", "—")),
        "recording_date": meta.get("recording_date", "—"),
        "report_generated": datetime.now().strftime("%d %B %Y, %H:%M"),
        "fs_hz": f"{waveform_data.get('fs_hz', 2000):.0f} Hz",
        "processing_ms": _fmt(
            full_report.get("processing_ms", layer4.get("processing_time_ms")),
            " ms", decimals=0),
        "report_id": report_id,
    }

    doc = BaseDocTemplate(
        output_path, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN,
        topMargin=MARGIN + 14 * mm, bottomMargin=MARGIN + 8 * mm,
        title=f"ERG Clinical Report — {meta_full['patient_id']}",
        author=ORG_NAME,
    )
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="main")

    def _make_canvas(*args, **kw):
        return ReportCanvas(*args, report_meta=meta_full, **kw)

    doc.addPageTemplates([PageTemplate(id="report", frames=[frame])])

    story = []

    # Title row
    story.append(Paragraph("Full-Field Electroretinogram — Clinical Decision Support Report",
                            _style("doctitle", fontSize=13, leading=17,
                                   fontName="Helvetica-Bold", textColor=INK)))
    story.append(Spacer(1, 5))
    story.append(Paragraph(
        "ISCEV 2022-compliant signal processing &nbsp;\u00b7&nbsp; "
        "Normative reference: Baker et al. (2025), N=407, DOI:10.1007/s10633-025-10009-2",
        _style("subtitle", fontSize=7.6, leading=10, textColor=SLATE)))
    story.append(Spacer(1, 3))

    story.append(build_patient_block(meta_full))
    story.append(Spacer(1, 3))

    story.extend(section_heading("Layer 1 — Traffic Light Result"))
    story.append(build_traffic_light_panel(layer1))

    story.extend(section_heading("Layer 2 — Clinical Parameter Summary"))
    story.append(build_metrics_table(features, z_scores, zscore_available))
    if features.get("phnr_polarity_atypical"):
        story.append(Spacer(1, 3))
        story.append(build_phnr_warning_block())

    story.extend(section_heading("Filtered ERG Waveform"))
    wf_drawing = build_waveform_drawing(
        waveform_data.get("time_ms", []),
        waveform_data.get("amplitude_uv", []),
        op_signal=waveform_data.get("op_signal"),
        fs_hz=waveform_data.get("fs_hz", 2000.0),
        pre_stimulus_ms=waveform_data.get("pre_stimulus_ms", 50.0),
        a_wave=waveform_data.get("a_wave"),
        b_wave=waveform_data.get("b_wave"),
        phnr_wave=waveform_data.get("phnr_wave"),
        ba_amplitude_uv=features.get("b_wave_amplitude_uv"),
        height_mm=42,
    )
    story.append(wf_drawing)
    legend = Table([[
        Paragraph('<font color="#0E7C86">\u2014\u2014</font> Filtered signal', S_BODY_SM),
        Paragraph('<font color="#C18A0B">\u2014 \u2014</font> OP band', S_BODY_SM),
        Paragraph('<font color="#B3261E">\u2014 \u2014</font> Flash onset', S_BODY_SM),
        Paragraph('Shaded region: pre-stimulus baseline', S_BODY_SM),
    ]], colWidths=[34 * mm, 34 * mm, 34 * mm, 72 * mm])
    legend.setStyle(TableStyle([("TOPPADDING", (0, 0), (-1, -1), 1),
                                 ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))
    story.append(legend)

    story.extend(section_heading("Layer 3 — Signal Quality & ISCEV Compliance"))
    story.append(build_quality_panel(quality))
    story.append(Spacer(1, 4))
    story.append(build_disclaimer_block())

    doc.build(story, canvasmaker=_make_canvas)
    return output_path


