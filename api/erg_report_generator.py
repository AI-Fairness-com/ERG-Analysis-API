def _fmt(val, unit="", decimals=1, dash="\u2014"):
    if val is None:
        return dash
    try:
        if isinstance(val, float) and (val != val):  # NaN check
            return dash
        return f"{val:.{decimals}f}{unit}"
    except (TypeError, ValueError):
        return str(val)


def _fmt_z(z):
    if z is None:
        return "N/A"
    try:
        if z != z:
            return "N/A"
        sign = "+" if z >= 0 else ""
        return f"Z = {sign}{z:.2f}"
    except (TypeError, ValueError):
        return "N/A"


