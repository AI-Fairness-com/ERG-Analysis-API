"""Independent check of the Baker et al. (2025) reference limits.

Reads the subject-level dataset released with the paper
(Mendeley Data, DOI 10.17632/kcptb9jrf5.1, ISCEV_ffERG_reference_data.xlsx)
and the project's normative file, then reports:

  1. Recalculated 2.5th and 97.5th percentiles for every limit set
     (rank method p(n + 1)) against the published values (T3-B).
  2. Age make-up of each reference group (T3-B, T3-C).
  3. How often healthy reference subjects receive AMBER or RED under
     Equation 10.2, by age, sex and electrode (T3-C).

Usage:
    python baker2025_reference_check.py "path/to/ISCEV ffERG reference data.xlsx"

In Colab, upload the spreadsheet and run the cell; the normative file is
read from GitHub when the script is not inside the repository.

The dataset is not stored in this repository; download it from the DOI above.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import fisher_exact

try:                                    # run as a file from the repo
    ROOT = Path(__file__).resolve().parent.parent
except NameError:                       # pasted into a Colab or Jupyter cell
    ROOT = Path.cwd()
NORM = ROOT / "data" / "samples" / "normative_data_baker2025.json"
NORM_URL = ("https://raw.githubusercontent.com/AI-Fairness-com/ERG-Analysis-API/"
            "main/data/samples/normative_data_baker2025.json")
DEFAULT_XLSX = "ISCEV ffERG reference data.xlsx"   # name of the Mendeley download

COLUMNS = [
    ("DA 0.01", "b_amp", "DA 0.01 b-wave amplitude (µV)"),
    ("DA 0.01", "b_imp", "DA 0.01 b-wave timing (ms)"),
    ("DA 3.0", "a_amp", "DA 3 a-wave amplitude (µV)"),
    ("DA 3.0", "a_imp", "DA 3 a-wave timing (ms)"),
    ("DA 3.0", "b_amp", "DA 3 b-wave amplitude (µV)"),
    ("DA 3.0", "b_imp", "DA 3 b-wave timing (ms)"),
    ("DA 10.0", "a_amp", "DA 10 a-wave amplitude (µV)"),
    ("DA 10.0", "a_imp", "DA 10 a-wave timing (ms)"),
    ("DA 10.0", "b_amp", "DA 10 b-wave amplitude (µV)"),
    ("DA 10.0", "b_imp", "DA 10 b-wave timing (ms)"),
    ("LA 30 Hz", "b_amp", "LA 30Hz peak amplitude (µV)"),
    ("LA 30 Hz", "b_imp", "LA 30Hz peak timing (ms)"),
    ("LA 3.0", "a_amp", "LA 3 a-wave amplitude (µV)"),
    ("LA 3.0", "a_imp", "LA 3 a-wave timing (ms)"),
    ("LA 3.0", "b_amp", "LA 3 b-wave amplitude (µV)"),
    ("LA 3.0", "b_imp", "LA 3 b-wave timing (ms)"),
]
GROUPS = ["le35", "36to59", "ge60"]


def age_group(age):
    """Baker et al. groups; ages are decimal years."""
    return np.where(age < 36, "le35", np.where(age < 60, "36to59", "ge60"))


def zone(x, e, amplitude):
    """Equation 10.2 (Chapter 10). Returns GREEN, AMBER, RED or ATYPICAL."""
    L, U = e["lower"], e["upper"]
    L_lo, U_hi = e["lower_ci"][0], e["upper_ci"][1]
    if L <= x <= U:
        return "GREEN"
    if amplitude:
        if x > U:
            return "ATYPICAL"
        return "AMBER" if x >= L_lo else "RED"
    if x < L:
        return "ATYPICAL"
    return "AMBER" if x <= U_hi else "RED"


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)


def main(xlsx):
    df = pd.read_excel(xlsx)
    if NORM.exists():
        norm = json.loads(NORM.read_text(encoding="utf-8"))
    else:                               # outside the repo: read it from GitHub
        import urllib.request
        with urllib.request.urlopen(NORM_URL) as r:
            norm = json.loads(r.read().decode("utf-8"))
    age = df["age (y)"]
    df["group"] = age_group(age)

    # 1. Recalculated limits
    print("1. Recalculated limits (rank method p(n+1))")
    match = total = 0
    for proto, par, col in COLUMNS:
        single = proto == "DA 10.0" and par == "b_imp"   # one set for all ages
        for g in (["le35"] if single else GROUPS):
            e = norm["limits"][proto][par][g]
            x = (df[col] if single else df.loc[df.group == g, col]).dropna().values
            lo = np.percentile(x, 2.5, method="weibull")
            hi = np.percentile(x, 97.5, method="weibull")
            ok = all(abs(r - p) <= max(0.51, 0.02 * abs(p))
                     for r, p in ((lo, e["lower"]), (hi, e["upper"])))
            match += ok
            total += 1
            print(f"  {proto:8} {par:6} {'all' if single else g:7} n={len(x):3} "
                  f"(published {e['n']})  published {e['lower']}-{e['upper']}  "
                  f"recalculated {lo:.1f}-{hi:.1f}  {'MATCH' if ok else 'CHECK'}")
    print(f"  {match}/{total} rows match (DA 10.0 b-wave timing is one set for all ages)\n")

    # 2. Age make-up
    band = np.where(age < 18, "under 18", np.where(age > 80, "over 80", "18 to 80"))
    print("2. Age make-up of the reference groups")
    print(pd.crosstab(df.group, band, margins=True), "\n")

    # 3. Flag rates in healthy reference subjects
    zones = pd.DataFrame(index=df.index)
    for proto, par, col in COLUMNS:
        amp = par.endswith("amp")
        zones[f"{proto} {par}"] = [
            zone(v, norm["limits"][proto][par][g], amp) if pd.notna(v) else None
            for v, g in zip(df[col], df.group)]
    flagged = zones.apply(lambda r: any(z in ("AMBER", "RED") for z in r if z), axis=1)
    df["subgroup"] = np.where(df.group == "le35",
                              np.where(age < 18, "le35 child (7-17)", "le35 adult (18-35)"),
                              df.group)
    print("3. Healthy subjects with at least one AMBER or RED")
    for by in ["subgroup", "sex", "active electrode"]:
        for k, idx in df.groupby(by).groups.items():
            n, f = len(idx), int(flagged[idx].sum())
            lo, hi = wilson(f, n)
            vals = zones.loc[idx].values.ravel()
            vals = vals[vals != None]  # noqa: E711
            per = np.isin(vals, ["AMBER", "RED"]).mean()
            aty = (vals == "ATYPICAL").mean()
            print(f"  {by:16} {k:24} n={n:3}  >=1 flag {100*f/n:5.1f}% "
                  f"(95% CI {100*lo:.1f}-{100*hi:.1f})  per parameter: "
                  f"AMBER/RED {100*per:.1f}%, ATYPICAL {100*aty:.1f}%")
    n, f = len(df), int(flagged.sum())
    print(f"  all {n} subjects: >=1 flag {100*f/n:.1f}%")

    def test(mask_a, mask_b, label):
        a, b = flagged[mask_a], flagged[mask_b]
        p = fisher_exact([[a.sum(), len(a) - a.sum()], [b.sum(), len(b) - b.sum()]])[1]
        print(f"  Fisher exact test, {label}: p = {p:.4f}")
    test(df.subgroup == "le35 adult (18-35)", df.subgroup == "le35 child (7-17)",
         "adults 18-35 vs children 7-17")
    test(df.sex == "M", df.sex == "F", "male vs female")
    test(df["active electrode"].str.startswith("Gold"),
         df["active electrode"].str.startswith("Silver"), "gold foil vs silver thread")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a.lower().endswith(".xlsx")]
    main(args[0] if args else DEFAULT_XLSX)