# 3. Protocol completeness factor
# ══════════════════════════════════════════════════════════════════════════════

def compute_protocol_completeness(present_protocols: list,
                                   passed_qc:         list) -> dict:
    """Compute the protocol completeness factor and Layer 1 flag.

    The completeness factor multiplies the classifier confidence score in the
    Layer 1 Traffic Light report. A PARTIAL flag triggers a dashed badge
    border and mandatory caveat text in the Layer 2 summary.

    Parameters
    ----------
    present_protocols : list of str
        Protocol names present in the recording (subset of ISCEV_PROTOCOLS).
    passed_qc : list of str
        Protocols that passed quality grading (subset of present_protocols).

    Returns
    -------
    dict with keys:
      completeness_factor   – float in [0, 1]
      n_protocols_passed    – int
      n_protocols_total     – int (always 5)
      layer1_flag           – 'COMPLETE' / 'PARTIAL' / 'SEVERELY_INCOMPLETE'
      missing_protocols     – list of missing protocol names

    Flag thresholds:
      COMPLETE            factor == 1.0  (all 5 protocols present and passed QC)
      PARTIAL             0.6 ≤ factor < 1.0  (3–4 protocols)
      SEVERELY_INCOMPLETE factor < 0.6   (≤ 2 protocols)
    """
    n_total   = len(ISCEV_PROTOCOLS)
    n_passed  = sum(p in passed_qc for p in ISCEV_PROTOCOLS)
    factor    = n_passed / n_total
    missing   = [p for p in ISCEV_PROTOCOLS if p not in present_protocols]

    if factor == 1.0:
        flag = 'COMPLETE'
    elif factor >= 0.6:
        flag = 'PARTIAL'
    else:
        flag = 'SEVERELY_INCOMPLETE'

    return {
        'completeness_factor': round(factor, 2),
        'n_protocols_passed' : n_passed,
        'n_protocols_total'  : n_total,
        'layer1_flag'        : flag,
        'missing_protocols'  : missing,
    }


