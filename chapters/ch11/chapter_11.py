# 5. Sensitivity analysis (TRIPOD-AI Item 10b)
# ══════════════════════════════════════════════════════════════════════════════

def sensitivity_analysis_missing_data(df_test:       pd.DataFrame,
                                       y_pred_proba:  np.ndarray,
                                       label_col:     str   = 'label',
                                       auc_threshold: float = TRIPOD_AUC_THRESHOLD
                                       ) -> dict:
    """Compare classifier AUC on complete-case vs full imputed test subset.

    Required by TRIPOD-AI Item 10b when any imputation is performed.
    A difference > auc_threshold triggers an 'INVESTIGATE' flag that must
    be documented in the Model Card (Chapter 17) as an imputation sensitivity
    finding.

    Parameters
    ----------
    df_test : pd.DataFrame
        Test-partition DataFrame with ``*_missing`` indicator columns present.
    y_pred_proba : np.ndarray, shape (n_test, n_classes)
        Pooled predicted probabilities (output of pool_predictions()).
    label_col : str
        Integer class label column name.
    auc_threshold : float
        Maximum acceptable |AUC_all − AUC_complete_case| (default 0.05).

    Returns
    -------
    dict with keys: auc_all_subjects, auc_complete_case, absolute_difference,
                    n_complete_case, n_total, tripod_ai_flag ('PASS'/'INVESTIGATE').
    """
    indicator_cols = [c for c in df_test.columns if c.endswith('_missing')]
    complete_mask  = (
        (df_test[indicator_cols] == 0).all(axis=1)
        if indicator_cols
        else pd.Series([True] * len(df_test), index=df_test.index)
    )

    y_true     = df_test[label_col].values
    y_true_cc  = y_true[complete_mask]
    y_proba_cc = y_pred_proba[complete_mask]

    all_cls = np.arange(y_pred_proba.shape[1])
    auc_all = roc_auc_score(y_true,    y_pred_proba,
                            multi_class='ovr', average='macro',
                            labels=all_cls)
    # Complete-case AUC requires all classes to be present
    cc_classes = np.unique(y_true_cc)
    if len(cc_classes) < y_pred_proba.shape[1]:
        auc_cc = float('nan')
        diff   = float('nan')
        print(f'  Note: complete-case subset contains only '
              f'{len(cc_classes)}/{ y_pred_proba.shape[1]} classes '
              f'-- CC AUC undefined; increase dataset size for reliable estimate.')
    else:
        auc_cc = roc_auc_score(y_true_cc, y_proba_cc,
                               multi_class='ovr', average='macro',
                               labels=all_cls)
        diff   = abs(auc_all - auc_cc)

    flag   = 'INVESTIGATE' if diff > auc_threshold else 'PASS'
    result = {
        'auc_all_subjects'   : round(auc_all, 4),
        'auc_complete_case'  : round(auc_cc,  4),
        'absolute_difference': round(diff,    4),
        'n_complete_case'    : int(complete_mask.sum()),
        'n_total'            : len(y_true),
        'tripod_ai_flag'     : flag,
    }
    print(f'Sensitivity analysis (TRIPOD-AI §10b): '
          f'AUC all={auc_all:.4f}  CC={auc_cc:.4f}  '
          f'Δ={diff:.4f}  [{flag}]')
    return result


