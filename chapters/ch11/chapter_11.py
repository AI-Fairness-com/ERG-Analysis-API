# 4. MICE multiple imputation  ⚠️  training pipeline only
# ══════════════════════════════════════════════════════════════════════════════

def mice_impute(X_train:       np.ndarray,
                X_val:         np.ndarray,
                X_test:        np.ndarray,
                n_imputations: int = 5,
                max_iter:      int = 10,
                random_state:  int = 42) -> list:
    """Apply MICE multiple imputation to train/val/test partitions.

    ⚠️  TRAINING PIPELINE ONLY.
    Do NOT use in the production API deployment path. See §11.4.2 and
    the module docstring for the rationale.

    The imputer is FIT on X_train only, then APPLIED (transform) to all three
    partitions. Fitting on val or test data would constitute data leakage.

    Uses BayesianRidge as the imputation estimator (scikit-learn default for
    IterativeImputer), which is robust to collinearity between ERG features.

    Parameters
    ----------
    X_train, X_val, X_test : np.ndarray
        Feature matrices from patient_level_split() with NaN for missing values.
    n_imputations : int
        Number of independent imputed datasets to generate (default 5).
        Increase to 10–20 for publication-quality uncertainty estimates.
    max_iter : int
        Maximum MICE rounds per imputation (default 10).
    random_state : int
        Base seed; each imputation uses random_state + i for reproducibility.

    Returns
    -------
    list of n_imputations tuples: [(X_train_imp, X_val_imp, X_test_imp), ...]
    Pool the classifier predictions across imputations with pool_predictions().
    """
    imputed_sets = []
    for seed in range(random_state, random_state + n_imputations):
        imp = IterativeImputer(
            estimator        = BayesianRidge(),
            max_iter         = max_iter,
            random_state     = seed,
            initial_strategy = 'mean',
            imputation_order = 'ascending',   # most-complete features first
        )
        imp.fit(X_train)   # FIT on training data only
        imputed_sets.append((
            imp.transform(X_train),
            imp.transform(X_val),
            imp.transform(X_test),
        ))
    print(f'MICE complete: {n_imputations} imputed datasets generated.')
    return imputed_sets


def pool_predictions(proba_list: list) -> np.ndarray:
    """Average predicted probabilities across imputed datasets (Rubin's rules).

    Parameters
    ----------
    proba_list : list of np.ndarray
        Each array has shape (n_samples, n_classes) — one per imputed dataset.

    Returns
    -------
    np.ndarray, shape (n_samples, n_classes)
        Mean probability across imputations.
    """
    return np.mean(np.stack(proba_list, axis=0), axis=0)


