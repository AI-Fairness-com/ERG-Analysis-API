# 2. Feature exclusion by missingness threshold
# ══════════════════════════════════════════════════════════════════════════════

def exclude_high_missingness_features(df_train:         pd.DataFrame,
                                       df_val:           pd.DataFrame,
                                       df_test:          pd.DataFrame,
                                       label_col:        str   = 'label',
                                       threshold_global: float = MISSINGNESS_THRESHOLD,
                                       threshold_class:  float = MISSINGNESS_THRESHOLD
                                       ) -> tuple:
    """Remove features with excessive missingness from all three partitions.

    Thresholds are computed on the training set only to prevent leakage.
    Both a global threshold (across all classes) and a per-class threshold
    are applied; a feature is excluded if it fails either check.

    Corresponding ``*_missing`` indicator columns are also removed when their
    parent feature is excluded.

    Parameters
    ----------
    df_train, df_val, df_test : pd.DataFrame
        Feature DataFrames from patient_level_split() (Chapter 10).
    label_col : str
        Name of the integer class label column.
    threshold_global : float
        Maximum permitted fraction of NaN values globally (default 0.40).
    threshold_class : float
        Maximum permitted fraction of NaN values within any single class
        (default 0.40).

    Returns
    -------
    tuple (df_train, df_val, df_test, excluded_features_list)
    """
    feature_cols = [c for c in df_train.columns
                    if c != label_col and '_missing' not in c]
    to_exclude   = set()

    # Global check
    global_miss     = df_train[feature_cols].isna().mean()
    global_excluded = global_miss[global_miss > threshold_global].index.tolist()
    to_exclude.update(global_excluded)
    if global_excluded:
        print(f'Globally excluded ({threshold_global:.0%} threshold): '
              f'{global_excluded}')

    # Per-class check
    for cls in df_train[label_col].unique():
        sub      = df_train[df_train[label_col] == cls][feature_cols]
        cls_miss = sub.isna().mean()
        cls_excl = cls_miss[cls_miss > threshold_class].index.tolist()
        if cls_excl:
            print(f'  Class {cls}: per-class excluded {cls_excl}')
            to_exclude.update(cls_excl)

    # Drop corresponding indicator columns too
    indicator_cols = [f'{f}_missing' for f in to_exclude
                      if f'{f}_missing' in df_train.columns]
    to_exclude.update(indicator_cols)
    drop_cols = list(to_exclude)

    df_train = df_train.drop(columns=drop_cols, errors='ignore')
    df_val   = df_val.drop(  columns=drop_cols, errors='ignore')
    df_test  = df_test.drop( columns=drop_cols, errors='ignore')

    print(f'Total features excluded: {len(drop_cols)}')
    return df_train, df_val, df_test, drop_cols


