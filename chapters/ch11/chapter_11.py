# 1. NaN indicator encoding
# ══════════════════════════════════════════════════════════════════════════════

def add_missing_indicators(df:         pd.DataFrame,
                            features:   list,
                            fill_value: Union[float, str] = 0.0) -> pd.DataFrame:
    """Add binary indicator columns for NaN values then fill NaNs.

    For each feature in the list:
      1. Creates a new column ``{feature}_missing`` (1 = was NaN, 0 = observed).
      2. Fills the NaN in the original column with fill_value.

    Parameters
    ----------
    df : pd.DataFrame
        Feature DataFrame (will not be modified in-place).
    features : list of str
        Column names to process.
    fill_value : float or 'mean'
        Replacement value for NaN entries.
        • 0.0  – use for MNAR-physiological amplitudes (zero = absent response).
        • 'mean' – use for MAR timing features (column training mean).

    Returns
    -------
    pd.DataFrame with original columns filled and new ``*_missing`` columns added.

    Notes
    -----
    apply ONLY to the training set first, then apply the same fill_value
    (including any computed mean) to val/test to avoid leakage.
    """
    df = df.copy()
    for feat in features:
        if feat not in df.columns:
            continue
        df[f'{feat}_missing'] = df[feat].isna().astype(int)
        fill = df[feat].mean(skipna=True) if fill_value == 'mean' else fill_value
        df[feat] = df[feat].fillna(fill)
    return df


