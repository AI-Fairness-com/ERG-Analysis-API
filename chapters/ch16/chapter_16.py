# 1. SAP pre-registration hash verification
# ══════════════════════════════════════════════════════════════════════════════

def verify_sap_hash(sap_path:        str  = 'docs/SAP_v1.0.pdf',
                    registered_hash: str  = None) -> dict:
    """Compute SHA-256 hash of the SAP document and compare to registered hash.

    Must be called at the start of every validation script to confirm that the
    Statistical Analysis Plan has not been modified after pre-registration.
    Any discrepancy must be declared as a deviation from the pre-registered plan
    before analysis proceeds.

    Parameters
    ----------
    sap_path : str
        Path to the SAP PDF file.
    registered_hash : str or None
        Expected SHA-256 hex digest from the OSF registration record.
        If None, the computed hash is printed for manual recording — no
        comparison is made and no exception is raised.

    Returns
    -------
    dict with keys: sap_path, computed_hash, registered_hash,
                    hash_match (bool or None), verified_at

    Raises
    ------
    ValueError if registered_hash is provided and does not match.
    """
    with open(sap_path, 'rb') as f:
        computed = hashlib.sha256(f.read()).hexdigest()

    match = (computed == registered_hash) if registered_hash else None
    result = {
        'sap_path'       : sap_path,
        'computed_hash'  : computed,
        'registered_hash': registered_hash,
        'hash_match'     : match,
        'verified_at'    : datetime.datetime.now().isoformat(),
    }

    if match is False:
        raise ValueError(
            'SAP document hash does not match the pre-registered hash. '
            'Do not proceed with analysis until the discrepancy is resolved. '
            'Any analysis performed with a modified SAP must be declared as '
            'a deviation from the pre-registered plan.')

    print(f"SAP hash verified: {'MATCH' if match else 'UNREGISTERED (record hash now)'}  "
          f"[{computed[:16]}...]")
    return result


