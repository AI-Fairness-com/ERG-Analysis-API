# 2. Five-fold stratified patient-level cross-validation
# ══════════════════════════════════════════════════════════════════════════════

def run_stratified_cv(df:           pd.DataFrame,
                      feature_cols: list,
                      label_col:    str = 'label',
                      patient_col:  str = 'patient_id',
                      n_splits:     int = N_FOLDS,
                      random_state: int = RANDOM_SEED) -> dict:
    """Five-fold stratified group cross-validation (patient-level splitting).

    Splitting is performed at the patient level (StratifiedGroupKFold):
    all recordings from one patient are assigned to exactly one fold,
    preventing patient-level data leakage between train and validation sets.

    Stratification ensures that the proportion of each disease class is
    preserved in every fold (critical for Complete CSNB, minimum N=60).

    Splitting is performed before STFT spectrogram extraction — the fold
    indices are saved and applied to the spectrogram dataset in the same order.

    Parameters
    ----------
    df : pd.DataFrame – one row per recording
    feature_cols : list of str – feature column names
    label_col : str – integer class label column
    patient_col : str – patient identifier column
    n_splits : int – number of folds (default 5)
    random_state : int

    Returns
    -------
    dict with keys: n_splits, random_state, fold_results (list), leakage_check
    Each fold_result has: fold, train_idx, val_idx, n_train, n_val.
    """
    rng         = np.random.default_rng(random_state)
    shuffle_idx = rng.permutation(len(df))
    df          = df.iloc[shuffle_idx].reset_index(drop=True)

    X      = df[feature_cols].values
    y      = df[label_col].values
    groups = df[patient_col].values

    sgkf         = StratifiedGroupKFold(n_splits=n_splits, shuffle=True,
                                        random_state=random_state)
    fold_results = []

    for fold_idx, (train_idx, val_idx) in enumerate(sgkf.split(X, y, groups)):
        y_tr  = y[train_idx]
        y_val = y[val_idx]

        # Strict patient-level leakage check
        tr_patients  = set(groups[train_idx])
        val_patients = set(groups[val_idx])
        assert len(tr_patients & val_patients) == 0, \
            f'DATA LEAKAGE: {len(tr_patients & val_patients)} patients in both sets.'

        # Stratification check: StratifiedGroupKFold enforces this
        # algorithmically. We warn (not assert) so small synthetic
        # datasets do not crash on legitimate sampling variation.
        for cls in np.unique(y):
            p_tr  = float((y_tr  == cls).mean())
            p_val = float((y_val == cls).mean())
            if abs(p_tr - p_val) > 0.10:
                warnings.warn(
                    f'Fold {fold_idx+1}: class {cls} proportion '
                    f'differs >10pp (train={p_tr:.3f}, val={p_val:.3f}).')

        cls_counts = {int(k): int(v)
                      for k, v in zip(*np.unique(y_val, return_counts=True))}
        print(f'  Fold {fold_idx+1}: train={len(y_tr)}, val={len(y_val)}, '
              f'classes={cls_counts}')
        fold_results.append({
            'fold'     : fold_idx + 1,
            'train_idx': train_idx,
            'val_idx'  : val_idx,
            'n_train'  : len(y_tr),
            'n_val'    : len(y_val),
        })

    return {
        'n_splits'    : n_splits,
        'random_state': random_state,
        'fold_results': fold_results,
        'leakage_check': 'PASS',
    }


