# 7. Integrated validation report
# ══════════════════════════════════════════════════════════════════════════════

def build_validation_report(internal_cv_results: dict,
                             external_auc:        dict,
                             brier_scores:        dict,
                             combat_params:       dict,
                             sap_hash:            str,
                             class_names:         list,
                             model_version:       str = 'v1.0.0') -> dict:
    """Assemble a machine-readable validation report for the Model Card (§16.7).

    Serialises to JSON and saves to outputs/validation/validation_report.json.
    Structure complies with TRIPOD-AI (Collins et al., 2024).

    Parameters
    ----------
    internal_cv_results : dict – from run_stratified_cv()
    external_auc : dict – from compute_per_class_auc() on external data
    brier_scores : dict – from compute_calibration_metrics()
    combat_params : dict – from apply_combat_harmonisation()
    sap_hash : str – SHA-256 hex digest from verify_sap_hash()
    class_names : list of str
    model_version : str

    Returns
    -------
    dict – full validation report structure
    """
    os.makedirs('outputs/validation', exist_ok=True)

    macro_ext = external_auc.get('macro_average', {}).get('auc')
    deployment_cleared = (macro_ext is not None
                          and macro_ext >= ALBASU_REF_AUC)

    report = {
        'model_version'          : model_version,
        'generated_at'           : datetime.datetime.now().isoformat(),
        'sap_hash_verified'      : sap_hash,
        'validation_standard'    : 'TRIPOD-AI (Collins et al., 2024)',
        'normative_reference'    : ('Robson et al. (2025), '
                                    'DOI:10.1007/s10633-025-10009-2'),
        'primary_outcome'        : ('Macro-AUC-ROC, Stage 2 six-class, '
                                    'external validation'),
        'stage1_binary': {
            'classifier'         : 'ViT Small, Hamming STFT',
            'minimum_sensitivity': STAGE1_MIN_SENS,
            'auc_internal_point' : '[computed from internal CV]',
            'auc_external_point' : '[computed from external validation]',
            'auc_external_95ci'  : '[DeLong method]',
            'deployment_cleared' : deployment_cleared,
        },
        'stage2_multiclass': {
            'classifier'              : 'ViT Small, Hamming STFT, 6-class',
            'macro_auc_internal'      : '[computed]',
            'macro_auc_external'      : macro_ext,
            'macro_auc_albasu_ref'    : ALBASU_REF_AUC,
            'per_class_auc'           : external_auc,
            'brier_scores'            : brier_scores,
            'calibration_method'      : 'Platt scaling (Chapter 14)',
            'minimum_class_sensitivity': STAGE2_MIN_SENS,
            'classes_below_threshold' : '[list of classes with sensitivity < 0.75]',
        },
        'batch_harmonisation': {
            'method'               : 'ComBat (neuroCombat)',
            'batch_variable'       : 'device_manufacturer',
            'biological_covariates': ['age_strata', 'sex'],
            'n_batches'            : combat_params.get('n_batches'),
            'params_path'          : 'outputs/validation/combat_params.pkl',
        },
        'fair_data': {
            'principles'     : 'Wilkinson et al. (2016)',
            'data_doi'       : '[OSF DOI on data release]',
            'model_weights_url': ('github.com/AI-Fairness-com/'
                                  'ERG-Analysis-API/releases'),
        },
        'tripod_ai_compliance' : 'docs/tripod_ai_compliance.csv',
        'performance_table_path': 'outputs/validation/performance_table.csv',
        'calibration_plot_path' : 'outputs/validation/calibration_plots.png',
    }

    report_path = 'outputs/validation/validation_report.json'
    with open(report_path, 'w') as f:
        json.dump(report, f, indent=2, default=str)
    print(f'Validation report saved: {report_path}')
    return report


