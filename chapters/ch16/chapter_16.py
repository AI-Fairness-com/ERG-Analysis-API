# 3. Centre-level leakage prevention
# ══════════════════════════════════════════════════════════════════════════════

def verify_centre_stratification(train_df:   pd.DataFrame,
                                  ext_df:     pd.DataFrame,
                                  centre_col: str = 'centre_id') -> dict:
    """Verify no external validation centre appears in the training set.

    External validation centres must be completely independent of the training
    set. Any overlap invalidates the external validation results and must be
    corrected before reporting.

    External centre IDs must follow the 'EXT_' prefix naming convention to
    prevent accidental training inclusion in future data collection rounds.

    Parameters
    ----------
    train_df, ext_df : pd.DataFrame – must contain centre_col
    centre_col : str

    Returns
    -------
    dict with keys: status, train_centres, ext_centres, overlap_detected

    Raises
    ------
    ValueError if any overlap is detected.
    """
    train_centres = set(train_df[centre_col].unique())
    ext_centres   = set(ext_df[centre_col].unique())
    overlap       = train_centres & ext_centres

    if overlap:
        raise ValueError(
            f'DATA LEAKAGE DETECTED: {len(overlap)} centre(s) appear in both '
            f'training and external validation sets: {overlap}. '
            f'Remove all recordings from these centres from the training set '
            f'before proceeding. External validation results computed with '
            f'this leakage are invalid and must not be reported.')

    non_prefixed = [c for c in ext_centres if not str(c).startswith('EXT_')]
    if non_prefixed:
        warnings.warn(
            f'External centres {non_prefixed} do not follow the EXT_ naming '
            f'convention. Add EXT_ prefix to prevent accidental training inclusion.')

    print('Centre stratification verified: PASS')
    print(f'  Training centres : {sorted(train_centres)}')
    print(f'  External centres : {sorted(ext_centres)}')
    print(f'  Overlap          : NONE')

    return {
        'status'          : 'PASS',
        'train_centres'   : sorted(train_centres),
        'ext_centres'     : sorted(ext_centres),
        'overlap_detected': False,
    }


