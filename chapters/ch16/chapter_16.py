# 5. Calibration curves and Brier Score
# ══════════════════════════════════════════════════════════════════════════════

def compute_calibration_metrics(y_true:      np.ndarray,
                                 y_proba_cal: np.ndarray,
                                 class_names: list,
                                 n_bins:      int   = CALIBRATION_N_BINS,
                                 output_dir:  str   = 'outputs/validation',
                                 brier_warn:  float = BRIER_WARN) -> dict:
    """Compute calibration curves and Brier Score per class (§16.5.3).

    Produces an 8-panel reliability diagram (7 classes + unused panel).
    CALIBRATION_WARNING is raised for any class with Brier Score > brier_warn.
    Classes exceeding the threshold must NOT appear in clinical probability
    outputs until Platt scaling is rerun on a larger calibration set.

    Parameters
    ----------
    y_true : np.ndarray, shape (n_samples,) – integer class labels
    y_proba_cal : np.ndarray, shape (n_samples, n_classes) – Platt-scaled probs
    class_names : list of str
    n_bins : int – number of probability bins for reliability diagram
    output_dir : str
    brier_warn : float – CALIBRATION_WARNING threshold (default 0.25)

    Returns
    -------
    dict with keys: per_class {class_name: brier_score}, macro (float)
    """
    os.makedirs(output_dir, exist_ok=True)
    n_classes = len(class_names)
    y_bin     = label_binarize(y_true, classes=list(range(n_classes)))

    fig, axes = plt.subplots(2, 4, figsize=(20, 10))
    axes_flat = axes.flatten()
    brier_scores = {}

    for c, name in enumerate(class_names):
        bs = float(brier_score_loss(y_bin[:, c], y_proba_cal[:, c]))
        brier_scores[name] = round(bs, 4)

        frac_pos, mean_pred = calibration_curve(
            y_bin[:, c], y_proba_cal[:, c],
            n_bins=n_bins, strategy='uniform')

        ax = axes_flat[c]
        ax.plot([0, 1], [0, 1], '--', color='#CCCCCC', linewidth=1)
        ax.plot(mean_pred, frac_pos, 'o-', color='#2E75B6',
                linewidth=2, markersize=6)
        ax.set_title(f'{name}\nBrier={bs:.3f}'
                     + (' ⚠' if bs > brier_warn else ''),
                     fontsize=9, fontweight='bold')
        ax.set_xlabel('Mean predicted probability', fontsize=8)
        ax.set_ylabel('Fraction of positives', fontsize=8)
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1)
        ax.grid(True, alpha=0.2)

        if bs > brier_warn:
            warnings.warn(
                f'CALIBRATION_WARNING: {name} Brier Score {bs:.4f} > '
                f'{brier_warn}. This class must NOT appear in clinical '
                f'probability outputs until Platt scaling is rerun on a '
                f'larger calibration set.',
                UserWarning,
            )

    axes_flat[-1].axis('off')   # 8th panel unused
    plt.suptitle('Per-Class Calibration Plots (Post Platt Scaling)',
                 fontsize=14, fontweight='bold')
    plt.tight_layout()
    plot_path = os.path.join(output_dir, 'calibration_plots.png')
    plt.savefig(plot_path, dpi=150, bbox_inches='tight')
    plt.close()

    macro_brier = round(float(np.mean(list(brier_scores.values()))), 4)
    print(f'Brier Scores: {brier_scores}')
    print(f'Macro Brier : {macro_brier}')
    print(f'Saved: {plot_path}')

    return {'per_class': brier_scores, 'macro': macro_brier}


