# 4. AUC-ROC with DeLong 95% CI
# ══════════════════════════════════════════════════════════════════════════════

def delong_auc_ci(y_true:  np.ndarray,
                  y_score: np.ndarray,
                  alpha:   float = DELONG_ALPHA) -> dict:
    """Compute AUC-ROC and 95% CI using the DeLong method.

    Implements DeLong, DeLong & Clarke-Pearson (1988).
    Uses structural component (placement value) decomposition for
    variance estimation — more accurate than bootstrap for AUC, and
    explicitly required by TRIPOD-AI guidelines.

    Parameters
    ----------
    y_true  : np.ndarray – binary labels (0/1) for one class (one-vs-rest)
    y_score : np.ndarray – predicted probability for the positive class
    alpha   : float – significance level (default 0.05 → 95% CI)

    Returns
    -------
    dict with keys: auc, ci_lower, ci_upper, se, n_pos, n_neg
    Returns None values with a message if insufficient cases.
    """
    pos = y_score[y_true == 1]
    neg = y_score[y_true == 0]
    n1, n0 = len(pos), len(neg)

    if n1 == 0 or n0 == 0:
        return {'auc': None, 'ci_lower': None, 'ci_upper': None,
                'se': None, 'message': 'Insufficient cases for AUC computation.'}

    # Placement values (structural components)
    pv_pos = np.array([np.mean(p > neg) + 0.5 * np.mean(p == neg)
                       for p in pos])
    pv_neg = np.array([np.mean(n < pos) + 0.5 * np.mean(n == pos)
                       for n in neg])

    auc    = float(np.mean(pv_pos))
    var_pv = (np.var(pv_pos, ddof=1) / n1) + (np.var(pv_neg, ddof=1) / n0)
    se     = float(np.sqrt(var_pv))
    z      = stats.norm.ppf(1 - alpha / 2)
    ci_lo  = max(0.0, auc - z * se)
    ci_hi  = min(1.0, auc + z * se)

    return {
        'auc'     : round(auc,   4),
        'ci_lower': round(ci_lo, 4),
        'ci_upper': round(ci_hi, 4),
        'se'      : round(se,    5),
        'n_pos'   : n1,
        'n_neg'   : n0,
    }


def compute_per_class_auc(y_true:      np.ndarray,
                           y_proba:     np.ndarray,
                           class_names: list) -> dict:
    """Compute one-vs-rest AUC with DeLong 95% CI for each class.

    Parameters
    ----------
    y_true : np.ndarray, shape (n_samples,) – integer class labels
    y_proba : np.ndarray, shape (n_samples, n_classes) – predicted probabilities
    class_names : list of str

    Returns
    -------
    dict {class_name: delong_result} plus 'macro_average' key
    """
    n_classes = len(class_names)
    y_bin     = label_binarize(y_true, classes=list(range(n_classes)))
    results   = {}

    for c, name in enumerate(class_names):
        results[name] = delong_auc_ci(y_bin[:, c], y_proba[:, c])
        r = results[name]
        if r['auc'] is not None:
            print(f'  {name:38s}: AUC={r["auc"]:.4f} '
                  f'[{r["ci_lower"]:.4f}–{r["ci_upper"]:.4f}]')
        else:
            print(f'  {name:38s}: {r["message"]}')

    valid_aucs = [v['auc'] for v in results.values() if v['auc'] is not None]
    macro_auc  = round(float(np.mean(valid_aucs)), 4) if valid_aucs else None
    print(f'  {"Macro-average":38s}: AUC={macro_auc:.4f}')
    results['macro_average'] = {'auc': macro_auc}
    return results


