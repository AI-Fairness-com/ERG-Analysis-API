    N_FEAT  = 28

    # ── Synthetic dataset ─────────────────────────────────────────────────
    class_p  = [0.28, 0.18, 0.15, 0.12, 0.10, 0.09, 0.08]
    y_all    = rng.choice(N_CLASS, size=N_REC, p=class_p)
    X_all    = rng.normal(0, 1, (N_REC, N_FEAT)).astype(np.float32)
    for c in range(N_CLASS):
        X_all[y_all == c, 0] += c * 1.5
    pat_ids  = np.repeat(np.arange(N_REC // 2), 2)[:N_REC]

    feat_names = [f'feat_{i:02d}' for i in range(N_FEAT)]
    df_all     = pd.DataFrame(X_all, columns=feat_names)
    df_all['label']      = y_all
    df_all['patient_id'] = pat_ids
    df_all['centre_id']  = np.where(pat_ids < N_REC // 4, 'SITE_A', 'SITE_B')

    # ── 1. SAP hash (synthetic) ───────────────────────────────────────────
    print('=== SAP hash verification ===')
    sap_dummy = '/tmp/dummy_sap.pdf'
    with open(sap_dummy, 'wb') as f:
        f.write(b'%PDF dummy SAP content for smoke test')
    sap_result = verify_sap_hash(sap_dummy, registered_hash=None)
    sap_hash   = sap_result['computed_hash']
    print(f'  Hash: {sap_hash[:24]}...\n')

    # ── 2. Stratified CV ──────────────────────────────────────────────────
    print('=== Five-fold stratified CV ===')
    cv_result = run_stratified_cv(df_all, feat_names, n_splits=N_FOLDS)
    print(f'  Leakage check: {cv_result["leakage_check"]}\n')

    # ── 3. Centre stratification ──────────────────────────────────────────
    print('=== Centre stratification ===')
    train_df = df_all[df_all.centre_id.isin(['SITE_A', 'SITE_B'])].copy()
    ext_df   = df_all.sample(80, random_state=42).copy()
    ext_df['centre_id'] = 'EXT_IRAN_001'
    verify_centre_stratification(train_df, ext_df)
    print()

    # ── 4. Per-class AUC with DeLong CI ───────────────────────────────────
    print('=== Per-class AUC (DeLong CI) ===')
    # Simulate calibrated probabilities: softmax of noisy class signal
    logits = rng.normal(0, 1, (N_REC, N_CLASS)).astype(float)
    for c in range(N_CLASS):
        logits[y_all == c, c] += 3.0
    e = np.exp(logits - logits.max(axis=1, keepdims=True))
    y_proba = e / e.sum(axis=1, keepdims=True)
    auc_results = compute_per_class_auc(y_all, y_proba, ALL_CLASSES)
    print()

    # ── 5. Calibration metrics ────────────────────────────────────────────
    print('=== Calibration metrics ===')
    os.makedirs('outputs/validation', exist_ok=True)
    cal_result = compute_calibration_metrics(
        y_all, y_proba, ALL_CLASSES, output_dir='outputs/validation')
    print()

    # ── 6. AUC forest plot ────────────────────────────────────────────────
    fig, ax = plt.subplots(figsize=(9, 5))
    cls_list = [n for n in ALL_CLASSES if auc_results.get(n, {}).get('auc')]
    aucs  = [auc_results[n]['auc']      for n in cls_list]
    cis_lo = [auc_results[n]['ci_lower'] for n in cls_list]
    cis_hi = [auc_results[n]['ci_upper'] for n in cls_list]
    yerr  = [np.array(aucs) - np.array(cis_lo),
             np.array(cis_hi) - np.array(aucs)]
    y_pos = np.arange(len(cls_list))
    ax.barh(y_pos, aucs, xerr=yerr, color='#2E75B6', ecolor='#1F4E79',
            capsize=4, alpha=0.85)
    ax.axvline(ALBASU_REF_AUC, color='red', ls='--', lw=1.2,
               label=f'Albasu et al. 2024 reference ({ALBASU_REF_AUC})')
    ax.axvline(0.5, color='gray', ls=':', lw=0.8, label='Chance (0.5)')
    ax.set_yticks(y_pos)
    ax.set_yticklabels([c[:30] for c in cls_list], fontsize=9)
    ax.set_xlabel('AUC-ROC  (95% CI, DeLong method)', fontsize=10)
    ax.set_title('Chapter 16 – Per-Class AUC Forest Plot\n'
                 '(synthetic data smoke test)', fontsize=11, fontweight='bold')
    ax.legend(fontsize=9)
    ax.set_xlim(0.4, 1.05)
    ax.grid(True, axis='x', alpha=0.25)
    plt.tight_layout()
    plt.savefig('ch16_fig1_auc_forest.png', dpi=150, bbox_inches='tight')
    print('Saved: ch16_fig1_auc_forest.png')

    # ── 7. Validation report ──────────────────────────────────────────────
    print('\n=== Build validation report ===')
    report = build_validation_report(
        internal_cv_results = cv_result,
        external_auc        = auc_results,
        brier_scores        = cal_result['per_class'],
        combat_params       = {'n_batches': 2},
        sap_hash            = sap_hash,
        class_names         = ALL_CLASSES,
        model_version       = 'v1.0.0',
    )
    print(f'  deployment_cleared: {report["stage1_binary"]["deployment_cleared"]}')
    print(f'  macro_auc_external: {report["stage2_multiclass"]["macro_auc_external"]}')

    plt.show()