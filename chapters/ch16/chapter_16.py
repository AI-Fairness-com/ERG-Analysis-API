# 6. ComBat batch effect harmonisation
# ══════════════════════════════════════════════════════════════════════════════

def apply_combat_harmonisation(feature_matrix: np.ndarray,
                                batch_labels:   np.ndarray,
                                covariates:     pd.DataFrame,
                                fit_params:     dict = None,
                                feature_names:  list = None) -> dict:
    """Apply ComBat harmonisation to remove device/site batch effects (§16.6.1).

    ⚠️  CRITICAL: fit_params=None fits ComBat on the provided data.
    Always fit on training data only. Pass the returned fit_params to
    all subsequent calls on validation and test data.

    Requires: pip install neuroCombat

    Parameters
    ----------
    feature_matrix : np.ndarray, shape (n_samples, n_features)
    batch_labels : np.ndarray, shape (n_samples,) – device/site label per sample
    covariates : pd.DataFrame – must contain 'age_strata' and 'sex' columns
                 (biological covariates that should NOT be removed)
    fit_params : dict or None
        None  → fit new ComBat model on the provided data (training only)
        dict  → apply pre-fitted parameters (validation / test / deployment)
    feature_names : list of str, optional – for logging

    Returns
    -------
    dict with keys: harmonised_features (np.ndarray), combat_params (dict),
                    n_batches (int), n_features (int)
    """
    try:
        from neuroCombat import neuroCombat
    except ImportError:
        raise ImportError(
            'neuroCombat is required for ComBat harmonisation. '
            'Install with: pip install neuroCombat')

    # neuroCombat expects (n_features, n_samples) — transpose
    data_T = feature_matrix.T
    covars_dict = {
        'age_strata': covariates['age_strata'].map(
            {'le35': 0, '36to59': 1, 'ge60': 2}).values,
        'sex':        covariates['sex'].map({'M': 0, 'F': 1}).values,
        'batch':      batch_labels,
    }
    covars_df = pd.DataFrame(covars_dict)

    if fit_params is None:
        result     = neuroCombat(
            dat             = data_T,
            covars          = covars_df,
            batch_col       = 'batch',
            continuous_cols = [],
            categorical_cols= ['age_strata', 'sex'],
        )
        harmonised = result['data'].T
        fit_params = result['estimates']
        print('ComBat fitted on training data.')
        print(f'  Batches identified : {np.unique(batch_labels).tolist()}')
        print(f'  Features harmonised: {data_T.shape[0]}')
    else:
        from neuroCombat import neuroCombat_harmonize
        harmonised = neuroCombat_harmonize(
            dat       = data_T,
            estimates = fit_params,
            batch_col = 'batch',
            covars    = covars_df,
        ).T
        print('ComBat applied using pre-fitted parameters.')

    return {
        'harmonised_features': harmonised,
        'combat_params'      : fit_params,
        'n_batches'          : int(len(np.unique(batch_labels))),
        'n_features'         : int(data_T.shape[0]),
    }


