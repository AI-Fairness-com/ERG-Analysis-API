# Version stamp generation and comparison (Section 17.3.3)
import datetime
import hashlib
import json


def generate_version_stamp(
        api_version: str,           # e.g. "1.0.0"
        model_weights_path: str,    # file that stores the model
        config_dict: dict,          # processing and calibration
        normative_version: str      # e.g. "Baker2025_v1"
) -> dict:
    """
    Build the version stamp stored in the Layer 4 audit record.

    A hash is a fixed-length fingerprint computed from the bytes of
    a file or text. Any change to the input changes the fingerprint.
    """

    def sha256_file(path):
        digest = hashlib.sha256()
        with open(path, "rb") as f:
            for block in iter(lambda: f.read(1024 * 1024), b""):
                digest.update(block)
        return digest.hexdigest()

    def sha256_dict(d):
        text = json.dumps(d, sort_keys=True)
        return hashlib.sha256(text.encode("utf-8")).hexdigest()

    return {
        "api_version": api_version,
        "model_weights_hash": sha256_file(model_weights_path),
        "config_hash": sha256_dict(config_dict),
        "normative_ref_version": normative_version,
        "generated_at": datetime.datetime.now(
            datetime.timezone.utc).isoformat(),
    }


def _parse_version(text):
    """Turn 'v1.2.3' or '1.2.3' into (1, 2, 3); None if malformed."""
    parts = str(text).lstrip("vV").split(".")
    if len(parts) != 3 or not all(p.isdigit() for p in parts):
        return None
    return tuple(int(p) for p in parts)


def compare_version_stamps(stamp_a: dict, stamp_b: dict) -> dict:
    """
    Compare the version stamps of two serial reports.

    Returns the flag, the changed fields, and a plain-language
    message.
    """
    fields = ["api_version", "model_weights_hash",
              "config_hash", "normative_ref_version"]
    changes = {f: (stamp_a.get(f), stamp_b.get(f))
               for f in fields if stamp_a.get(f) != stamp_b.get(f)}
    if not changes:
        return {"flag": "VERSION_IDENTICAL",
                "changed_fields": changes,
                "message": ("Both reports were generated by an "
                            "identical pipeline. Serial comparison "
                            "is valid.")}

    v_a = _parse_version(stamp_a.get("api_version"))
    v_b = _parse_version(stamp_b.get("api_version"))
    names = (f"{stamp_a.get('api_version')} and "
             f"{stamp_b.get('api_version')}")
    review = ("The reports could be read differently. A specialist "
              "should review the serial comparison (Section 17.3).")
    core = [f for f in ("model_weights_hash", "normative_ref_version")
            if f in changes]

    if v_a is None or v_b is None:
        flag = "VERSION_MAJOR_CHANGE"
        message = "A version string could not be read. " + review
    elif "api_version" not in changes:
        flag = "VERSION_MAJOR_CHANGE"
        message = ("The pipeline changed but the version number was "
                   "not updated, which must be corrected. " + review)
    elif core or v_a[0] != v_b[0]:
        flag = "VERSION_MAJOR_CHANGE"
        message = f"MAJOR change between versions {names}. " + review
        if v_a[0] == v_b[0]:
            message += (" The model weights or normative reference "
                        "changed, so a MAJOR version was required.")
    elif v_a[1] != v_b[1]:
        flag = "VERSION_MINOR_CHANGE"
        message = (f"MINOR change between versions {names}: new "
                   "functionality or recalibrated probabilities, "
                   "with no change to any Traffic Light assignment. "
                   "Serial comparison is valid.")
    else:
        flag = "VERSION_PATCH_CHANGE"
        message = (f"PATCH change between versions {names}: a fix "
                   "that does not affect clinical outputs. Serial "
                   "comparison is valid.")

    return {"flag": flag, "changed_fields": changes,
            "message": message}

# Shewhart rolling AUC control chart (Section 17.4.1)
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score


def baseline_from_bootstrap(
        y_true: np.ndarray,     # true class of each baseline patient
        y_prob: np.ndarray,     # predicted class probabilities
        n_boot: int = 2000,
        seed: int = 42) -> dict:
    """
    Baseline mean and standard deviation (sigma) of the macro-AUC.

    For the Stage 2 macro-AUC, pass the six disease classes only.
    The mean is the AUC of the baseline window (the first 90 days).
    Sigma is the standard deviation of n_boot bootstrap AUCs, each
    computed on a random resample of the baseline patients drawn
    with replacement. One row per patient is assumed.
    """
    rng = np.random.default_rng(seed)
    n = len(y_true)
    classes = np.unique(y_true)

    def macro_auc(idx):
        return roc_auc_score(y_true[idx], y_prob[idx],
                             multi_class="ovr", average="macro",
                             labels=classes)

    mu = macro_auc(np.arange(n))
    boots = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        if len(np.unique(y_true[idx])) < len(classes):
            continue            # a class is missing; AUC undefined
        boots.append(macro_auc(idx))
    return {"mu": mu, "sigma": float(np.std(boots, ddof=1)),
            "n_boot_used": len(boots)}


def shewhart_auc_monitor(
        auc_series: pd.Series,      # index = time, values = AUC
        baseline_mu: float,         # from baseline_from_bootstrap
        baseline_sigma: float,      # from baseline_from_bootstrap
        sigma_warning: float = 2.0,
        sigma_alarm: float = 3.0,
        x_label: str = "Deployment month",
        output_dir: str = "outputs/drift") -> dict:
    """
    Shewhart control chart for rolling AUC drift detection.

    A value between sigma_warning and sigma_alarm standard
    deviations from the baseline mean is a WARNING. A value beyond
    sigma_alarm is OUT_OF_CONTROL. Consecutive rolling windows share
    most of their reports, so an alert prompts an investigation and
    does not by itself prove drift.
    """
    os.makedirs(output_dir, exist_ok=True)
    mu, sigma = baseline_mu, baseline_sigma
    lcl_warn = mu - sigma_warning * sigma
    ucl_warn = mu + sigma_warning * sigma
    lcl_alarm = mu - sigma_alarm * sigma
    ucl_alarm = mu + sigma_alarm * sigma

    # Classify each time point
    flags = []
    for val in auc_series:
        if val < lcl_alarm or val > ucl_alarm:
            flags.append("OUT_OF_CONTROL")
        elif val < lcl_warn or val > ucl_warn:
            flags.append("WARNING")
        else:
            flags.append("IN_CONTROL")

    # Plot
    colors = {"IN_CONTROL": "#2E75B6", "WARNING": "#FFC000",
              "OUT_OF_CONTROL": "#C00000"}
    fig, ax = plt.subplots(figsize=(12, 5))
    ax.plot(auc_series.index, auc_series.values, "-",
            color="#2E75B6", linewidth=1.5, label="Rolling AUC")
    ax.axhline(mu, color="black", linewidth=1.5,
               label=f"Baseline mean ({mu:.3f})")
    for lcl, ucl, label, col in [
            (lcl_warn, ucl_warn, "2σ warning", "#FFC000"),
            (lcl_alarm, ucl_alarm, "3σ alarm", "#C00000")]:
        ax.axhline(lcl, color=col, linewidth=1.2, linestyle="--",
                   label=f"Lower {label} limit")
        ax.axhline(ucl, color=col, linewidth=1.2, linestyle="--",
                   label=f"Upper {label} limit")
    for x, y, flag in zip(auc_series.index, auc_series.values, flags):
        ax.scatter(x, y, color=colors[flag], zorder=5, s=50)
    ax.set_xlabel(x_label)
    ax.set_ylabel("90-day rolling macro-AUC")
    ax.set_title("Shewhart Rolling AUC Control Chart",
                 fontweight="bold")
    ax.legend(fontsize=8, loc="lower left")
    plt.tight_layout()
    plt.savefig(f"{output_dir}/shewhart_auc.png", dpi=220,
                bbox_inches="tight")
    plt.close()

    n_warning = flags.count("WARNING")
    n_alarm = flags.count("OUT_OF_CONTROL")
    status = flags[-1]          # status of the most recent value
    print(f"Shewhart monitor: {status} "
          f"(warnings={n_warning}, alarms={n_alarm})")
    return {
        "status": status,
        "baseline_mu": round(mu, 4),
        "baseline_sigma": round(sigma, 4),
        "lcl_warn": round(lcl_warn, 4),
        "ucl_warn": round(ucl_warn, 4),
        "lcl_alarm": round(lcl_alarm, 4),
        "ucl_alarm": round(ucl_alarm, 4),
        "flags": flags,
        "n_warnings": n_warning,
        "n_alarms": n_alarm,
    }

# Page-Hinkley test for a fall in the rolling AUC (Section 17.4.2)

import numpy as np


def page_hinkley_drift_test(
        auc_values,             # rolling AUC, one value per month
        baseline_mu: float,     # baseline mean AUC
        delta: float = 0.008,   # shortfall tolerated each month
        lam: float = 0.040) -> dict:   # alarm threshold (AUC units)
    """
    Page-Hinkley test for a sustained fall in the mean AUC.

    Returns the statistic S_t for every month and the 0-based index
    of the first alarm (None if there is no alarm). After an alarm
    investigation closes, call the function again on the newer
    values to restart the test.
    """
    ph, ph_min = 0.0, 0.0
    statistic, alarm_index = [], None
    for i, auc in enumerate(auc_values):
        ph += baseline_mu - auc - delta
        ph_min = min(ph_min, ph)
        statistic.append(ph - ph_min)
        if alarm_index is None and statistic[-1] > lam:
            alarm_index = i
    return {"statistic": np.array(statistic),
            "alarm_index": alarm_index,
            "alarm": alarm_index is not None}


# Illustrative demonstration with the 18 monthly values of Figure 17.2
