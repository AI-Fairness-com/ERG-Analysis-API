# 2. Shewhart rolling AUC control chart
# ══════════════════════════════════════════════════════════════════════════════

def shewhart_auc_monitor(auc_series:    pd.Series,
                          baseline_days: int   = BASELINE_DAYS,
                          sigma_warning: float = SIGMA_WARNING,
                          sigma_alarm:   float = SIGMA_ALARM,
                          output_dir:    str   = 'outputs/drift') -> dict:
    """Shewhart control chart for rolling AUC drift detection (§17.4.1).

    Baseline statistics (mean and SD) are estimated from the first
    baseline_days time points. Each subsequent AUC value is classified as:
      IN_CONTROL    – within baseline_mean ± sigma_warning × sigma
      WARNING       – beyond ±2σ but within ±3σ
      OUT_OF_CONTROL – beyond ±3σ

    Overall status: OUT_OF_CONTROL if any alarm; WARNING if ≥3 warnings;
    IN_CONTROL otherwise.

    Parameters
    ----------
    auc_series : pd.Series
        Index = date or deployment month, values = rolling macro-AUC.
    baseline_days : int
        Number of initial time points used to estimate baseline statistics.
    sigma_warning, sigma_alarm : float
        Warning and alarm sigma multipliers (default 2.0 and 3.0).
    output_dir : str

    Returns
    -------
    dict with keys: status, baseline_mu, baseline_sigma,
                    lcl_warn, ucl_warn, lcl_alarm, ucl_alarm, flags,
                    n_warnings, n_alarms
    """
    os.makedirs(output_dir, exist_ok=True)

    baseline  = auc_series.iloc[:baseline_days]
    mu        = float(baseline.mean())
    sigma     = float(baseline.std(ddof=1))

    lcl_warn  = mu - sigma_warning * sigma
    ucl_warn  = mu + sigma_warning * sigma
    lcl_alarm = mu - sigma_alarm   * sigma
    ucl_alarm = mu + sigma_alarm   * sigma

    flags = []
    for val in auc_series:
        if val < lcl_alarm or val > ucl_alarm:
            flags.append('OUT_OF_CONTROL')
        elif val < lcl_warn or val > ucl_warn:
            flags.append('WARNING')
        else:
            flags.append('IN_CONTROL')

    # ── Plot ──────────────────────────────────────────────────────────────
    colour_map = {'IN_CONTROL'   : '#2E75B6',
                  'WARNING'      : '#FFC000',
                  'OUT_OF_CONTROL': '#C00000'}

    fig, ax = plt.subplots(figsize=(12, 5))

    # Background bands
    ax.axhspan(lcl_alarm, lcl_warn,  alpha=0.08, color='#FFC000')
    ax.axhspan(ucl_warn,  ucl_alarm, alpha=0.08, color='#FFC000')
    ax.axhspan(-1,        lcl_alarm, alpha=0.08, color='#C00000')
    ax.axhspan(ucl_alarm, 2,         alpha=0.08, color='#C00000')
    ax.axhspan(lcl_warn,  ucl_warn,  alpha=0.06, color='#2E7D32')

    ax.plot(auc_series.index, auc_series.values, 'o-',
            color='#2E75B6', linewidth=1.5, markersize=5,
            label='Rolling AUC', zorder=3)
    ax.axhline(mu, color='black', linewidth=1.5, linestyle='-',
               label=f'Baseline mean ({mu:.3f})')

    for lcl, ucl, lbl, col in [
        (lcl_warn,  ucl_warn,  f'2σ Warning ({sigma_warning:.0f}σ)',  '#FFC000'),
        (lcl_alarm, ucl_alarm, f'3σ Alarm ({sigma_alarm:.0f}σ)',      '#C00000'),
    ]:
        ax.axhline(lcl, color=col, linewidth=1.2, linestyle='--',
                   label=f'LCL {lbl}')
        ax.axhline(ucl, color=col, linewidth=1.2, linestyle='--',
                   label=f'UCL {lbl}')

    for x, y, flag in zip(auc_series.index, auc_series.values, flags):
        ax.scatter(x, y, color=colour_map[flag], zorder=5, s=60)

    ax.set_xlabel('Deployment month', fontsize=11)
    ax.set_ylabel('90-day rolling macro-AUC', fontsize=11)
    ax.set_title('Shewhart Rolling AUC Control Chart', fontsize=12,
                 fontweight='bold')
    ax.legend(fontsize=8, loc='lower left')
    ax.set_ylim(max(0, lcl_alarm - 3 * sigma), min(1, ucl_alarm + 3 * sigma))
    plt.tight_layout()
    plot_path = os.path.join(output_dir, 'shewhart_auc.png')
    plt.savefig(plot_path, dpi=150, bbox_inches='tight')
    plt.close()
    print(f'Saved: {plot_path}')

    n_warning = flags.count('WARNING')
    n_alarm   = flags.count('OUT_OF_CONTROL')
    status    = ('OUT_OF_CONTROL' if n_alarm > 0
                 else 'WARNING' if n_warning > 2
                 else 'IN_CONTROL')
    print(f'Shewhart monitor: {status}  '
          f'(warnings={n_warning}, alarms={n_alarm})')

    return {
        'status'         : status,
        'baseline_mu'    : round(mu,        4),
        'baseline_sigma' : round(sigma,     4),
        'lcl_warn'       : round(lcl_warn,  4),
        'ucl_warn'       : round(ucl_warn,  4),
        'lcl_alarm'      : round(lcl_alarm, 4),
        'ucl_alarm'      : round(ucl_alarm, 4),
        'flags'          : flags,
        'n_warnings'     : n_warning,
        'n_alarms'       : n_alarm,
    }


