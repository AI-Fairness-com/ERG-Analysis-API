# 1. Version stamp generation and comparison
# ══════════════════════════════════════════════════════════════════════════════

def generate_version_stamp(api_version:        str,
                            model_weights_path: str,
                            config_dict:        dict,
                            normative_version:  str) -> dict:
    """Generate a version stamp for embedding in every API report.

    The stamp is stored in the Layer 4 audit record of every report. Any
    field change across two reports signals a version boundary and triggers
    a VERSION_MISMATCH warning in the Layer 3 Specialist Report header.

    Parameters
    ----------
    api_version : str
        Semantic version string, e.g. '1.0.0'.
    model_weights_path : str
        Path to the .pt model weights file. SHA-256 hash is computed.
    config_dict : dict
        Config-API reproducibility dictionary (Chapter 8 STFT_CONFIG et al.).
        SHA-256 hash of the JSON-serialised dict is stored.
    normative_version : str
        Normative dataset version identifier, e.g. 'Robson2025_v1'.

    Returns
    -------
    dict with keys: api_version, model_weights_hash, config_hash,
                    normative_ref_version, generated_at
    """
    def sha256_file(path: str) -> str:
        with open(path, 'rb') as f:
            return hashlib.sha256(f.read()).hexdigest()

    def sha256_dict(d: dict) -> str:
        return hashlib.sha256(
            json.dumps(d, sort_keys=True).encode()
        ).hexdigest()

    return {
        'api_version'          : api_version,
        'model_weights_hash'   : sha256_file(model_weights_path),
        'config_hash'          : sha256_dict(config_dict),
        'normative_ref_version': normative_version,
        'generated_at'         : datetime.datetime.now().isoformat(),
    }


def compare_version_stamps(stamp_a: dict, stamp_b: dict) -> dict:
    """Compare version stamps from two serial reports.

    Called automatically when a serial report comparison is requested
    (e.g. longitudinal monitoring in Chapter 18). Returns a clinical flag
    and a human-readable message for the Layer 3 Specialist Report header.

    Clinical flags:
      VERSION_IDENTICAL      – safe for direct serial comparison
      VERSION_MINOR_CHANGE   – comparison valid with caution
      VERSION_MAJOR_CHANGE   – serial comparison must be interpreted carefully;
                               normative reference or model may have changed
      VERSION_CONFIG_CHANGE  – processing configuration differs; specialist review

    Parameters
    ----------
    stamp_a, stamp_b : dict – outputs of generate_version_stamp()

    Returns
    -------
    dict with keys: flag, changed_fields, message
    """
    fields  = ['api_version', 'model_weights_hash',
               'config_hash', 'normative_ref_version']
    changes = {f: (stamp_a.get(f), stamp_b.get(f))
               for f in fields if stamp_a.get(f) != stamp_b.get(f)}

    if not changes:
        return {
            'flag'          : 'VERSION_IDENTICAL',
            'changed_fields': {},
            'message'       : ('Both reports generated by identical pipeline. '
                               'Serial comparison is valid.'),
        }

    if 'api_version' in changes:
        v_a, v_b     = changes['api_version']
        major_change = v_a.split('.')[0] != v_b.split('.')[0]
        flag    = 'VERSION_MAJOR_CHANGE' if major_change else 'VERSION_MINOR_CHANGE'
        prefix  = ('MAJOR version change: normative reference or model '
                   if major_change else 'Minor version change: ')
        message = (
            f'CAUTION: Reports generated by different API versions '
            f'({v_a} vs {v_b}). {prefix}'
            f'may have changed. Serial comparison should be interpreted '
            f'with caution. See Model Card §17.3 for details.')
    else:
        flag    = 'VERSION_CONFIG_CHANGE'
        message = ('Processing configuration changed between reports. '
                   'Serial comparison should be reviewed by a specialist.')

    return {'flag': flag, 'changed_fields': changes, 'message': message}


