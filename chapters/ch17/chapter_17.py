# 3. Page-Hinkley test for gradual drift
# ══════════════════════════════════════════════════════════════════════════════

def page_hinkley_drift_test(auc_series:    pd.Series,
                             baseline_days: int   = BASELINE_DAYS,
                             delta:         float = PH_DELTA,
                             lam:           float = PH_LAMBDA) -> dict:
    """Page-Hinkley test for gradual monotonic AUC drift (§17.4.2).

    Detects sustained downward trends too slow for Shewhart rules.
    Accumulates deviations of each AUC value from the baseline mean.
    An alarm is triggered when M_t − PH_t > lambda, where M_t is the
    running maximum of the cumulative sum.

    Parameters
    ----------
    auc_series : pd.Series
        Index = date or deployment month, values = rolling macro-AUC.
    baseline_days : int
        Initial points used to estimate baseline mean.
    delta : float
        Tolerated mean shift before detection in AUC units (default 0.01).
    lam : float
        Alarm threshold (default 50, calibrated to 90-day baseline).

    Returns
    -------
    dict with keys: alarm_triggered, alarm_index, alarm_date, ph_values,
                    m_values, delta, lambda_threshold
    """
    mu = float(auc_series.iloc[:baseline_days].mean())

    ph_vals = []
    ph      = 0.0
    m_max   = 0.0
    alarm_idx  = None
    alarm_date = None

    for i, (date, val) in enumerate(auc_series.items()):
        m_t = float(val) - mu - delta
        ph  = ph + m_t
        m_max = max(m_max, ph)
        ph_vals.append(ph)

        if m_max - ph > lam and alarm_idx is None:
            alarm_idx  = i
            alarm_date = date
            print(f'Page-Hinkley ALARM at index {i} (date={date}): '
                  f'M_t - PH_t = {m_max - ph:.2f} > lambda={lam}')

    triggered = alarm_idx is not None
    if not triggered:
        print(f'Page-Hinkley: no alarm triggered (max M_t-PH_t < {lam})')

    return {
        'alarm_triggered'  : triggered,
        'alarm_index'      : alarm_idx,
        'alarm_date'       : str(alarm_date) if alarm_date else None,
        'ph_values'        : ph_vals,
        'delta'            : delta,
        'lambda_threshold' : lam,
    }


