    ax2.plot(range(18), ph_vals, color='#2E75B6', lw=1.5, label='PH_t')
    ax2.plot(range(18), m_vals,  color='#C62828', lw=1.0,
             ls='--', label='M_t (running max)')
    ax2.fill_between(range(18),
                     np.array(m_vals) - PH_LAMBDA,
                     np.array(ph_vals),
                     where=np.array(m_vals) - np.array(ph_vals) > PH_LAMBDA,
                     alpha=0.25, color='#C62828', label='Alarm zone')
    ax2.axhline(0, color='gray', lw=0.7, ls=':')
    ax2.set_xlabel('Deployment month', fontsize=10)
    ax2.set_ylabel('Cumulative statistic', fontsize=10)
    ax2.set_title(f'Page-Hinkley Test\n'
                  f'(δ={PH_DELTA}, λ={PH_LAMBDA:.0f})',
                  fontsize=11, fontweight='bold')
    ax2.legend(fontsize=8)
    ax2.grid(True, alpha=0.2)

