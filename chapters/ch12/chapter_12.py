if __name__ == '__main__':

    # ── Synthetic dataset: 700 recordings, 7 classes ──────────────────────
    rng         = np.random.default_rng(RANDOM_SEED)
    N_REC       = 700
    N_FEAT      = 28
    class_probs = [0.28, 0.18, 0.15, 0.12, 0.10, 0.09, 0.08]
    y_all       = rng.choice(N_CLASS := N_CLASSES, size=N_REC, p=class_probs)
    X_all       = rng.normal(0, 1, (N_REC, N_FEAT)).astype(np.float32)

    # Add class-discriminating signal to first 8 features
    for c in range(N_CLASS):
        mask = y_all == c
        X_all[mask, 0] += c * 1.5     # b_amp (normalised)
        X_all[mask, 1] -= c * 0.8     # b_implicit_ms
        X_all[mask, 2] += (6 - c) * 0.6   # op_sum
        X_all[mask, 3] -= c * 0.4     # phnr_amp

    feat_names = (
        ['b_amp_norm', 'b_implicit_ms', 'op_sum_uv', 'phnr_amp_uv',
         'a_amp_uv', 'ba_ratio', 'op2_implicit_ms', 'bwave_mean']
        + [f'feat_{i:02d}' for i in range(N_FEAT - 8)]
    )

