# 1. Random Forest  (primary production classical model)
# ══════════════════════════════════════════════════════════════════════════════

def build_rf_pipeline(n_estimators:  int   = 250,
                      max_depth:     int   = None,
                      min_samples_split: int = 5,
                      class_weight:  str   = 'balanced',
                      random_state:  int   = RANDOM_SEED) -> Pipeline:
    """Build a Random Forest classification pipeline.

    Configuration (§12.2.1):
      n_estimators = 250  – enough trees for stable OOB estimate and importances
      criterion    = 'gini' (default)
      oob_score    = True  – free internal validation estimate
      class_weight = 'balanced' – compensates for class imbalance

    Best performance: Albasu et al. (2024) accuracy 70.83 %, AUC 0.722
    (Boxcar/Bartlett window, nperseg=128, noverlap=64).

    Parameters
    ----------
    n_estimators : int
    max_depth : int or None (None = grow until pure leaves)
    min_samples_split : int
    class_weight : str
    random_state : int

    Returns
    -------
    sklearn Pipeline (unfitted)
    """
    clf = RandomForestClassifier(
        n_estimators      = n_estimators,
        max_depth         = max_depth,
        min_samples_split = min_samples_split,
        criterion         = 'gini',
        oob_score         = True,
        class_weight      = class_weight,
        n_jobs            = -1,
        random_state      = random_state,
    )
    return Pipeline(_base_steps() + [('classifier', clf)])


