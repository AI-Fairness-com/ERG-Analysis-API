# ══════════════════════════════════════════════════════════════════════════════

def build_knn_pipeline(n_neighbors: int = 7,
                       weights:     str = 'distance',
                       metric:      str = 'euclidean') -> Pipeline:
    """Build a K-Nearest Neighbors classification pipeline.

    Configuration (§12.6):
      weights = 'distance'  – upweights closer neighbours; preferred for ERG
                              feature space with genuine density gradients
      metric  = 'euclidean' (default), 'manhattan', or 'minkowski'
      k tuned over odd values 3–19 (odd prevents tie-breaking ambiguity)

    Optimal k typically falls between 5 and 11 on normalised ERG feature
    matrices; k > 15 over-smooths minority class (Complete CSNB) boundaries.

    Returns
    -------
    sklearn Pipeline (unfitted)
    """
    clf = KNeighborsClassifier(
        n_neighbors = n_neighbors,
        weights     = weights,
        metric      = metric,
        n_jobs      = -1,
    )
    return Pipeline(_base_steps() + [('classifier', clf)])


