# ══════════════════════════════════════════════════════════════════════════════
# Hyperparameter tuning
# ══════════════════════════════════════════════════════════════════════════════

def tune_pipeline(pipeline:    Pipeline,
                  param_grid:  dict,
                  X_train:     np.ndarray,
                  y_train:     np.ndarray,
                  n_splits:    int = N_FOLDS,
                  random_state: int = RANDOM_SEED) -> GridSearchCV:
    """Run GridSearchCV with stratified k-fold CV on a classifier pipeline.

    Scoring metric is 'roc_auc_ovr' (macro one-vs-rest AUC) — the primary
    clinical performance metric. Optimising against AUC prevents the grid
    search from selecting configurations that maximise overall accuracy while
    ignoring minority classes.

    Parameters
    ----------
    pipeline : sklearn Pipeline (unfitted)
    param_grid : dict mapping pipeline parameter paths to value lists
    X_train, y_train : training partition arrays
    n_splits : int (default 5)
    random_state : int

    Returns
    -------
    Fitted GridSearchCV object. Access best model via .best_estimator_.
    """
    cv = StratifiedKFold(n_splits=n_splits, shuffle=True,
                         random_state=random_state)
    gs = GridSearchCV(
        pipeline,
        param_grid  = param_grid,
        cv          = cv,
        scoring     = 'roc_auc_ovr',
        n_jobs      = -1,
        refit       = True,
        verbose     = 1,
    )
    gs.fit(X_train, y_train)
    print(f'Best CV AUC  : {gs.best_score_:.4f}')
    print(f'Best params  : {gs.best_params_}')
    return gs


# ══════════════════════════════════════════════════════════════════════════════
# Evaluation
# ══════════════════════════════════════════════════════════════════════════════

def evaluate_classifier(pipeline:      Pipeline,
                         X_test:        np.ndarray,
                         y_test:        np.ndarray,
                         model_name:    str = 'Classifier',
                         feature_names: list = None,
                         plot:          bool = True) -> dict:
    """Apply the full evaluation metric suite to a fitted pipeline.

    Metrics (in the clinically mandated order — §12.7):
      1. Per-class precision, recall (sensitivity), F1  (classification_report)
      2. Macro-average F1
      3. Macro AUC-ROC (one-vs-rest)
      4. Calibration plot and Brier Score per class
      5. Overall accuracy (reported last)

    A Brier Score > BRIER_WARN (0.25) for any class triggers a calibration
    warning. Apply CalibratedClassifierCV before production deployment.

    Parameters
    ----------
    pipeline : fitted sklearn Pipeline
    X_test, y_test : test partition arrays
    model_name : str  label for figure titles and printout
    feature_names : list of str (optional, for RF importance plot)
    plot : bool  whether to generate figures

    Returns
    -------
    dict with keys: macro_auc, macro_f1, accuracy, brier_scores,
                    brier_warn, y_proba, report_str
    """
    y_pred  = pipeline.predict(X_test)
    y_proba = pipeline.predict_proba(X_test)
    n_cls   = y_proba.shape[1]
    lb      = LabelBinarizer().fit(np.arange(n_cls))
    y_bin   = lb.transform(y_test)

    # ── Per-class metrics ─────────────────────────────────────────────────
    report = classification_report(
        y_test, y_pred,
        target_names=CLASS_NAMES[:n_cls],
        digits=3, zero_division=0,
    )
    macro_f1  = f1_score(y_test, y_pred, average='macro', zero_division=0)
    macro_auc = roc_auc_score(y_bin, y_proba,
                               multi_class='ovr', average='macro')
    accuracy  = accuracy_score(y_test, y_pred)

    # ── Brier Score per class ─────────────────────────────────────────────
    brier_scores = {}
    brier_warn   = False
    for c in range(n_cls):
        bs = brier_score_loss(y_bin[:, c], y_proba[:, c])
        brier_scores[CLASS_NAMES[c]] = round(float(bs), 4)
        if bs > BRIER_WARN:
            brier_warn = True

    print(f'\n{"="*60}')
    print(f'  {model_name}')
    print(f'{"="*60}')
    print(report)
    print(f'Macro F1   : {macro_f1:.4f}')
    print(f'Macro AUC  : {macro_auc:.4f}')
    print(f'Brier scores (warn > {BRIER_WARN}):')
    for cls, bs in brier_scores.items():
        warn = '  ⚠️  CALIBRATE' if bs > BRIER_WARN else ''
        print(f'  {cls:<40s} {bs:.4f}{warn}')
    if brier_warn:
        print('  → Apply CalibratedClassifierCV before deployment.')
    print(f'Accuracy   : {accuracy:.4f}  (reported last)')

    if plot:
        fig, axes = plt.subplots(1, 2, figsize=(14, 5))

        # Calibration plot
        ax_cal = axes[0]
        ax_cal.plot([0, 1], [0, 1], 'k--', lw=0.8, label='Perfect calibration')
        colours = plt.cm.tab10(np.linspace(0, 1, n_cls))
        for c in range(n_cls):
            frac_pos, mean_pred = calibration_curve(
                y_bin[:, c], y_proba[:, c], n_bins=5, strategy='quantile')
            ax_cal.plot(mean_pred, frac_pos, 'o-', color=colours[c],
                        label=CLASS_NAMES[c][:20], markersize=4)
        ax_cal.set_xlabel('Mean predicted probability', fontsize=10)
        ax_cal.set_ylabel('Fraction of positives', fontsize=10)
        ax_cal.set_title(f'{model_name} – Calibration', fontsize=11, fontweight='bold')
        ax_cal.legend(fontsize=7, loc='upper left')
        ax_cal.grid(True, alpha=0.25)

        # Brier Score bar chart
        ax_br = axes[1]
        names = [n[:22] for n in brier_scores.keys()]
        vals  = list(brier_scores.values())
        colours_b = ['#C62828' if v > BRIER_WARN else '#2E75B6' for v in vals]
        ax_br.barh(range(len(vals)), vals, color=colours_b)
        ax_br.axvline(BRIER_WARN, color='red', ls='--', lw=1.2,
                      label=f'Warning threshold ({BRIER_WARN})')
        ax_br.set_yticks(range(len(vals)))
        ax_br.set_yticklabels(names, fontsize=8)
        ax_br.set_xlabel('Brier Score', fontsize=10)
        ax_br.set_title(f'{model_name} – Brier Scores', fontsize=11, fontweight='bold')
        ax_br.legend(fontsize=9)
        ax_br.grid(True, axis='x', alpha=0.25)

        plt.tight_layout()
        fname = f'ch12_{model_name.lower().replace(" ", "_")}_eval.png'
        plt.savefig(fname, dpi=150, bbox_inches='tight')
        print(f'Saved: {fname}')
        plt.show()

        # Random Forest feature importance plot
        clf = pipeline['classifier']
        if hasattr(clf, 'feature_importances_') and feature_names is not None:
            imps   = clf.feature_importances_
            ranked = sorted(zip(feature_names, imps),
                            key=lambda x: x[1], reverse=True)[:15]
            names_r, vals_r = zip(*ranked)
            fig2, ax2 = plt.subplots(figsize=(10, 6))
            ax2.barh(range(15), vals_r[::-1], color='#2E75B6')
            ax2.set_yticks(range(15))
            ax2.set_yticklabels([n[:50] for n in names_r[::-1]], fontsize=8)
            ax2.set_xlabel('Mean decrease in Gini impurity', fontsize=10)
            ax2.set_title(f'{model_name} – Top 15 Feature Importances\n'
                          f'(b_mean expected near top: Albasu et al., 2024)',
                          fontsize=11, fontweight='bold')
            ax2.grid(True, axis='x', alpha=0.25)
            plt.tight_layout()
            plt.savefig('ch12_rf_feature_importances.png', dpi=150,
                        bbox_inches='tight')
            print('Saved: ch12_rf_feature_importances.png')
            plt.show()

    return {
        'macro_auc'   : round(macro_auc, 4),
        'macro_f1'    : round(macro_f1,  4),
        'accuracy'    : round(accuracy,  4),
        'brier_scores': brier_scores,
        'brier_warn'  : brier_warn,
        'y_proba'     : y_proba,
        'report_str'  : report,
    }


def compare_classifiers(results: dict) -> pd.DataFrame:
    """Print a comparison table of AUC, F1, accuracy, and calibration status.

    Parameters
    ----------
    results : dict
        {model_name: evaluate_classifier() output dict}

    Returns
    -------
    pd.DataFrame summary table
    """
    rows = []
    for name, r in results.items():
        rows.append({
            'Model'       : name,
            'Macro AUC'   : r['macro_auc'],
            'Macro F1'    : r['macro_f1'],
            'Accuracy'    : r['accuracy'],
            'Calibration' : '⚠️ RECALIBRATE' if r['brier_warn'] else 'OK',
        })
    df = pd.DataFrame(rows).sort_values('Macro AUC', ascending=False)
    print('\n' + '='*70)
    print('  CLASSIFIER COMPARISON  (Table 12.1)')
    print('='*70)
    print(df.to_string(index=False))
    print('='*70)
    return df


# ══════════════════════════════════════════════════════════════════════════════
# Full pipeline construction and serialisation
# ══════════════════════════════════════════════════════════════════════════════

def build_full_pipeline(model,
                         X_train:       np.ndarray,
                         y_train:       np.ndarray,
                         feature_names: list,
                         config:        dict,
                         output_dir:    str = 'models') -> Pipeline:
    """Fit a classifier pipeline, serialise it, and record in config-API dict.

    The sklearn Pipeline enforces the correct fit/transform discipline:
    all preprocessing steps are fitted on X_train only. When predict() is
    called on X_val or X_test, each step runs in transform-only mode.

    Pipeline steps:
      imputer     – mean imputation (residual NaN after Chapter 11 encoding)
      scaler      – StandardScaler
      classifier  – the model passed as argument

    Parameters
    ----------
    model : unfitted sklearn estimator
    X_train, y_train : training partition arrays
    feature_names : list of str
    config : dict (config-API reproducibility dictionary)
    output_dir : str  directory for .pkl and .json artefacts

    Returns
    -------
    Fitted sklearn Pipeline
    """
    os.makedirs(output_dir, exist_ok=True)

    pipeline = Pipeline(_base_steps() + [('classifier', model)])
    pipeline.fit(X_train, y_train)

    model_version = config.get('model_version', 'v1_0')
    model_type    = type(model).__name__
    model_path    = os.path.join(output_dir, f'{model_version}_{model_type}.pkl')
    config_path   = os.path.join(output_dir, f'{model_version}_config.json')

    joblib.dump(pipeline, model_path)

    config['classical_ml'] = {
        'model_path'   : model_path,
        'model_type'   : model_type,
        'feature_names': list(feature_names),
        'class_names'  : CLASS_NAMES,
        'fitted_at'    : pd.Timestamp.now().isoformat(),
    }
    with open(config_path, 'w') as f:
        json.dump(config, f, indent=2)

    print(f'Pipeline serialised → {model_path}')
    print(f'Config recorded     → {config_path}')
    return pipeline


