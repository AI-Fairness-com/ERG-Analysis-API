def build_dt_pipeline(max_depth:         int = 10,
                      min_samples_split: int = 10,
                      class_weight:      str = 'balanced',
                      random_state:      int = RANDOM_SEED) -> Pipeline:
    """Build a Decision Tree classification pipeline.

    Configuration (§12.3.1):
      max_depth = 10  – performance plateau at moderate depth with 28 features
      min_samples_split = 10  – prevents leaf nodes defined by 1–2 recordings
      class_weight = 'balanced'

    The fitted tree can be exported to Graphviz for regulatory documentation:
        export_graphviz(pipeline['classifier'], out_file='tree.dot',
                        feature_names=feature_names,
                        class_names=CLASS_NAMES, filled=True)

    Performance: Albasu et al. (2024) accuracy 62.7–66.7 %, AUC 0.635–0.644.

    Returns
    -------
    sklearn Pipeline (unfitted)
    """
    clf = DecisionTreeClassifier(
        max_depth         = max_depth,
        min_samples_split = min_samples_split,
        criterion         = 'gini',
        class_weight      = class_weight,
        random_state      = random_state,
    )
    return Pipeline(_base_steps() + [('classifier', clf)])


