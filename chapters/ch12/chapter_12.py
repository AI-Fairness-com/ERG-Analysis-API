# 3. SVM with RBF kernel + Platt scaling
# ══════════════════════════════════════════════════════════════════════════════

def build_svm_pipeline(C:            float = 1.0,
                       gamma:        str   = 'scale',
                       kernel:       str   = 'rbf',
                       class_weight: str   = 'balanced',
                       random_state: int   = RANDOM_SEED) -> Pipeline:
    """Build an SVM classification pipeline with Platt-scaled probabilities.

    probability=True activates Platt scaling (sigmoid fit on internal CV),
    converting raw SVM decision values to calibrated probability outputs
    required for the Layer 2 clinical report. Calibration quality must be
    verified with a calibration plot and Brier Score (§12.7.3–4).

    Parameters
    ----------
    C : float
        Regularisation parameter. Smaller = wider margin, more regularisation.
    gamma : str or float
        RBF kernel width. 'scale' = 1/(n_features × X.var()).
    kernel : str
        'rbf' (recommended) or 'linear' (comparison condition).
    class_weight : str
    random_state : int

    Returns
    -------
    sklearn Pipeline (unfitted)
    """
    clf = SVC(
        C            = C,
        gamma        = gamma,
        kernel       = kernel,
        class_weight = class_weight,
        probability  = True,    # Platt scaling for calibrated probabilities
        random_state = random_state,
    )
    return Pipeline(_base_steps() + [('classifier', clf)])


