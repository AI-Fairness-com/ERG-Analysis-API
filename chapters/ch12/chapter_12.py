# 4. Logistic Regression (L1 / L2, signed coefficients)
# ══════════════════════════════════════════════════════════════════════════════

def build_lr_pipeline(penalty:      str   = 'l2',
                      C:            float = 1.0,
                      max_iter:     int   = 1000,
                      random_state: int   = RANDOM_SEED) -> Pipeline:
    """Build a Logistic Regression classification pipeline.

    Solver selection (§12.5.2):
      L2 penalty → lbfgs  (memory-efficient, multinomial CE natively)
      L1 penalty → liblinear  (only solver supporting L1 in sklearn for multi-class)

    Signed coefficients provide TRIPOD-AI Item 15 interpretability: a positive
    coefficient on b-wave implicit time increases log-odds for that disease class,
    aligning with the established clinical finding of b-wave delay in bipolar
    cell dysfunction.

    Parameters
    ----------
    penalty : str
        'l2' (Ridge) or 'l1' (Lasso).
    C : float
        Inverse regularisation strength. Smaller = stronger regularisation.
    max_iter : int
    random_state : int

    Returns
    -------
    sklearn Pipeline (unfitted)
    """
    solver       = 'liblinear' if penalty == 'l1' else 'lbfgs'
    multi_class  = 'ovr'       if penalty == 'l1' else 'multinomial'
    clf = LogisticRegression(
        penalty     = penalty,
        C           = C,
        solver      = solver,
        multi_class = multi_class,
        max_iter    = max_iter,
        random_state= random_state,
    )
    return Pipeline(_base_steps() + [('classifier', clf)])


LR_PARAM_GRID = {
    'classifier__C'      : [0.01, 0.1, 1.0, 10.0],
    'classifier__penalty': ['l2'],    # l1 needs separate pipeline with liblinear
}


