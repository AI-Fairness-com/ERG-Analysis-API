# Shared preprocessing steps
# ══════════════════════════════════════════════════════════════════════════════

def _base_steps() -> list:
    """Return the shared preprocessing step list for all pipelines.

    Steps (in order — must not be reordered):
      imputer  – mean imputation for any residual NaN after Chapter 11 encoding
      scaler   – StandardScaler (zero mean, unit variance)

    The Chapter 11 MissingIndicatorEncoder and SentinelReplacer are assumed
    to have been applied before feature matrix construction. In the full
    production pipeline (build_full_pipeline), they are included as explicit
    pipeline steps referencing src.missing_data.
    """
    return [
        ('imputer', SimpleImputer(strategy='mean')),
        ('scaler',  StandardScaler()),
    ]


