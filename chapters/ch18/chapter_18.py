# 3. LongitudinalPatientRecord class
# ══════════════════════════════════════════════════════════════════════════════

class LongitudinalPatientRecord:
    """Encapsulates a patient's complete ERG recording history.

    Provides all longitudinal analysis methods for the Layer 3 Specialist
    Report progression summary:
      - Version stamp compatibility check across prior visits
      - CoR-based visit-level change flags
      - Progression summary assembly

    Archive format: one JSON file per visit in
    {archive_dir}/{patient_id}/{visit_date}.json
    Each JSON is a Layer 4 audit record containing at minimum:
      version_stamp, date, and per-parameter ERG values.

    Parameters
    ----------
    patient_id : str
    archive_dir : str – root directory of patient archive JSON files
    cor_table : dict – {(parameter, electrode): {'cor': float, 'mdc95': float}}
                       (from Chapter 15 REFERENCE_COR_MDC)
    norm_module : object – NormativeReference instance (Chapter 15)
    """

    RATE_THRESHOLDS = RATE_THRESHOLDS

    def __init__(self,
                 patient_id:  str,
                 archive_dir: str,
                 cor_table:   dict,
                 norm_module):
        self.patient_id  = patient_id
        self.archive_dir = archive_dir
        self.cor_table   = cor_table
        self.norm_module = norm_module
        self.history     = self._load_archive()

    def _load_archive(self) -> pd.DataFrame:
        """Load all prior Layer 4 audit records for this patient.

        Returns an empty DataFrame if no archive exists yet.
        """
        records      = []
        archive_path = os.path.join(self.archive_dir, self.patient_id)
        if not os.path.exists(archive_path):
            return pd.DataFrame()
        for fname in sorted(os.listdir(archive_path)):
            if fname.endswith('.json'):
                with open(os.path.join(archive_path, fname)) as f:
                    records.append(json.load(f))
        return pd.DataFrame(records)

    def check_version_stamps(self, current_stamp: dict) -> dict:
        """Compare current stamp against all archive stamps (Chapter 17 §17.3.3).

        Returns the most severe version change across all prior visits.
        """
        from chapter_17_model_card_drift import compare_version_stamps

        if self.history.empty or 'version_stamp' not in self.history.columns:
            return {'flag': 'NO_PRIOR_REPORTS'}

        flags = []
        for _, row in self.history.iterrows():
            flags.append(compare_version_stamps(
                row['version_stamp'], current_stamp))

        worst = (
            'VERSION_MAJOR_CHANGE' if any(
                f['flag'] == 'VERSION_MAJOR_CHANGE' for f in flags)
            else 'VERSION_MINOR_CHANGE' if any(
                f['flag'] == 'VERSION_MINOR_CHANGE' for f in flags)
            else 'VERSION_IDENTICAL'
        )
        return {'overall_flag': worst, 'per_visit_flags': flags}

    def apply_cor_flags(self,
                         current_values:  dict,
                         electrode:       str,
                         protocol:        str,
                         disease_class:   str,
                         baseline_values: dict = None,
                         hcq_patient:     bool = False,
                         gene_therapy:    bool = False) -> dict:
        """Apply CoR-based visit-level flags for all parameters.

        Compares each current parameter value to the most recent prior visit
        using the Coefficient of Repeatability from cor_table.

        Parameters
        ----------
        current_values : dict {param_name: float}
        electrode, protocol, disease_class : str
        baseline_values : dict, optional – first visit values for % decline calc
        hcq_patient : bool – hydroxychloroquine patient (lower thresholds)
        gene_therapy : bool – post gene therapy (improvement expected)

        Returns
        -------
        dict {param_name: change_result} or {'status': 'NO_PRIOR_VISITS'}
        """
        if self.history.empty:
            return {'status': 'NO_PRIOR_VISITS'}

        prev   = self.history.iloc[-1]
        flags  = {}

        for param, curr_val in current_values.items():
            prev_val = prev.get(param)
            if prev_val is None:
                flags[param] = {'status': 'NO_PRIOR_VALUE'}
                continue

            key = (param, electrode)
            if key not in self.cor_table:
                flags[param] = {'status': 'NO_COR_DATA'}
                continue

            cor   = self.cor_table[key]['cor']
            mdc95 = self.cor_table[key]['mdc95']
            delta = float(curr_val) - float(prev_val)
            abs_d = abs(delta)

            if abs_d >= cor:
                zone = ('SIGNIFICANT_PROGRESSION' if delta < 0
                        else 'SIGNIFICANT_IMPROVEMENT')
            elif abs_d >= mdc95:
                zone = 'BORDERLINE_CHANGE'
            else:
                zone = 'NO_CHANGE'

            flags[param] = {
                'delta'       : round(delta, 3),
                'change_zone' : zone,
                'cor'         : cor,
                'mdc95'       : mdc95,
            }

        return flags

    def generate_progression_summary(self,
                                      current_values: dict,
                                      current_stamp:  dict,
                                      electrode:      str,
                                      protocol:       str,
                                      disease_class:  str,
                                      **kwargs) -> dict:
        """Assemble the complete Layer 3 progression summary.

        Returns a structured dict for embedding in the Specialist Report.
        Components (in fixed order per §18.5.4):
          1. Version stamp comparison
          2. Per-parameter CoR visit-level flags
          3. N prior visits in archive
          4. Patient identifier
        """
        return {
            'version_check'    : self.check_version_stamps(current_stamp),
            'visit_level_flags': self.apply_cor_flags(
                current_values, electrode, protocol, disease_class, **kwargs),
            'n_prior_visits'   : len(self.history),
            'patient_id'       : self.patient_id,
        }


