# 2. Longitudinal Bland-Altman serial difference plot
# ══════════════════════════════════════════════════════════════════════════════

def plot_longitudinal_bland_altman(visit_df:   pd.DataFrame,
                                    cor:        float,
                                    param_name: str,
                                    patient_id: str,
                                    output_dir: str = 'outputs/longitudinal'
                                    ) -> dict:
    """Generate a Bland-Altman difference plot for a serial ERG record (§18.5.3).

    Plots consecutive-visit differences against the visit pair mean.
    Differences exceeding the Coefficient of Repeatability (CoR) are flagged
    in red. A trend line through the differences detects a systematic
    visit-to-visit directional change.

    Parameters
    ----------
    visit_df : pd.DataFrame
        Sorted by date. Required columns: date, param_value.
    cor : float
        Coefficient of Repeatability for this parameter and electrode type
        (from Chapter 15 REFERENCE_COR_MDC table).
    param_name : str
        Parameter label for figure title and filename.
    patient_id : str
    output_dir : str

    Returns
    -------
    dict with keys: differences, means, cor, trend_slope, trend_p,
                    trend_flag, n_cor_crossings, plot_path
    """
    os.makedirs(output_dir, exist_ok=True)

    vals  = visit_df['param_value'].values
    dates = visit_df['date'].values
    diffs = np.diff(vals)                       # visit(k+1) − visit(k)
    means = (vals[:-1] + vals[1:]) / 2
    visit_labels = [
        f'{str(dates[i])[:10]}→{str(dates[i+1])[:10]}'
        for i in range(len(diffs))
    ]

    # Trend line through differences
    x_idx = np.arange(len(diffs))
    slope, intercept, r, p, se = stats.linregress(x_idx, diffs)
    trend_flag = 'DECLINING_TREND' if slope < 0 and p < 0.05 else 'NO_TREND'

    fig, ax = plt.subplots(figsize=(10, 6))
    for i, (m, d, lbl) in enumerate(zip(means, diffs, visit_labels)):
        colour = '#C00000' if abs(d) > cor else '#2E75B6'
        ax.scatter(m, d, color=colour, s=80, zorder=5)
        ax.annotate(lbl, (m, d), textcoords='offset points',
                    xytext=(6, 4), fontsize=7, color=colour)

    ax.axhline(0,    color='black',   linewidth=1.0, linestyle='-')
    ax.axhline( cor, color='#C00000', linewidth=1.2, linestyle='--',
                label=f'+CoR = +{cor:.1f}')
    ax.axhline(-cor, color='#C00000', linewidth=1.2, linestyle='--',
                label=f'−CoR = −{cor:.1f}')
    ax.plot(means, intercept + slope * x_idx, color='#FFC000',
            linewidth=1.5, linestyle='-.',
            label=f'Trend: slope={slope:.2f}/visit (p={p:.3f})')

    ax.set_xlabel(f'Mean of consecutive visits  ({param_name})', fontsize=10)
    ax.set_ylabel('Difference (next − current visit)', fontsize=10)
    ax.set_title(f'Longitudinal Bland-Altman  │  {patient_id}  │  {param_name}',
                 fontsize=11, fontweight='bold')
    ax.legend(fontsize=9)
    plt.tight_layout()

    safe_param = param_name.replace('/', '_').replace(' ', '_')
    path = os.path.join(output_dir,
                        f'bland_altman_longitudinal_{patient_id}_{safe_param}.png')
    plt.savefig(path, dpi=150, bbox_inches='tight')
    plt.close()

    return {
        'differences'   : diffs.tolist(),
        'means'         : means.tolist(),
        'cor'           : cor,
        'trend_slope'   : round(float(slope), 4),
        'trend_p'       : round(float(p),     4),
        'trend_flag'    : trend_flag,
        'n_cor_crossings': int(np.sum(np.abs(diffs) > cor)),
        'plot_path'     : path,
    }


