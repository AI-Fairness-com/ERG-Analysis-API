# 1. Linear mixed-effects model
# ══════════════════════════════════════════════════════════════════════════════

def fit_longitudinal_lme(df:           pd.DataFrame,
                          param_name:   str,
                          disease_class: str,
                          min_visits:   int   = LME_MIN_VISITS,
                          min_span_yrs: float = LME_MIN_SPAN_YRS,
                          output_dir:   str   = 'outputs/longitudinal') -> dict:
    """Fit a linear mixed-effects model to longitudinal ERG data.

    Estimates a population-level slope (fixed effect) and individual
    trajectories (random slopes + intercepts) for each eligible patient.
    Used to determine the population rate of decline for a given disease
    class and to flag individual patients whose rate exceeds the clinical
    threshold in RATE_THRESHOLDS.

    Parameters
    ----------
    df : pd.DataFrame
        One row per recording. Required columns:
          patient_id  – string patient identifier
          time_years  – years from baseline (float; baseline = 0.0)
          param_value – ERG parameter value in clinical units (µV or ms)
    param_name : str
        ERG parameter name for labelling (e.g. 'b_amp_uv').
    disease_class : str
        Disease class label (used for rate threshold lookup).
    min_visits : int
        Minimum number of visits per patient for LME eligibility (default 3).
    min_span_yrs : float
        Minimum time span (years) between first and last visit (default 1.0).
    output_dir : str

    Returns
    -------
    dict with keys: param_name, disease_class, pop_slope, pop_intercept,
                    pop_slope_ci95, patient_slopes, s_w_per_patient,
                    n_patients, n_recordings, model_aic, model_summary

    Raises
    ------
    ValueError if no patients meet eligibility criteria.
    """
    os.makedirs(output_dir, exist_ok=True)

    # Eligibility filter
    eligible = []
    for pid, grp in df.groupby('patient_id'):
        grp  = grp.dropna(subset=['param_value', 'time_years']).sort_values('time_years')
        span = grp['time_years'].max() - grp['time_years'].min()
        if len(grp) >= min_visits and span >= min_span_yrs:
            eligible.append(grp)
        else:
            warnings.warn(
                f'Patient {pid} excluded: {len(grp)} visits, span {span:.1f}y.')

    if not eligible:
        raise ValueError('No patients meet the eligibility criteria.')

    df_elig = pd.concat(eligible, ignore_index=True)

    # Fit mixed-effects model: random slope + intercept per patient
    model  = smf.mixedlm('param_value ~ time_years',
                          df_elig,
                          groups=df_elig['patient_id'],
                          re_formula='~time_years')
    result = model.fit(method='lbfgs', warn_convergence=False)

    pop_intercept = float(result.fe_params['Intercept'])
    pop_slope     = float(result.fe_params['time_years'])

    # Per-patient random effects → individual slopes
    patient_slopes = {}
    for pid in df_elig['patient_id'].unique():
        re  = result.random_effects.get(pid, {})
        b0  = float(re.get('Group', re.get('Intercept', 0)))
        b1  = float(re.get('time_years', 0))
        patient_slopes[pid] = {
            'individual_slope' : round(pop_slope + b1, 4),
            'random_intercept' : round(b0, 4),
            'random_slope'     : round(b1, 4),
        }

    # Residual within-subject SD (per patient)
    df_elig       = df_elig.copy()
    df_elig['fitted'] = result.fittedvalues
    df_elig['resid']  = df_elig['param_value'] - df_elig['fitted']
    s_w_individual    = df_elig.groupby('patient_id')['resid'].std(ddof=1).to_dict()

    print(f'LME fit complete: {param_name} │ {disease_class}')
    print(f'  Population slope     : {pop_slope:.3f} units/year')
    print(f'  Population intercept : {pop_intercept:.3f}')
    print(f'  N eligible patients  : {df_elig["patient_id"].nunique()}')
    print(f'  N recordings used    : {len(df_elig)}')

    return {
        'param_name'    : param_name,
        'disease_class' : disease_class,
        'pop_slope'     : round(pop_slope,     4),
        'pop_intercept' : round(pop_intercept, 4),
        'pop_slope_ci95': [float(v) for v in np.round(
            result.conf_int().loc['time_years'].values, 4)],
        'patient_slopes': patient_slopes,
        's_w_per_patient': {k: round(v, 4)
                             for k, v in s_w_individual.items()},
        'n_patients'    : df_elig['patient_id'].nunique(),
        'n_recordings'  : len(df_elig),
        'model_aic'     : round(result.aic, 2),
        'model_summary' : result.summary().as_text(),
    }


def predict_next_visit(lme_result:   dict,
                        patient_id:   str,
                        t_future_yrs: float,
                        sigma_e:      float) -> dict:
    """Generate a 95% prediction interval for a patient at a future time point.

    Uses the patient's individual slope from the LME random effects to project
    their trajectory to t_future_yrs from baseline.

    Parameters
    ----------
    lme_result : dict – output of fit_longitudinal_lme()
    patient_id : str
    t_future_yrs : float – years from baseline at the future visit
    sigma_e : float
        Residual standard deviation from the LME model (measurement noise).
        Use the patient-specific s_w value from lme_result['s_w_per_patient']
        or the pooled residual SD from the model if unavailable.

    Returns
    -------
    dict with keys: patient_id, t_future_yrs, predicted_mean, pi_lower, pi_upper

    Notes
    -----
    The prediction SE uses a simplified form: sqrt(2) × sigma_e, which
    combines trajectory variance and measurement noise under the assumption
    that var_trajectory ≈ sigma_e². For wide individual slope CIs, use the
    full form incorporating the D matrix from result.cov_re.
    """
    ps = lme_result['patient_slopes'].get(patient_id)
    if ps is None:
        raise ValueError(f'Patient {patient_id} not found in LME results.')

    b0        = lme_result['pop_intercept'] + ps['random_intercept']
    b1        = ps['individual_slope']
    pred_mean = b0 + b1 * t_future_yrs

    # Simplified prediction SE: sqrt(var_trajectory + var_measurement)
    pred_se = float(np.sqrt(sigma_e ** 2 + sigma_e ** 2))

    return {
        'patient_id'    : patient_id,
        't_future_yrs'  : t_future_yrs,
        'predicted_mean': round(pred_mean, 3),
        'pi_lower'      : round(pred_mean - PI_Z95 * pred_se, 3),
        'pi_upper'      : round(pred_mean + PI_Z95 * pred_se, 3),
    }


