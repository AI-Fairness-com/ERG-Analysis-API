# 1. Annotated ERG waveform
# ══════════════════════════════════════════════════════════════════════════════

def plot_erg_waveform(recording: dict,
                     norms:     dict  = None,
                     protocol:  str   = 'DA 3.0',
                     show_ops:  bool  = True,
                     title:     str   = None) -> plt.Figure:
    """Produce a fully annotated ERG waveform figure (ISCEV 2022 conventions).

    Parameters
    ----------
    recording : dict
        Standardised ERG dict from any Chapter 3 loader.
        Required keys: time_ms, amplitude_uv, fs_hz.
    norms : dict, optional
        Normative reference dict with keys time_ms, p10, p90 (arrays).
    protocol : str
        ISCEV protocol label for the figure title.
    show_ops : bool
        When True, adds a second panel with the 75–300 Hz OP-filtered trace.
    title : str, optional
        Override the auto-generated figure title.

    Returns
    -------
    plt.Figure
    """
    t   = recording['time_ms']
    amp = recording['amplitude_uv']
    fs  = recording['fs_hz']
    elc = recording.get('electrode_type', 'unknown')

    # Stimulus onset sample (closest sample to t = 0 ms).
    s0 = int(np.argmin(np.abs(t)))

    # a-wave trough: first minimum in the 5–40 ms post-stimulus window.
    post_t   = t[s0:]
    post_amp = amp[s0:]
    a_win    = (post_t >= 5) & (post_t <= 40)
    if a_win.any():
        a_local = int(np.argmin(post_amp[a_win]))
        a_gi    = s0 + int(np.where(a_win)[0][0]) + a_local
    else:
        a_gi = s0 + int(np.argmin(post_amp[:60]))

    # b-wave peak: maximum after the a-wave trough.
    b_gi = a_gi + int(np.argmax(amp[a_gi:]))

    a_amp_uv  = amp[a_gi]               # baseline-to-trough (ISCEV)
    b_amp_uv  = amp[b_gi] - amp[a_gi]   # trough-to-peak (ISCEV)
    a_time_ms = t[a_gi]
    b_time_ms = t[b_gi]

    n = 2 if show_ops else 1
    fig, axes = plt.subplots(
        n, 1, figsize=(12, 4 * n), sharex=True,
        gridspec_kw={'height_ratios': [3, 1] if n == 2 else [1]})
    ax = axes[0] if n == 2 else axes

    # Normative reference band.
    if norms is not None:
        ax.fill_between(norms['time_ms'], norms['p10'], norms['p90'],
                        alpha=0.18, color='gray',
                        label='Normative range (10th–90th centile)')

    # Main waveform.
    ax.plot(t, amp, color='#2E75B6', linewidth=1.8,
            label=f'{protocol} ERG  |  {elc} electrode')
    ax.axhline(0, color='gray', linewidth=0.7, linestyle=':')
    ax.axvline(0, color='red',  linewidth=1.0, linestyle='--', alpha=0.7,
               label='Stimulus onset (t = 0 ms)')

    # a-wave: double-headed bracket from baseline to trough.
    ax.annotate('', xy=(a_time_ms, amp[a_gi]), xytext=(a_time_ms, 0),
                arrowprops=dict(arrowstyle='<->', color='#C62828', lw=1.4))
    ax.text(a_time_ms + 4, amp[a_gi] / 2,
            f'a: {abs(a_amp_uv):.0f} µV\n@ {a_time_ms:.0f} ms',
            fontsize=8.5, color='#C62828', va='center')

    # b-wave: bracket from a-wave trough to b-wave peak (ISCEV trough-to-peak).
    ax.annotate('', xy=(b_time_ms, amp[b_gi]), xytext=(b_time_ms, amp[a_gi]),
                arrowprops=dict(arrowstyle='<->', color='#1F4E79', lw=1.4))
    ax.text(b_time_ms + 4, (amp[b_gi] + amp[a_gi]) / 2,
            f'b: {b_amp_uv:.0f} µV\n@ {b_time_ms:.0f} ms',
            fontsize=8.5, color='#1F4E79', va='center')

    ax.set_ylabel('Amplitude (µV)', fontsize=11)
    ax.legend(loc='lower right', fontsize=9)
    ax.grid(True, alpha=0.25)

    # OP panel: 75–300 Hz bandpass isolates oscillatory potentials.
    if show_ops:
        sos = butter(4, [75, 300], btype='bandpass', fs=fs, output='sos')
        op  = sosfiltfilt(sos, amp)
        axes[1].plot(t, op, color='#2E7D32', linewidth=1.2,
                     label='Oscillatory potentials (75–300 Hz)')
        axes[1].axhline(0, color='gray', linewidth=0.7, linestyle=':')
        axes[1].set_ylabel('OP amplitude (µV)', fontsize=11)
        axes[1].legend(loc='lower right', fontsize=9)
        axes[1].grid(True, alpha=0.25)

    plt.xlabel('Time (ms)', fontsize=11)
    auto_title = (title if title else
                  f'{protocol}  |  {elc}  |  '
                  f'a = {abs(a_amp_uv):.0f} µV @ {a_time_ms:.0f} ms  |  '
                  f'b = {b_amp_uv:.0f} µV @ {b_time_ms:.0f} ms')
    fig.suptitle(auto_title, fontsize=12, fontweight='bold')
    plt.tight_layout()
    return fig


