# 3. SNR overlay
# ══════════════════════════════════════════════════════════════════════════════

def add_snr_overlay(ax:           plt.Axes,
                    time_ms:      np.ndarray,
                    amplitude_uv: np.ndarray,
                    fs:           float,
                    electrode:    str   = 'dtl',
                    pre_ms:       float = 200.0) -> dict:
    """Add an SNR noise-floor band and quality badge to an existing waveform axis.

    Parameters
    ----------
    ax : plt.Axes
        Matplotlib axis on which to draw the overlay.
    time_ms : np.ndarray
        Time axis in milliseconds.
    amplitude_uv : np.ndarray
        Amplitude array in microvolts.
    fs : float
        Sampling rate in Hz.
    electrode : str
        Electrode type key for threshold lookup
        ('contact_lens', 'gold_foil', 'dtl', 'skin').
    pre_ms : float
        Pre-stimulus window length in milliseconds used to estimate noise RMS.

    Returns
    -------
    dict with keys: snr, snr_db, quality_flag, noise_rms_uv
    """
    pre_n = int(pre_ms * fs / 1000)
    noise = amplitude_uv[:pre_n]
    n_rms = float(np.sqrt(np.mean(noise ** 2)))

    # ±2 × RMS noise envelope.
    ax.fill_between(time_ms, -2 * n_rms, 2 * n_rms,
                    alpha=0.15, color='orange',
                    label=f'±2× noise RMS  ({n_rms:.1f} µV)')

    # SNR from the 250 ms post-stimulus signal window.
    sig     = amplitude_uv[pre_n: pre_n + int(0.25 * fs)]
    s_pk2pk = float(np.max(sig) - np.min(sig))
    snr     = s_pk2pk / n_rms if n_rms > 0 else 0.0
    snr_db  = 20 * np.log10(snr) if snr > 0 else -99.0

    # Electrode-specific PASS and WARNING thresholds (Chapter 2, Section 2.3).
    thresholds = {'contact_lens': 8, 'gold_foil': 6, 'dtl': 4, 'skin': 3}
    warn_thresholds = {'contact_lens': 4.0, 'gold_foil': 3.0, 'dtl': 2.5, 'skin': 1.5}
    key = electrode.lower().replace(' ', '_')
    pass_thr = thresholds.get(key, 4)
    warn_thr = warn_thresholds.get(key, 2.5)

    flag = 'PASS' if snr >= pass_thr else ('WARNING' if snr >= warn_thr else 'FAIL')
    col  = {'PASS': '#2E7D32', 'WARNING': '#F9A825', 'FAIL': '#C62828'}[flag]

    ax.text(0.02, 0.97,
            f'Quality: {flag}   SNR: {snr:.1f}  ({snr_db:.1f} dB)',
            transform=ax.transAxes, fontsize=9.5, va='top',
            color='white', fontweight='bold',
            bbox=dict(boxstyle='round,pad=0.35', facecolor=col, alpha=0.92))

    return {'snr': snr, 'snr_db': snr_db,
            'quality_flag': flag, 'noise_rms_uv': n_rms}


