# 2. STFT spectrogram
# ══════════════════════════════════════════════════════════════════════════════

def plot_erg_spectrogram(recording: dict,
                         protocol:  str   = 'DA 3.0',
                         fmin_hz:   float = 0.0,
                         fmax_hz:   float = 300.0,
                         nperseg:   int   = 64,
                         noverlap:  int   = 56,
                         title:     str   = None) -> plt.Figure:
    """Compute and display an STFT spectrogram of an ERG recording.

    Parameters
    ----------
    recording : dict
        Standardised ERG dict (Chapter 3 format).
    protocol : str
        Protocol label for the figure title.
    fmin_hz, fmax_hz : float
        Frequency display range in Hz.
    nperseg : int
        STFT window length in samples.
    noverlap : int
        Number of overlapping samples between windows.
    title : str, optional
        Override the auto-generated figure title.

    Returns
    -------
    plt.Figure
    """
    t   = recording['time_ms']
    amp = recording['amplitude_uv']
    fs  = recording['fs_hz']

    # STFT with Hann window to minimise spectral leakage.
    freqs, t_stft, Zxx = stft(amp, fs=fs, nperseg=nperseg,
                               noverlap=noverlap, window='hann')

    # Align STFT time axis to stimulus onset at t = 0 ms.
    stim_idx = int(np.argmin(np.abs(t)))
    t_ms     = t_stft * 1000 - t[stim_idx]

    # Convert to dB and normalise relative to mean pre-stimulus energy.
    amp_db   = 20 * np.log10(np.abs(Zxx) + 1e-12)
    pre_cols = t_ms < 0
    if pre_cols.any():
        baseline = np.mean(amp_db[:, pre_cols], axis=1, keepdims=True)
        amp_db   = amp_db - baseline

    # Crop to requested frequency range.
    fmask    = (freqs >= fmin_hz) & (freqs <= fmax_hz)
    f_plot   = freqs[fmask]
    amp_plot = amp_db[fmask, :]

    fig, ax = plt.subplots(figsize=(12, 5))
    pcm = ax.pcolormesh(t_ms, f_plot, amp_plot,
                        shading='gouraud', cmap='inferno')

    # Key frequency band boundaries.
    for freq, colour, label in [
        (30,  'white', '30 Hz  (b-wave / OP boundary)'),
        (75,  'cyan',  '75 Hz  (OP lower limit)'),
        (300, 'cyan',  '300 Hz (OP upper limit)'),
    ]:
        if fmin_hz <= freq <= fmax_hz:
            ax.axhline(freq, color=colour, linewidth=0.8,
                       linestyle='--', alpha=0.65, label=label)

    ax.axvline(0, color='red', linewidth=1.2, linestyle='--',
               alpha=0.85, label='Stimulus onset')

    plt.colorbar(pcm, ax=ax, label='Amplitude (dB re pre-stimulus baseline)')
    ax.set_xlabel('Time (ms)', fontsize=11)
    ax.set_ylabel('Frequency (Hz)', fontsize=11)
    ax.legend(loc='upper right', fontsize=8, framealpha=0.6)
    fig.suptitle(
        title if title else
        f'STFT Spectrogram  |  {protocol}  |  fs = {int(fs)} Hz  |  '
        f'nperseg = {nperseg}  noverlap = {noverlap}',
        fontsize=12, fontweight='bold')
    plt.tight_layout()
    return fig


