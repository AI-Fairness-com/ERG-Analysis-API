# 5. Interactive Plotly waveform viewer
# ══════════════════════════════════════════════════════════════════════════════

def build_interactive_waveform(recording: dict,
                                norms:     dict = None,
                                protocol:  str  = 'DA 3.0') -> go.Figure:
    """Build the interactive Plotly waveform viewer used in the API clinical report.

    Features
    --------
    - ERG waveform with hover tooltip (time ms, amplitude µV)
    - Normative reference band (10th–90th centile), toggleable in legend
    - OP-filtered trace (75–300 Hz), hidden by default, toggleable
    - Stimulus onset marker
    - Exports as self-contained HTML with no Python dependency

    Parameters
    ----------
    recording : dict
        Standardised ERG dict (Chapter 3 format).
    norms : dict, optional
        Normative reference dict with keys time_ms, p10, p90 (arrays).
    protocol : str
        ISCEV protocol label.

    Returns
    -------
    go.Figure

    Notes
    -----
    Save as self-contained HTML for embedding in the clinical report:
        fig.write_html('report/patient_waveform.html', include_plotlyjs='cdn')
    """
    t   = recording['time_ms']
    amp = recording['amplitude_uv']
    fs  = recording['fs_hz']
    elc = recording.get('electrode_type', 'unknown')
    pid = recording.get('patient_id', 'Unknown')

    fig = go.Figure()

    # Normative reference band as a filled polygon.
    if norms is not None:
        x_band = list(norms['time_ms']) + list(norms['time_ms'])[::-1]
        y_band = list(norms['p90'])     + list(norms['p10'])[::-1]
        fig.add_trace(go.Scatter(
            x=x_band, y=y_band, fill='toself',
            fillcolor='rgba(180,180,180,0.22)',
            line=dict(color='rgba(0,0,0,0)'),
            name='Normative range (10th–90th centile)',
            hoverinfo='skip'))

    # Main ERG waveform.
    fig.add_trace(go.Scatter(
        x=t.tolist(), y=amp.tolist(),
        mode='lines', name=f'{protocol} ERG',
        line=dict(color='#2E75B6', width=2),
        hovertemplate='Time: %{x:.1f} ms<br>Amplitude: %{y:.1f} µV<extra></extra>'))

    # OP-filtered trace (hidden by default; toggle from legend).
    sos = butter(4, [75, 300], btype='bandpass', fs=fs, output='sos')
    op  = sosfiltfilt(sos, amp)
    fig.add_trace(go.Scatter(
        x=t.tolist(), y=op.tolist(),
        mode='lines', name='OPs (75–300 Hz)',
        line=dict(color='#2E7D32', width=1.2),
        visible='legendonly',
        hovertemplate='Time: %{x:.1f} ms<br>OP: %{y:.1f} µV<extra></extra>'))

    # Stimulus onset marker.
    fig.add_vline(x=0, line_width=1.2, line_dash='dash', line_color='red',
                  annotation_text='Stimulus onset',
                  annotation_position='top right')

    fig.update_layout(
        title=dict(
            text=f'ERG  |  Patient: {pid}  |  {protocol}  |  {elc} electrode',
            font=dict(size=14, family='Arial')),
        xaxis=dict(title='Time (ms)', gridcolor='#EEEEEE'),
        yaxis=dict(title='Amplitude (µV)', gridcolor='#EEEEEE',
                   zeroline=True, zerolinecolor='gray', zerolinewidth=0.8),
        legend=dict(orientation='h', y=-0.20),
        plot_bgcolor='white', height=480)

    return fig


