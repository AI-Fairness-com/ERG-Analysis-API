# 4. Baseline drift indicator
# ══════════════════════════════════════════════════════════════════════════════

def plot_baseline_drift(recording:          dict,
                        ax:                 plt.Axes = None,
                        drift_threshold_uv: float    = 10.0) -> dict:
    """Display a baseline drift indicator for the pre-stimulus window.

    Parameters
    ----------
    recording : dict
        Standardised ERG dict (Chapter 3 format).
    ax : plt.Axes, optional
        If provided, draws the drift trace onto this axis.
    drift_threshold_uv : float
        Drift amplitude (µV) above which drift is flagged.

    Returns
    -------
    dict with keys: drift_detected (bool), max_drift_uv (float)
    """
    t   = recording['time_ms']
    amp = recording['amplitude_uv']
    fs  = recording['fs_hz']

    pre_t   = t[t < 0]
    pre_amp = amp[t < 0]

    # 100 ms sliding mean to reveal slow drift trends.
    w = max(1, int(0.1 * fs))
    if len(pre_amp) >= w:
        wins       = sliding_window_view(pre_amp, w)
        drift_mean = np.mean(wins, axis=1)
        drift_t    = pre_t[w // 2: w // 2 + len(drift_mean)]
    else:
        drift_mean, drift_t = pre_amp, pre_t

    max_drift      = float(np.max(np.abs(drift_mean)))
    drift_detected = max_drift > drift_threshold_uv

    if ax is not None:
        ax.plot(drift_t, drift_mean, color='#E65100', linewidth=1.4,
                label='100 ms running mean')
        ax.axhline(0, color='gray', linewidth=0.7, linestyle=':')
        ax.axhline( drift_threshold_uv, color='red', linewidth=0.8,
                   linestyle='--', alpha=0.6)
        ax.axhline(-drift_threshold_uv, color='red', linewidth=0.8,
                   linestyle='--', alpha=0.6,
                   label=f'±{drift_threshold_uv:.0f} µV drift limit')
        lbl = 'DRIFT DETECTED' if drift_detected else 'Baseline stable'
        col = '#C62828' if drift_detected else '#2E7D32'
        ax.set_title(
            f'Baseline drift  |  max = {max_drift:.1f} µV  |  {lbl}',
            fontsize=10, color=col)
        ax.set_xlabel('Time (ms)', fontsize=10)
        ax.set_ylabel('Drift (µV)', fontsize=10)
        ax.legend(fontsize=9)

    return {'drift_detected': drift_detected, 'max_drift_uv': max_drift}


