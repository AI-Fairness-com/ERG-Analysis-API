# 6. Topographic mfERG heatmap
# ══════════════════════════════════════════════════════════════════════════════

def plot_mferg_heatmap(mferg_data:    dict,
                       snr_threshold: float = 2.5,
                       show_quality:  bool  = True) -> plt.Figure:
    """Topographic mfERG heatmap with optional signal quality overlay.

    Parameters
    ----------
    mferg_data : dict
        Required keys:
          amplitudes  – 1-D array of per-element P1 amplitudes (nV/deg²)
          snr_values  – 1-D array of per-element SNR values
          coords      – list of (x, y) hex centre coordinates
          hex_radius  – float, radius of each hexagon in the coordinate system
    snr_threshold : float
        SNR below which a hex element is considered low quality (display only).
    show_quality : bool
        When True, adds a second panel showing per-element SNR quality map.

    Returns
    -------
    plt.Figure
    """
    amps   = np.array(mferg_data['amplitudes'])
    snrs   = np.array(mferg_data['snr_values'])
    coords = mferg_data['coords']
    r      = mferg_data['hex_radius']

    n_panels = 2 if show_quality else 1
    fig, axes = plt.subplots(1, n_panels, figsize=(6 * n_panels, 6))
    if n_panels == 1:
        axes = [axes]

    # Amplitude heatmap.
    amp_norm = plt.Normalize(vmin=0, vmax=float(np.nanpercentile(amps, 95)))
    amp_cmap = cm.get_cmap('RdYlBu_r')
    patches, colours = [], []
    for i, (x, y) in enumerate(coords):
        patches.append(RegularPolygon(
            (x, y), numVertices=6, radius=r * 0.94, orientation=np.pi / 6))
        val = amps[i] if i < len(amps) else 0
        colours.append(amp_cmap(amp_norm(val)))
    pc = PatchCollection(patches, facecolor=colours,
                         edgecolor='white', linewidth=0.4)
    axes[0].add_collection(pc)
    axes[0].autoscale_view()
    sm = plt.cm.ScalarMappable(cmap=amp_cmap, norm=amp_norm)
    plt.colorbar(sm, ax=axes[0], label='P1 amplitude (nV/deg²)')
    axes[0].set_title('mfERG Amplitude Map', fontsize=12, fontweight='bold')
    axes[0].set_aspect('equal')
    axes[0].axis('off')

    # Quality map: green = adequate SNR; red = below threshold.
    if show_quality:
        snr_norm = plt.Normalize(vmin=0, vmax=max(6, float(np.nanmax(snrs))))
        snr_cmap = cm.get_cmap('RdYlGn')
        q_patches, q_colours = [], []
        for i, (x, y) in enumerate(coords):
            q_patches.append(RegularPolygon(
                (x, y), numVertices=6, radius=r * 0.94, orientation=np.pi / 6))
            val = snrs[i] if i < len(snrs) else 0
            q_colours.append(snr_cmap(snr_norm(val)))
        qc = PatchCollection(q_patches, facecolor=q_colours,
                             edgecolor='white', linewidth=0.4)
        axes[1].add_collection(qc)
        axes[1].autoscale_view()
        sm2 = plt.cm.ScalarMappable(cmap=snr_cmap, norm=snr_norm)
        plt.colorbar(sm2, ax=axes[1], label='SNR per element')
        axes[1].set_title('mfERG Signal Quality Map', fontsize=12, fontweight='bold')
        axes[1].set_aspect('equal')
        axes[1].axis('off')

    fig.suptitle('Multifocal ERG Topographic Analysis',
                 fontsize=13, fontweight='bold')
    plt.tight_layout()
    return fig


