def rfe_selection(X_train:       np.ndarray,
                  y_train:       np.ndarray,
                  feature_names: list) -> list:
    """Recursive Feature Elimination with cross-validation (RFECV).

    Uses a Random Forest as the inner estimator. The cross-validated version
    automatically determines the optimal number of features by maximising
    macro AUC-ROC.

    Parameters
    ----------
    X_train : np.ndarray, shape (n_samples, n_features)
    y_train : np.ndarray, shape (n_samples,)
    feature_names : list of str

    Returns
    -------
    list of selected feature name strings.
    """
    estimator = RandomForestClassifier(
        n_estimators=100, max_depth=6, random_state=42, n_jobs=-1)
    cv       = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
    selector = RFECV(estimator=estimator, step=5, cv=cv,
                     scoring='roc_auc_ovr', min_features_to_select=10,
                     n_jobs=-1)
    selector.fit(X_train, y_train)
    selected = [f for f, s in zip(feature_names, selector.support_) if s]
    print(f'RFE selected {len(selected)} features '
          f'(optimal n = {selector.n_features_})')
    return selected


def correlation_filter(X_train:       np.ndarray,
                        feature_names: list,
                        threshold:     float = 0.90) -> list:
    """Remove highly correlated features (Pearson r > threshold).

    For each correlated pair, retains the less redundant feature
    (the one with lower mean correlation to all other features).

    Parameters
    ----------
    X_train : np.ndarray, shape (n_samples, n_features)
    feature_names : list of str
    threshold : float
        Pearson |r| above which a pair is considered redundant.

    Returns
    -------
    list of retained feature name strings.
    """
    df    = pd.DataFrame(X_train, columns=feature_names)
    corr  = df.corr(method='pearson').abs()
    upper = corr.where(np.triu(np.ones(corr.shape), k=1).astype(bool))

    to_drop = set()
    for col in upper.columns:
        correlated = upper.index[upper[col] > threshold].tolist()
        if correlated:
            all_candidates = [col] + correlated
            mean_corrs     = {f: corr[f].drop(f).mean() for f in all_candidates}
            most_redundant = max(mean_corrs, key=mean_corrs.get)
            to_drop.add(most_redundant)

    retained = [f for f in feature_names if f not in to_drop]
    print(f'Correlation filter: dropped {len(to_drop)}, '
          f'retained {len(retained)}')
    return retained


def mrmr_selection(X_train:       np.ndarray,
                   y_train:       np.ndarray,
                   feature_names: list,
                   n_features:    int = 40) -> list:
    """Minimum Redundancy Maximum Relevance feature selection.

    Requires the mrmr-selection package:  pip install mrmr-selection
    Falls back to all features with a warning if not installed.

    Parameters
    ----------
    X_train : np.ndarray, shape (n_samples, n_features)
    y_train : np.ndarray, shape (n_samples,)
    feature_names : list of str
    n_features : int
        Maximum number of features to select.

    Returns
    -------
    list of selected feature name strings.
    """
    try:
        import mrmr
        df       = pd.DataFrame(X_train, columns=feature_names)
        selected = mrmr.mrmr_classif(
            X=df, y=pd.Series(y_train),
            K=min(n_features, len(feature_names)))
        print(f'mRMR selected {len(selected)} features')
        return selected
    except ImportError:
        print('mrmr-selection not installed.  Run: pip install mrmr-selection')
        print('Falling back to all features.')
        return feature_names


def rf_importance_selection(X_train:       np.ndarray,
                             y_train:       np.ndarray,
                             feature_names: list,
                             top_k:         int = 40) -> list:
    """Select top-k features by Random Forest mean decrease in impurity.

    Parameters
    ----------
    X_train : np.ndarray, shape (n_samples, n_features)
    y_train : np.ndarray, shape (n_samples,)
    feature_names : list of str
    top_k : int
        Number of top features to return.

    Returns
    -------
    list of selected feature name strings (descending importance order).
    """
    rf = RandomForestClassifier(n_estimators=200, max_depth=8,
                                 random_state=42, n_jobs=-1)
    rf.fit(X_train, y_train)
    ranked   = sorted(zip(feature_names, rf.feature_importances_),
                      key=lambda x: x[1], reverse=True)
    selected = [name for name, _ in ranked[:top_k]]
    print(f'RF importance: top {len(selected)} features selected')
    for name, imp in ranked[:10]:
        print(f'  {name:<45s}  {imp:.4f}')
    return selected


def feature_selection_pipeline(X_train:        np.ndarray,
                                 y_train:        np.ndarray,
                                 feature_names:  list,
                                 vote_threshold: int = 2) -> list:
    """Run all four selection methods; retain features selected by ≥ vote_threshold.

    Parameters
    ----------
    X_train : np.ndarray, shape (n_samples, n_features)
    y_train : np.ndarray, shape (n_samples,)
    feature_names : list of str
    vote_threshold : int
        Minimum number of methods (out of 4) that must select a feature.

    Returns
    -------
    list of selected feature name strings, sorted by descending vote count.
    """
    print('Running feature selection pipeline...')
    print(f'Input: {X_train.shape[1]} features, {X_train.shape[0]} samples')

    rfe_feats  = set(rfe_selection(X_train, y_train, feature_names))
    corr_feats = set(correlation_filter(X_train, feature_names))
    mrmr_feats = set(mrmr_selection(X_train, y_train, feature_names))
    rf_feats   = set(rf_importance_selection(X_train, y_train, feature_names))

    votes = Counter()
    for feat_set in [rfe_feats, corr_feats, mrmr_feats, rf_feats]:
        for f in feat_set:
            votes[f] += 1

    selected = sorted([f for f, v in votes.items() if v >= vote_threshold],
                      key=lambda f: -votes[f])

    print(f'\nSelected {len(selected)} features '
          f'(threshold = {vote_threshold}/4 votes)')
    for v in range(4, 0, -1):
        at_v = [f for f in selected if votes[f] == v]
        if at_v:
            print(f'  {v} votes: {len(at_v)} features')
    return selected


